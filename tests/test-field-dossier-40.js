'use strict';
const assert=require('node:assert/strict');
const field=require('../ite-field-dossier-40.js');
const operations=require('../ite-operations-40.js');
const t='2026-11-05T10:00:00Z',actor='TEST-OP';
let s=operations.empty();
s=operations.addClient(s,{id:'TEST-C',name:'Cliente TEST'},actor,t);
s=operations.addSite(s,'TEST-C',{id:'TEST-S',address:'Via TEST 1'},actor,t);
s=operations.addPlant(s,'TEST-C','TEST-S',{id:'TEST-P',type:'Termico'},actor,t);
s=operations.addDevice(s,{clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P'},{id:'TEST-D',brand:'Marca TEST',model:'Modello TEST',serial:'TEST-123'},actor,t);
s=operations.addOperator(s,{id:actor,name:'Tecnico TEST',color:'#123456'},actor,t);
s=operations.appointment(s,{id:'TEST-A',clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',deviceId:'TEST-D',operatorId:actor,start:t,end:'2026-11-05T12:00:00Z',kind:'Manutenzione'},actor,t);
s=operations.arrive(s,'TEST-A',actor,t);
s=operations.finish(s,'TEST-INT-A',actor,'2026-11-05T11:30:00Z',{description:'Controllo TEST',extraWork:[]});
s=operations.quote(s,{id:'TEST-Q',clientId:'TEST-C',lines:[{id:'TEST-L1',category:'Termico',kind:'FORNITURA',description:'Materiale TEST',quantity:2,unitPrice:10},{id:'TEST-L2',category:'Termico',kind:'POSA',description:'Lavoro TEST',quantity:1,unitPrice:30,extra:true}]},actor,t);
const doc={id:'TEST-DOC',clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',deviceId:'TEST-D',interventionId:'TEST-INT-A',type:'DICO_IDRICO',title:'DICO TEST',status:'BOZZA',revision:1,attachments:[],history:[{revision:1}]};
const reg={schema:1,documents:[doc],events:[]};
const snapshot=JSON.stringify({s,reg});
const report=field.build(s,reg);
assert.equal(report.counts.appointments,1);
assert.equal(report.counts.closedInterventions,1);
assert.equal(report.counts.linkedDocuments,1);
assert.equal(report.rows[0].minutes,90);
assert.equal(report.rows[0].quotes[0].approved,20);
assert.equal(report.rows[0].quotes[0].pendingExtra,30);
assert.equal(report.rows[0].quotes[0].supply,20);
assert.equal(report.rows[0].quotes[0].installation,30);
assert.equal(report.issues.length,0);
assert.equal(field.build(s,reg,{clientId:'TEST-NONE'}).counts.appointments,0);
assert.throws(()=>field.build(s,reg,{clientId:'REAL-C'}),/FILTRO_NON_TEST/);
assert.equal(JSON.stringify({s,reg}),snapshot);
assert.equal(JSON.parse(field.exportJSON(report)).format,'ITE40_FIELD_DOSSIER_TEST');
console.log('PASS: fascicolo integrato, tempi, preventivi, documenti, filtri, immutabilita');

const summary=report.clientQuotes[0];
assert.equal(report.version,'4.0.25');
assert.equal(report.financialScope,'CLIENTE');
assert.equal(report.rows[0].quoteScope,'CLIENTE_NON_ATTRIBUITO');
assert.equal(summary.approvedSupply,20);
assert.equal(summary.approvedInstallation,0);
assert.equal(summary.pendingExtra,30);
assert.equal(report.rows[0].interventionHistory.length,2);
const withSecond={...s,appointments:[...s.appointments,{...s.appointments[0],id:'TEST-A2',start:'2026-11-06T10:00:00Z',end:'2026-11-06T12:00:00Z',status:'PROGRAMMATO'}]};
const two=field.build(withSecond,reg);
assert.equal(two.counts.appointments,2);
assert.equal(two.clientQuotes.length,1,'Non duplicare i totali del preventivo per appuntamento');
const broken={...s,interventions:[...s.interventions,{...s.interventions[0],id:'TEST-INT-OTHER'}]};
assert.ok(field.build(broken,reg).issues.some(x=>x.code==='INTERVENTI_MULTIPLI'));
const orphan={...s,interventions:[...s.interventions,{...s.interventions[0],id:'TEST-INT-ORPHAN',appointmentId:'TEST-MISSING'}]};
assert.ok(field.build(orphan,reg).issues.some(x=>x.code==='INTERVENTO_ORFANO'));
console.log('PASS: milestone 4.0.25 ambito cliente, deduplicazione, storico, integrita');
