"use strict";
const assert=require("node:assert/strict");
const core=require("../ite-integrated-core-225.js");
const finance=require("../gestionale4/finance-230.js");
const s=core.createStore();
core.add(s,"clients",{id:"c",name:"Cliente sintetico"});
core.add(s,"quotes",{id:"q",clientId:"c",status:"ACCETTATO",lines:[{id:"l1",kind:"FORNITURA",description:"Materiale test",cents:10000,qty:1},{id:"l2",kind:"POSA",description:"Posa test",cents:5000,qty:1}]});
finance.addInvoice(s,{id:"f",clientId:"c",kind:"VENDITA",number:"1",cents:15000,quoteId:"q"});
finance.addInvoice(s,{id:"p",clientId:"c",kind:"PROFORMA",number:"P1",cents:1000});
finance.addInvoice(s,{id:"a",clientId:"c",kind:"ACQUISTO",number:"A1",cents:4000});
finance.addCredit(s,"f","n","NC1",5000);
assert.equal(finance.summary(s.snapshot()).salesNetCents,10000);
assert.equal(finance.summary(s.snapshot()).purchaseCents,4000);
assert.equal(finance.summary(s.snapshot()).proformaCents,1000);
assert.equal(finance.summary(s.snapshot()).creditCents,5000);
assert.equal(finance.audit(s.snapshot()).ok,true);
const before=s.exportMetadata();
assert.throws(()=>finance.addCredit(s,"f","n2","NC2",11000),/CREDITO_ECCESSIVO/);
assert.equal(s.exportMetadata(),before,"atomic rollback");
assert.throws(()=>finance.addInvoice(s,{id:"bad",clientId:"c",kind:"VENDITA",number:"2",cents:-1}),/FATTURA_INPUT/);
assert.throws(()=>finance.addInvoice(s,{id:"dup",clientId:"c",kind:"VENDITA",number:" 1 ",cents:1000}),/NUMERO_DUPLICATO_TIPO/);
assert.equal(s.exportMetadata(),before,"duplicate number rollback");
assert.throws(()=>finance.addCredit(s,"f","n4","nc1",100),/NUMERO_DUPLICATO_TIPO/);
assert.equal(s.exportMetadata(),before,"duplicate TD04 rollback");
const corrupt=s.snapshot();corrupt.invoices.push({id:"n3",clientId:"c",kind:"TD04",number:"NC3",cents:12000,originalInvoiceId:"f"});
assert(finance.audit(corrupt).errors.some(x=>x.code==="CREDITO_ECCESSIVO"));
console.log("I.T.E. 4.0.230 finance tests passed");
