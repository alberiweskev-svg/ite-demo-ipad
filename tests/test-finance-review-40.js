'use strict';
const assert=require('node:assert/strict');
const intake=require('../ite-finance-intake-40.js');
const review=require('../ite-finance-review-40.js');
const map=new Map();
const storage={getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v)};
const api=review.create(storage);
assert.deepEqual(api.load(),[]);
api.upsert({id:'TEST-C1',role:'CLIENTE',name:'Cliente fittizio'});
api.upsert({id:'TEST-F1',role:'FORNITORE',name:'Fornitore fittizio'});
const doc=intake.normalize({id:'TEST-D1',subjectId:'TEST-C1',direction:'VENDITA',type:'TD01',number:'TEST/1',issuedAt:'2026-11-06',taxable:100,vat:22,total:122,lines:[{kind:'FORNITURA',description:'TEST',quantity:1,unitPrice:60},{kind:'POSA',description:'TEST',quantity:1,unitPrice:40}]});
const before=JSON.stringify(doc);
assert.equal(api.audit([doc]).status,'COERENTE');
assert.equal(JSON.stringify(doc),before);
assert.equal(api.audit([{...doc,subjectId:'TEST-MISSING'}]).issues[0].code,'ANAGRAFICA_ASSENTE');
assert.equal(api.audit([{...doc,subjectId:'TEST-F1'}]).issues[0].code,'RUOLO_INCOERENTE');
assert.throws(()=>api.upsert({id:'REAL-1',name:'Vero',role:'CLIENTE'}),/ANAGRAFICA/);
const backup=api.exportBackup();const old=map.get(review.KEY);
assert.throws(()=>api.restore('{"format":"ITE40_FINANCE_SUBJECTS_TEST","version":1,"subjects":[{"id":"REAL-1"}]}'),/ANAGRAFICA/);
assert.equal(map.get(review.KEY),old,'ripristino non atomico');
api.remove('TEST-F1');assert.equal(api.get().length,1);
api.restore(backup);assert.equal(api.get().length,2);
assert.equal(review.create(storage).load().length,2);
console.log('Riconciliazione e anagrafiche TEST integrate: OK');
