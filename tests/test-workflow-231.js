"use strict";
const assert=require("node:assert/strict");
const core=require("../ite-integrated-core-225.js");
const flow=require("../gestionale4/workflow-231.js");
const store=core.createStore();
core.add(store,"clients",{id:"c",name:"Cliente sintetico"});
core.add(store,"sites",{id:"s",clientId:"c",address:"Via Test 1"});
core.add(store,"plants",{id:"p",siteId:"s",type:"Termico"});
core.add(store,"equipment",{id:"e",plantId:"p",type:"Caldaia"});
flow.createVisit(store,{id:"a",siteId:"s",equipmentId:"e",operator:"Tecnico prova",start:"2026-11-23T09:00:00",end:"2026-11-23T10:00:00"});
const before=store.exportMetadata();
assert.throws(()=>flow.createVisit(store,{id:"b",siteId:"s",operator:"Tecnico prova",start:"2026-11-23T09:30:00",end:"2026-11-23T10:30:00"}),/OPERATORE_OCCUPATO/);
assert.equal(store.exportMetadata(),before);
flow.quoteFromVisit(store,{id:"q",appointmentId:"a",lines:[{id:"l1",kind:"FORNITURA",description:"Materiale fittizio",cents:10000,qty:2},{id:"l2",kind:"POSA",description:"Posa fittizia",cents:5000,qty:1}]});
assert.equal(flow.overview(store.snapshot()).quotes[0].totalCents,25000);
assert.equal(flow.overview(store.snapshot()).quotes[0].supplyCents,20000);
assert.throws(()=>flow.invoiceFromQuote(store,{id:"f",quoteId:"q",number:"1"}),/PREVENTIVO_NON_ACCETTATO/);
store.transact(store.snapshot().revision,s=>{s.quotes[0].status="ACCETTATO"});
assert.equal(flow.overview(store.snapshot()).unbilled.length,1);
flow.invoiceFromQuote(store,{id:"f",quoteId:"q",number:"1"});
assert.equal(store.snapshot().invoices[0].cents,25000);
assert.equal(flow.overview(store.snapshot()).unbilled.length,0);
assert.throws(()=>flow.invoiceFromQuote(store,{id:"f2",quoteId:"q",number:"2"}),/FATTURA_GIA_PRESENTE/);
core.add(store,"documents",{id:"d",kind:"DICO",filename:"fittizio.pdf",mime:"application/pdf",bytes:100,clientId:"c",siteId:"s"});
assert.equal(flow.overview(store.snapshot()).issues.length,0);
console.log("I.T.E. 4.0.231 workflow tests passed");
