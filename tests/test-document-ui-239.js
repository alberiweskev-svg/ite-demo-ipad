'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../gestionale4/index.html'),'utf8');
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(x=>x.trim());
assert.ok(inline.length,'missing inline application script');
for(const js of inline)new vm.Script(js,{filename:'gestionale4/index.html'});
for(const expected of ['id="pdf-preview"','workspace.previewBatch(store,items)','const {items}=await inspectSelected()','bytes:128','Demo integrata di collaudo 4.0.241'])assert.ok(html.includes(expected),'missing '+expected);
assert.ok(!html.includes("filename:'esempio-non-esistente.pdf',mime:'application/pdf',bytes:0"));
const core=require('../ite-integrated-core-225.js'),docs=require('../gestionale4/document-workspace-237.js');
const state=core.blank();state.clients.push({id:'demo',name:'Cliente Demo'});state.sites.push({id:'sede',clientId:'demo',address:'Via Fittizia 1'});const store=core.createStore(state);
const item={kind:'DICO',filename:'demo.pdf',mime:'application/pdf',bytes:128,siteId:'sede'};
const before=store.snapshot();
assert.equal(docs.previewBatch(store,[item]).count,1);
assert.deepEqual(store.snapshot(),before,'dry-run must not mutate');
docs.addBatch(store,[item],()=> 'documento-1');
assert.equal(store.snapshot().documents[0].clientId,'demo');
assert.throws(()=>docs.previewBatch(store,[item]),/DOCUMENTO_DUPLICATO/);
assert.equal(docs.audit(store.snapshot()).issues.length,0);
console.log('Document UI 239 and dry-run: OK');
