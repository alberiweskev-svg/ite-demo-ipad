'use strict';
const assert=require('node:assert/strict'),lib=require('../ite-hierarchy-test-40.js');
const map=new Map(),storage={getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v)};
const db=lib.create(storage);assert.deepEqual(db.load(),lib.empty());
db.upsert('clienti',{id:'TEST-C1',nome:'Cliente fittizio'});
db.upsert('sedi',{id:'TEST-S1',nome:'Sede fittizia',clienteId:'TEST-C1'});
db.upsert('impianti',{id:'TEST-I1',nome:'Impianto fittizio',sedeId:'TEST-S1'});
db.upsert('apparecchiature',{id:'TEST-A1',nome:'Caldaia fittizia',impiantoId:'TEST-I1'});
db.upsert('interventi',{id:'TEST-W1',nome:'Manutenzione fittizia',apparecchiaturaId:'TEST-A1',operatoreId:'TEST-OP1',stato:'CHIUSO',arrivo:1000,uscita:2000});
assert.equal(db.path('interventi','TEST-W1').length,5);
assert.equal(db.get().interventi[0].uscita-db.get().interventi[0].arrivo,1000);
const original=map.get(lib.KEY);
assert.throws(()=>db.remove('clienti','TEST-C1'),/GENITORE_ASSENTE/);
assert.equal(map.get(lib.KEY),original);
assert.throws(()=>db.upsert('sedi',{id:'TEST-S2',nome:'Orfana',clienteId:'TEST-NONE'}),/GENITORE_ASSENTE/);
assert.throws(()=>db.upsert('interventi',{id:'TEST-W2',nome:'Errato',apparecchiaturaId:'TEST-A1',operatoreId:'TEST-OP1',stato:'CHIUSO',arrivo:2000,uscita:1000}),/TEMPI/);
assert.throws(()=>db.upsert('clienti',{id:'REAL-C1',nome:'Reale'}),/RECORD/);
assert.equal(map.get(lib.KEY),original);
const backup=db.exportBackup();assert.throws(()=>db.restore('{"format":"bad"}'),/FORMATO/);
assert.equal(map.get(lib.KEY),original);
const copy=lib.create(storage);assert.equal(copy.load().interventi.length,1);
copy.restore(backup);assert.equal(copy.path('interventi','TEST-W1')[0].id,'TEST-C1');
console.log('Gerarchia, tempi, integrita e backup TEST: OK');
