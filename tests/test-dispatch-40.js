'use strict';
const assert=require('node:assert/strict');
const ops=require('../ite-operations-40.js'),dispatch=require('../ite-dispatch-40.js');
const at='2026-11-05T08:00:00Z',actor='TEST-OP';
let s=ops.empty();
s=ops.addClient(s,{id:'TEST-C',name:'Cliente TEST'},actor,at);
s=ops.addSite(s,'TEST-C',{id:'TEST-S',address:'Via TEST 1'},actor,at);
s=ops.addPlant(s,'TEST-C','TEST-S',{id:'TEST-P',type:'Termico'},actor,at);
s=ops.addDevice(s,{clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P'},{id:'TEST-D',brand:'TEST',model:'CALDAIA',serial:'TEST-001'},actor,at);
s=ops.addOperator(s,{id:actor,name:'Tecnico TEST',color:'#123456'},actor,at);
s=ops.addOperator(s,{id:'TEST-OP2',name:'Tecnico TEST 2',color:'#abcdef'},actor,at);
const a={id:'TEST-A',clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',deviceId:'TEST-D',operatorId:actor,start:'2026-11-05T09:00:00Z',end:'2026-11-05T10:00:00Z',kind:'Manutenzione'};
s=ops.appointment(s,a,actor,at);
s=ops.appointment(s,{...a,id:'TEST-B',start:'2026-11-05T10:00:00Z',end:'2026-11-05T11:00:00Z'},actor,at);
const snapshot=JSON.stringify(s);
assert.equal(dispatch.calendar(s,'2026-11-05T08:00:00Z','2026-11-05T12:00:00Z').length,2);
assert.deepEqual(dispatch.conflicts(s,{...a,start:'2026-11-05T09:30:00Z',end:'2026-11-05T10:30:00Z'},'TEST-A'),['TEST-B']);
assert.throws(()=>dispatch.reschedule(s,'TEST-A',{end:'2026-11-05T10:30:00Z'},actor,at),/OPERATORE_OCCUPATO/);
assert.equal(JSON.stringify(s),snapshot,'mutazioni vietate');
const moved=dispatch.reschedule(s,'TEST-A',{start:'2026-11-05T09:30:00Z',end:'2026-11-05T10:30:00Z',operatorId:'TEST-OP2'},actor,at);
assert.equal(moved.appointments[0].operatorId,'TEST-OP2');
assert.equal(moved.audit.at(-1).action,'APPUNTAMENTO_RIPROGRAMMATO');
assert.equal(dispatch.audit(moved).length,0);
const cancelled=dispatch.cancel(moved,'TEST-A',actor,at,'Cliente indisponibile');
assert.equal(cancelled.appointments[0].status,'ANNULLATO');
assert.equal(dispatch.workload(cancelled,'2026-11-05T08:00:00Z','2026-11-05T12:00:00Z')['TEST-OP2'].appointments,0);
assert.throws(()=>dispatch.cancel(cancelled,'TEST-A',actor,at,'ripeti'),/NON_ANNULLABILE/);
assert.throws(()=>dispatch.reschedule(s,'TEST-A',{operatorId:'REAL-OP'},actor,at),/SOLO_DATI_TEST/);
assert.throws(()=>dispatch.calendar(s,'2026-11-05T12:00:00Z','2026-11-05T08:00:00Z'),/INTERVALLO_NON_VALIDO/);
let started=ops.arrive(s,'TEST-A',actor,'2026-11-05T09:00:00Z');
assert.throws(()=>dispatch.reschedule(started,'TEST-A',{start:'2026-11-05T11:00:00Z'},actor,at),/NON_RIPROGRAMMABILE/);
started=ops.finish(started,'TEST-INT-A',actor,'2026-11-05T09:45:00Z',{description:'Manutenzione TEST'});
const load=dispatch.workload(started,'2026-11-05T08:00:00Z','2026-11-05T12:00:00Z');
assert.equal(load[actor].workedMinutes,45);
assert.equal(load[actor].scheduledMinutes,120);
assert.equal(dispatch.audit(started).length,0);
console.log('PASS 4.0.26: calendario, conflitti, riprogrammazione, tecnico, annullamento, carico, audit e immutabilita');
