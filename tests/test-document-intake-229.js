'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const intake=require('../gestionale4/document-intake-229.js'),core=require('../ite-integrated-core-225.js');
const header=Uint8Array.from(Buffer.from('%PDF-1.7'));
assert.equal(intake.classify('Di.Co. elettrico.pdf'),'DICO');
assert.equal(intake.classify('Di.Ri. impianto.pdf'),'DIRI');
assert.equal(intake.classify('Allegato GAS.pdf'),'GAS');
assert.equal(intake.classify('disegno-cad.pdf'),'CAD');
assert.equal(intake.classify('generico.pdf'),'ALLEGATO');
assert.throws(()=>intake.metadata('x.pdf',10,new Uint8Array(Buffer.from('NOT PDF!')),'DICO'),/FIRMA/);
assert.throws(()=>intake.metadata('x.pdf',20000001,header,'DICO'),/DIMENSIONE/);
assert.throws(()=>intake.metadata('x.txt',10,header,'DICO'),/NOME/);
const m=intake.metadata('esempio.pdf',123,header,'DICO','c','s');
assert.deepEqual(Object.keys(m),['kind','filename','mime','bytes','clientId','siteId']);
const store=core.createStore();store.transact(0,s=>{s.clients.push({id:'c',name:'Demo'});s.sites.push({id:'s',clientId:'c',address:'Via Esempio'});s.documents.push({id:'d',...m});});
assert.equal(store.snapshot().documents[0].bytes,123);
assert(!('payload' in store.snapshot().documents[0]));
