'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const ops=require('../ite-operations-40.js'),dash=require('../ite-field-dashboard-40.js');
const at='2026-11-05T08:00:00Z',actor='TEST-OP';
let s=ops.empty();
s=ops.addClient(s,{id:'TEST-C',name:'Cliente TEST'},actor,at);
s=ops.addSite(s,'TEST-C',{id:'TEST-S',address:'Via TEST'},actor,at);
s=ops.addPlant(s,'TEST-C','TEST-S',{id:'TEST-P',type:'Termico'},actor,at);
s=ops.addOperator(s,{id:actor,name:'Tecnico TEST',color:'#123456'},actor,at);
s=ops.appointment(s,{id:'TEST-A',clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',operatorId:actor,start:'2026-11-05T09:00:00Z',end:'2026-11-05T11:00:00Z',kind:'Manutenzione'},actor,at);
s=ops.appointment(s,{id:'TEST-B',clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',operatorId:actor,start:'2026-11-05T11:00:00Z',end:'2026-11-05T12:00:00Z',kind:'Controllo'},actor,at);
s=ops.quote(s,{id:'TEST-Q',clientId:'TEST-C',lines:[{id:'TEST-L1',category:'Idrico',kind:'FORNITURA',description:'Materiale',quantity:2,unitPrice:20,extra:false},{id:'TEST-L2',category:'Idrico',kind:'POSA',description:'Lavoro extra',quantity:1,unitPrice:30,extra:true}]},actor,at);
const from='2026-11-05T10:00:00Z',to='2026-11-05T12:00:00Z',before=JSON.stringify(s);
let r=dash.build(s,from,to);
assert.equal(r.summary.appointments,2);
assert.equal(r.summary.scheduledMinutes,120);
assert.equal(r.summary.approvedCents,4000);
assert.equal(r.summary.pendingExtraCents,3000);
assert.equal(r.clients[0].quotes,1);
assert.equal(JSON.stringify(s),before,'report must be read only');
