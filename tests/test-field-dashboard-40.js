r=dash.build(s,from,to);assert.equal(r.summary.approvedCents,7000);assert.equal(r.summary.pendingExtraCents,0);
s=ops.arrive(s,'TEST-A',actor,'2026-11-05T09:30:00Z');
s=ops.finish(s,'TEST-INT-A',actor,'2026-11-05T10:30:00Z',{description:'Eseguito'});
r=dash.build(s,from,to);assert.equal(r.summary.workedMinutes,30);assert.equal(r.operators[0].closed,1);
assert.equal(dash.build(s,from,to,'TEST-ALT').appointments.length,0);
