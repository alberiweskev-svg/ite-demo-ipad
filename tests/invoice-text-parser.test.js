'use strict';
const assert=require('node:assert/strict');
const {extractInvoiceText,parseItalianMoney,parseDate}=require('../src/invoice-text-parser.js');
assert.equal(parseItalianMoney('1.234,56'),1234.56);
assert.equal(parseItalianMoney('320,00'),320);
assert.equal(parseItalianMoney('12,34,56'),null);
assert.equal(parseDate('31-02-2026'),null);
const result=extractInvoiceText('Copia di cortesia Fattura 1 del 07-01-2025\nTotale € 320,00\nScadenze\n31-03-2025');
assert.deepEqual(result,{tipo_documento:'fattura_vendita',numero_documento:'1',data_emissione:'2025-01-07',totale_documento:320,scadenza:'2025-03-31',origine:'testo_fornito',richiede_conferma:true});
assert.equal(extractInvoiceText('documento sconosciuto').tipo_documento,null);
console.log('Invoice text parser: OK');
