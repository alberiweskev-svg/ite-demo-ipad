'use strict';
const assert=require('node:assert/strict');
const gate=require('../ite-procurement-batch-gate.js');
const at='2026-11-01T04:00:00Z';
const quote={id:'Q-1',type:'Preventivo fornitore',supplierId:'FORN-TEST',lines:[{code:'ABC',qty:2,unitPrice:12.5}],source:'pdf',review:{status:'confirmed',operator:'TECNICO-TEST',reviewedAt:at}};
const invoice={id:'F-1',type:'Fattura acquisto',supplierId:'FORN-TEST',supplierQuoteId:'Q-1',lines:[{code:'ABC',qty:2,unitPrice:13}],source:'pdf',review:{status:'confirmed',operator:'TECNICO-TEST',reviewedAt:at}};
const batch=[quote,invoice];
assert.equal(gate.validateBatch(batch).valid,true);
assert.equal(gate.buildReport(batch).exportable,true);
const snapshot=gate.exportSnapshot(batch);
assert.equal(snapshot.schema,'ite-supplier-reviewed-batch-v1');
assert.equal(gate.importSnapshot(snapshot).documents.length,2);
assert.equal(gate.importSnapshot(snapshot).persisted,false);
assert.equal(gate.validateBatch([quote,{...invoice,id:'Q-1'}]).valid,false);
assert(gate.validateBatch([quote,{...invoice,supplierId:'OTHER'}]).issues.includes('DOCUMENT:1:SUPPLIER_MISMATCH'));
assert(gate.validateBatch([quote,{...invoice,supplierQuoteId:'MISSING'}]).issues.includes('DOCUMENT:1:QUOTE_NOT_FOUND'));
assert(gate.validateBatch([quote,{...invoice,supplierQuoteId:''}]).issues.includes('DOCUMENT:1:QUOTE_LINK_MISSING'));
assert(gate.validateBatch([quote,{...invoice,review:{status:'pending'}}]).issues.includes('DOCUMENT:1:NOT_MANUALLY_CONFIRMED'));
assert(gate.validateBatch([quote,{...invoice,lines:[{code:'ABC',qty:0,unitPrice:13}]}]).issues.includes('DOCUMENT:1:QUANTITY_INVALID:0'));
assert.throws(()=>gate.exportSnapshot([quote,{...invoice,supplierId:'OTHER'}]));
assert.throws(()=>gate.importSnapshot({schema:'unknown',documents:batch}));
assert.throws(()=>gate.importSnapshot({schema:'ite-supplier-reviewed-batch-v1',documents:[quote,{...invoice,review:{status:'pending'}}]}));
assert.equal(gate.exportSnapshot(batch).documents[0].sourceText,undefined);
console.log('OK: supplier batch review gate, links, validation and snapshot roundtrip');
