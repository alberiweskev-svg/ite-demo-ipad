'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const ui=fs.readFileSync(path.join(base,'ite-work-orders-ui-40.js'),'utf8');
const engine=require('../ite-work-orders-40.js');
const workspace=require('../ite-operations-workspace-40.js');
const pos=name=>html.indexOf('src="'+name+'?v=4.0.30"');
assert.ok(pos('ite-work-orders-40.js')>=0,'engine linked');
assert.ok(pos('ite-work-orders-ui-40.js')>pos('ite-work-orders-40.js'),'UI loads after engine');
assert.ok(html.indexOf('ite-operations-workspace-40.js')<pos('ite-work-orders-40.js'),'workspace loads first');
for(const action of ['create','attachQuote','attachDocument','documentStatus','note','synchronize','archive','dossier'])assert.equal(typeof engine[action],'function',action);
for(const method of ['read','transact','backup','restore'])assert.ok(fs.readFileSync(path.join(base,'ite-operations-workspace-40.js'),'utf8').includes(method));
for(const label of ['Crea ordine da appuntamento','Collega preventivo','Collega documento TEST','Aggiorna stato','Registra nota','Archivia','Esporta fascicolo JSON'])assert.ok(ui.includes(label),label);
assert.ok(ui.includes('textContent'),'DOM text only');
assert.ok(!ui.includes('innerHTML'),'no unsafe HTML interpolation');
assert.ok(!ui.includes('FileReader'),'no real document ingestion');
assert.equal(typeof workspace.create,'function');
console.log('PASS 4.0.30: wiring, load order, actions, TEST-only UI');
