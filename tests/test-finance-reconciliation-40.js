'use strict';
const assert=require('node:assert/strict');
const finance=require('../ite-finance-intake-40.js');
const reconcile=require('../ite-finance-reconciliation-40.js').reconcile;
const subjects=[{id:'TEST-C1',name:'Cliente dimostrativo',role:'CLIENTE'},{id:'TEST-F1',name:'Fornitore dimostrativo',role:'FORNITORE'}];
const make=(id,subjectId,direction,type='TD01')=>finance.normalize({id,subjectId,direction,type,number:id,issuedAt:'2026-11-06',taxable:100,vat:22,total:122,lines:[{kind:'FORNITURA',description:'Materiale TEST',quantity:1,unitPrice:60},{kind:'POSA',description:'Lavoro TEST',quantity:1,unitPrice:40}]});
const docs=[make('TEST-I1','TEST-F1','ACQUISTO'),make('TEST-I2','TEST-C1','VENDITA'),make('TEST-I3','TEST-F1','ACQUISTO','TD04'),make('TEST-I4','TEST-C1','VENDITA','PR')];
const copy=JSON.stringify(docs);
let result=reconcile(docs,subjects);
assert.equal(result.status,'COERENTE');
assert.deepEqual(result.totals,{acquistiCents:12200,venditeCents:12200,proformaCents:12200,noteCreditoCents:12200,creditiResiduiCents:12200});
assert.equal(JSON.stringify(docs),copy,'riconciliazione non deve mutare il registro');
docs[2].recoveredCents=2200;
result=reconcile(docs,subjects);
assert.equal(result.totals.creditiResiduiCents,10000);
assert.equal(reconcile([make('TEST-X','TEST-MISSING','ACQUISTO')],subjects).issues[0].code,'ANAGRAFICA_ASSENTE');
assert.equal(reconcile([make('TEST-X','TEST-C1','ACQUISTO')],subjects).issues[0].code,'RUOLO_INCOERENTE');
assert.throws(()=>reconcile([docs[0],docs[0]],subjects),/DUPLICATO/);
assert.throws(()=>reconcile([make('REAL-1','TEST-C1','VENDITA')],subjects),/SOLO_DATI_TEST|DOCUMENTO_DUPLICATO_O_NON_TEST/);
assert.throws(()=>reconcile(docs,[subjects[0],subjects[0]]),/DUPLICATA/);
console.log('Riconciliazione contabile e anagrafica TEST: OK');
