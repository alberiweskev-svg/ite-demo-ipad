'use strict';
const assert=require('node:assert/strict');
const bridge=require('../ite-finance-xml-ledger-40.js');
const ledgerApi=require('../ite-finance-ledger-40.js');
const preview={type:'TD04',number:'NC-TEST-9',issuedAt:'2026-11-06',taxable:100,vat:22,total:122,status:'ANTEPRIMA_NON_REGISTRATA'};
const review={id:'TEST-XML-9',subjectId:'TEST-SUPPLIER-9',direction:'ACQUISTO',confirmed:true,lines:[{kind:'FORNITURA',description:'Materiale TEST',quantity:1,unitPrice:60},{kind:'POSA',description:'Posa TEST',quantity:1,unitPrice:40}]};
assert.throws(()=>bridge.convert(preview,{...review,confirmed:false}),/CONFERMA/);
assert.throws(()=>bridge.convert(preview,{...review,direction:'DA_VERIFICARE'}),/DIREZIONE/);
assert.throws(()=>bridge.convert(preview,{...review,id:'CLIENTE-VERO'}),/SOLO_DATI_TEST/);
assert.throws(()=>bridge.convert(preview,{...review,lines:[{kind:'FORNITURA',description:'TEST',quantity:1,unitPrice:99}]}),/IMPONIBILE/);
const store=new Map();const storage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)};
const ledger=ledgerApi.create(storage);ledger.load();
bridge.register(ledger,preview,review);
assert.equal(ledger.summary().creditiDaRecuperareCents,12200);
assert.equal(ledger.get().documents[0].lines.length,2);
assert.throws(()=>bridge.register(ledger,preview,review),/DUPLICATO/);
assert.equal(ledger.get().documents.length,1);
ledger.recover('TEST-XML-9',22);
assert.equal(ledger.summary().creditiDaRecuperareCents,10000);
const restored=ledgerApi.create(storage);restored.load();assert.equal(restored.get().documents[0].status,'PARZIALMENTE_RECUPERATA');
console.log('XML -> ledger review and persistence TEST: OK');
