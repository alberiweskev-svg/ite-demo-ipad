'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const recovery=require('../gestionale4/recovery-234.js');
const html=fs.readFileSync(path.join(__dirname,'../gestionale4/index.html'),'utf8');
assert.match(html,/id="recovery-version"/);
assert.match(html,/id="restore"/);
assert.match(html,/id="pending"/);
assert.match(html,/if\(!save\(\)\)\{store=core\.createStore\(before\)/);
assert.match(html,/Importazione annullata/);
assert.match(html,/Azzeramento annullato/);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(Boolean);
for(const script of scripts)new vm.Script(script);
const store=new Map();
const storage={getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const valid=x=>{if(!x||!Number.isInteger(x.revision)||!Array.isArray(x.clients))throw Error('INVALID')};
const data=n=>JSON.stringify({revision:n,clients:[],sites:[],plants:[],equipment:[],appointments:[],interventions:[],quotes:[],invoices:[],documents:[]});
const key='test-ite';
assert.equal(recovery.persist(storage,key,data(1),valid).saved,true);
assert.equal(recovery.persist(storage,key,data(2),valid).historySaved,true);
assert.equal(recovery.inspect(storage,key,valid).history[0].revision,1);
assert.equal(recovery.restore(storage,key,0,valid).revision,1);
assert.equal(JSON.parse(storage.getItem(key)).revision,1);
const broken={...storage,setItem(k,v){if(k===key)throw Error('QUOTA');store.set(k,v)}};
assert.throws(()=>recovery.persist(broken,key,data(3),valid),/QUOTA/);
assert.equal(JSON.parse(storage.getItem(key)).revision,1);
assert.equal(recovery.inspect(storage,key,valid).interrupted,true);
assert.equal(recovery.recoverPending(storage,key,valid).revision,3);
assert.equal(recovery.inspect(storage,key,valid).interrupted,false);
console.log('4.0.235: UI syntax, backup history, restore, interrupted save, rollback hooks OK');
