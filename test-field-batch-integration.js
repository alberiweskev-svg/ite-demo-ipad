'use strict';
const assert=require('node:assert/strict');
const workspace=require('./ite-field-workspace.js');
const batch=require('./ite-field-schedule-batch.js');
const catalog={clients:[{id:'C'}],sites:[{id:'S',clientId:'C'}],systems:[{id:'I',siteId:'S'}],equipment:[{id:'E',systemId:'I'}],operators:[{id:'T',active:true}]};
const base={id:'A',clientId:'C',siteId:'S',systemId:'I',equipmentId:'E',operatorId:'T',kind:'manutenzione',startsAt:'2026-11-05T09:00:00+01:00',endsAt:'2026-11-05T10:00:00+01:00'};
const original=workspace.open(catalog,[]);
const valid=[base,{...base,id:'B',startsAt:'2026-11-05T10:00:00+01:00',endsAt:'2026-11-05T11:00:00+01:00'}];
assert.equal(batch.preview(catalog,[],valid).ok,true);
const operations=valid.map(appointment=>({type:'schedule',appointment}));
assert.equal(workspace.preview(original,operations).valid,true);
const applied=workspace.batch(original,operations);
assert.equal(applied.appointments.length,2);
assert.equal(original.appointments.length,0);
const invalid=[base,{...base,id:'C',startsAt:'2026-11-05T09:30:00+01:00',endsAt:'2026-11-05T10:30:00+01:00'}];
assert.equal(batch.preview(catalog,[],invalid).ok,false);
assert.equal(workspace.preview(original,invalid.map(appointment=>({type:'schedule',appointment}))).valid,false);
assert.throws(()=>workspace.batch(original,invalid.map(appointment=>({type:'schedule',appointment}))),/OPERATORE_OCCUPATO/);
assert.equal(original.appointments.length,0);
console.log('PASS integrated batch scheduling, atomic rollback and preview');
