'use strict';
const assert=require('node:assert/strict');
const workspace=require('./ite-field-workspace.js'),planning=require('./ite-field-planning.js');
const catalog={clients:[{id:'C'}],sites:[{id:'S',clientId:'C'}],systems:[{id:'I',siteId:'S'}],equipment:[{id:'E',systemId:'I'}],operators:[{id:'O',active:true}]};
const appointment={id:'A',clientId:'C',siteId:'S',systemId:'I',equipmentId:'E',operatorId:'O',kind:'manutenzione',startsAt:'2026-11-03T09:00:00+01:00',endsAt:'2026-11-03T10:00:00+01:00'};
let state=workspace.open(catalog,[]);
state=workspace.apply(state,{type:'schedule',appointment});
state=workspace.apply(state,{type:'arrive',id:'A',operatorId:'O',at:'2026-11-03T09:00:00+01:00'});
state=workspace.apply(state,{type:'addExtra',id:'A',operatorId:'O',at:'2026-11-03T09:01:00+01:00',payload:{extra:{id:'X',description:'Ricambio',category:'idrico',lines:[{type:'FORNITURA',description:'Pezzi',quantity:2,unitCents:1000},{type:'POSA',description:'Lavoro',quantity:1,unitCents:5800}]}}});
const original=JSON.stringify(state);
assert.equal(workspace.preview(state,[{type:'approveLines',id:'A',operatorId:'O',at:'2026-11-03T09:02:00+01:00',payload:{id:'X',quantities:[3,1]}}]).valid,false);
assert.equal(JSON.stringify(state),original);
state=workspace.apply(state,{type:'approveLines',id:'A',operatorId:'O',at:'2026-11-03T09:02:00+01:00',payload:{id:'X',quantities:[1,0.5]}});
assert.equal(state.appointments[0].extraWorks[0].status,'parzialmente_accettato');
assert.equal(planning.extrasTotals(state.appointments[0]).FORNITURA,1000);
assert.equal(planning.extrasTotals(state.appointments[0]).POSA,2900);
assert.equal(planning.extrasTotals(state.appointments[0]).totalCents,3900);
assert.deepEqual(workspace.restore(workspace.snapshot(state)),state);
console.log('PASS partial extra approval and separated supply/labor totals');
