"use strict";
const assert=require("node:assert/strict");
const bridge=require("./ite-document-registry-bridge-120.js");
const batch=require("./ite-document-batch-117.js");
const review=require("./ite-document-review-119.js");
const catalog={clients:[{id:"C1"}],sites:[{id:"S1",clientId:"C1"}],systems:[{id:"P1",siteId:"S1"}],equipment:[{id:"E1",systemId:"P1"}]};
const original=JSON.stringify(catalog);
let r=bridge.convert({schema:"ITE_FIELD_WORKSPACE_V1",catalog,appointments:[]});
assert.equal(r.plants[0].id,"P1");assert.equal(r.equipment[0].plantId,"P1");
assert.equal(JSON.stringify(catalog),original);
r=bridge.addInvoices(r,[{id:"F1",clientId:"C1"}]);
assert.throws(()=>bridge.addInvoices(r,[{id:"F2",clientId:"OTHER"}]),/FATTURE_NON_COERENTI/);
assert.throws(()=>bridge.convert({...catalog,systems:[{id:"P1",siteId:"BAD"}]}),/IMPIANTO_SEDE_NON_VALIDO/);
const links={clientId:"C1",siteId:"S1",plantId:"P1",equipmentId:"E1"};
const b=batch.makeBatch([{filename:"dico.pdf",text:"Dichiarazione di conformita numero 12 data 09/11/2026",links}],r);
let state=review.review({batch:b,details:[{pages:1}]},r);
state=review.confirm(state,["DOC-0001"],"Tecnico TEST",r).state;
assert.equal(bridge.audit(state,r).invalid,0);
const changed=bridge.convert({...catalog,sites:[{id:"S2",clientId:"C1"}],systems:[{id:"P1",siteId:"S2"}]});
const audit=bridge.audit(state,changed);
assert.equal(audit.invalid,1);assert.equal(audit.staleConfirmations,1);
assert.equal(state.batch.documents[0].status,"CONFERMATO_TEST");
console.log("OK 4.0.120: hierarchy bridge, invoice ownership, immutable audit and stale confirmation");
