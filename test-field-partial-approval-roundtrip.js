'use strict';
const assert=require('node:assert/strict');
const w=require('./ite-field-workflow.js'),p=require('./ite-field-planning.js'),r=require('./ite-field-operations-report.js'),workspace=require('./ite-field-workspace.js');
const catalog={clients:[{id:'C'}],sites:[{id:'S',clientId:'C'}],systems:[{id:'I',siteId:'S'}],equipment:[{id:'E',systemId:'I'}],operators:[{id:'O',active:true}]};
const base={id:'A',clientId:'C',siteId:'S',systemId:'I',equipmentId:'E',operatorId:'O',kind:'riparazione',startsAt:'2026-11-04T09:00:00+01:00',endsAt:'2026-11-04T10:00:00+01:00'};
let a=w.arrive(w.appointment(base),'O','2026-11-04T09:00:00+01:00');
a=w.addExtra(a,{id:'X',description:'Sostituzione',category:'idrico',lines:[{type:'FORNITURA',description:'Materiale',quantity:2,unitCents:1000},{type:'POSA',description:'Montaggio',quantity:1,unitCents:5800}]},'O','2026-11-04T09:05:00+01:00');
a=w.approveLines(a,'X',[1,0.5],'O','2026-11-04T09:10:00+01:00');
assert.equal(a.extraWorks[0].status,'parzialmente_accettato');
assert.equal(p.extrasTotals(a).totalCents,3900);
assert.equal(r.validate(catalog,[a]).valid,true);
a=w.approveLines(a,'X',[2,1],'O','2026-11-04T09:15:00+01:00');
assert.equal(a.extraWorks[0].status,'accettato');
assert.equal(p.extrasTotals(a).totalCents,7800);
assert.ok(a.audit.some(e=>e.event==='EXTRA_LINES_APPROVED'));
a=w.close(a,'O','2026-11-04T10:00:00+01:00');
const data=workspace.open(catalog,[a]),roundtrip=workspace.restore(workspace.snapshot(data));
assert.deepEqual(roundtrip,data);
const corrupted=JSON.parse(JSON.stringify(data));corrupted.appointments[0].extraWorks[0].lines[0].acceptedQuantity=0;
assert.equal(r.validate(catalog,corrupted.appointments).valid,false);
assert.throws(()=>workspace.open(catalog,corrupted.appointments));
console.log('PASS partial approval updates, totals, audit, validation and snapshot roundtrip');
