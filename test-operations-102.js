const assert=require("node:assert/strict");
const w=require("./ite-workflow-100.js"),o=require("./ite-operations-102.js");
let s=w.fresh();
function add(k,row){s=w.transact(s,k,row,"Tecnico TEST",s.revision);}
add("clients",{id:"TEST-CLIENT-001",name:"Cliente fittizio"});
add("sites",{id:"TEST-SITE-001",name:"Sede fittizia",clientId:"TEST-CLIENT-001"});
add("plants",{id:"TEST-PLANT-001",name:"Impianto TEST",siteId:"TEST-SITE-001",clientId:"TEST-CLIENT-001"});
add("devices",{id:"TEST-DEVICE-001",name:"Caldaia TEST",plantId:"TEST-PLANT-001",clientId:"TEST-CLIENT-001"});
add("operators",{id:"TEST-OPERATOR-001",name:"Tecnico TEST"});
const refs={clientId:"TEST-CLIENT-001",siteId:"TEST-SITE-001",plantId:"TEST-PLANT-001",deviceId:"TEST-DEVICE-001",operatorId:"TEST-OPERATOR-001"};
add("appointments",{id:"TEST-APPT-001",...refs,startsAt:"2026-11-12T09:00:00.000Z"});
add("interventions",{id:"TEST-JOB-001",...refs,appointmentId:"TEST-APPT-001",arrivedAt:"2026-11-12T09:00:00.000Z",leftAt:"2026-11-12T10:00:00.000Z"});
add("quotes",{id:"TEST-QUOTE-001",clientId:refs.clientId,category:"FORNITURA",unitCents:10000,quantity:2});
add("extras",{id:"TEST-EXTRA-001",clientId:refs.clientId,quoteId:"TEST-QUOTE-001",category:"POSA",unitCents:5000,quantity:3});
add("invoices",{id:"TEST-INVOICE-001",clientId:refs.clientId,type:"VENDITA",totalCents:20000});
add("invoices",{id:"TEST-CREDIT-001",clientId:refs.clientId,type:"TD04",totalCents:3000});
const initial=JSON.stringify(s);
assert.throws(()=>o.transition(s,"appointments","TEST-APPT-001","CONCLUSO","Tecnico TEST",s.revision));
assert.throws(()=>o.transition(s,"appointments","TEST-APPT-001","CONFERMATO","Tecnico TEST",s.revision-1),/Conflitto/);
s=o.transition(s,"appointments","TEST-APPT-001","CONFERMATO","Tecnico TEST",s.revision);
s=o.transition(s,"appointments","TEST-APPT-001","CONCLUSO","Tecnico TEST",s.revision);
s=o.transition(s,"interventions","TEST-JOB-001","IN_CORSO","Tecnico TEST",s.revision);
s=o.transition(s,"interventions","TEST-JOB-001","CHIUSO","Tecnico TEST",s.revision);
assert.throws(()=>o.transition(s,"interventions","TEST-JOB-001","REVISIONATO","Tecnico TEST",s.revision),/Motivazione/);
s=o.transition(s,"interventions","TEST-JOB-001","REVISIONATO","Tecnico TEST",s.revision,{reason:"Verifica tecnica TEST"});
assert.throws(()=>o.transition(s,"extras","TEST-EXTRA-001","PARZIALE","Tecnico TEST",s.revision,{approvedQuantity:3}),/Quantità/);
s=o.transition(s,"extras","TEST-EXTRA-001","PARZIALE","Tecnico TEST",s.revision,{approvedQuantity:2});
assert.equal(o.report(s,refs.clientId).approvedExtrasCents,10000);
assert.equal(o.report(s).netSalesCents,17000);
assert.equal(o.history(s,"interventions","TEST-JOB-001").length,3);
assert.equal(JSON.parse(initial).revision,11);
assert.equal(s.officialReady,false);
console.log("ITE 4.0.102 operations regression PASS");
