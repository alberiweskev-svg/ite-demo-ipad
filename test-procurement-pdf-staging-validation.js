'use strict';
const assert=require('node:assert/strict');
const {stage,amount}=require('./ite-procurement-pdf-staging.js');
const input={id:'OFF-TEST',type:'Offerta fornitore',supplierId:'FORN-TEST'};
const good=stage({...input,text:'ART-1 | 2 | 1.234,50 | 2.469,00\nART-2 | 1,5 | 10,00 | 15,00'});
assert.equal(good.document.lines.length,2);
assert.equal(good.document.lines[0].unitPrice,1234.5);
assert.equal(good.document.lines[1].qty,1.5);
assert.equal(good.issues.length,0);
const bad=stage({...input,text:'ART-1 | 2 | 10,00 | 21,00\nART-2 | 1 | 4,00\nART-2 | 1 | 4,00'});
assert.equal(bad.document.lines.length,1);
assert.deepEqual(bad.rejected.map(x=>x.reason),['TOTALE_RIGA_NON_COINCIDE','CODICE_ARTICOLO_DUPLICATO']);
assert.ok(bad.issues.includes('LINES_REQUIRE_CORRECTION'));
assert.equal(bad.document.review.status,'pending');
const unstructured=stage({...input,text:'Descrizione articolo 2 pezzi a euro 10'});
assert.ok(unstructured.issues.includes('MANUAL_TRANSCRIPTION_REQUIRED'));
assert.equal(unstructured.document.lines.length,0);
assert.equal(amount('-10,00'),null);
assert.equal(amount('1.234,50'),1234.5);
assert.equal(good.requiresManualConfirmation,true);
console.log('PDF staging validation: synthetic cases passed');
