"use strict";
const assert=require("node:assert/strict");
globalThis.ITEDocumentIntake90=require("./ite-document-intake-90.js");
globalThis.ITEDocumentReview92=require("./ite-document-review-92.js");
globalThis.ITEServiceLedger40=require("./ite-service-ledger-40.js");
globalThis.ITEDocumentLinks93=require("./ite-document-links-93.js");
const G=require("./ite-document-gate-95.js"),I=globalThis.ITEDocumentIntake90,L=globalThis.ITEDocumentLinks93,S=globalThis.ITEServiceLedger40,R=globalThis.ITEDocumentReview92;
const ledger=S.empty(),links=L.empty(),reviews=R.empty(),empty=I.empty();
const baseline=G.evaluate(empty,links,ledger,reviews);
assert.deepEqual(baseline.summary,{total:0,metadataReady:0,officialReady:0,blocked:0,orphanLinks:0});
const d=I.createRecord({id:"TEST-DOC-001",name:"DICHIARAZIONE DI CONFORMITA ELETTRICO.pdf",size:100,mime:"application/pdf"});
const manifest=I.append(empty,d),before=JSON.stringify(manifest);
const report=G.evaluate(manifest,links,ledger,reviews);
assert.equal(report.summary.blocked,1);
assert.equal(report.rows[0].readyForOfficialIssue,false);
assert.ok(report.rows[0].issues.includes("SENZA_COLLEGAMENTO"));
assert.ok(report.rows[0].issues.includes("VERIFICA_TECNICA_PDF_NON_ESEGUITA"));
assert.ok(report.rows[0].issues.includes("CONTENUTO_PDF_NON_VERIFICATO"));
assert.equal(JSON.stringify(manifest),before);
assert.equal(G.filter(report,{onlyBlocked:true}).length,1);
assert.equal(G.filter(report,{clientId:"TEST-OTHER"}).length,0);
assert.equal(JSON.parse(G.exportReport(report)).summary.officialReady,0);
assert.throws(()=>G.exportReport({}),/Rapporto/);
let populated=S.empty();
populated=S.add(populated,"clients",{id:"TEST-CLIENT-01",name:"Cliente fittizio"});
populated=S.add(populated,"sites",{id:"TEST-SITE-01",clientId:"TEST-CLIENT-01",name:"Sede fittizia"});
const linked=L.link(links,manifest,populated,"TEST-DOC-001",{clientId:"TEST-CLIENT-01"},"Tecnico TEST","2026-11-08T12:00:00Z");
const linkedReport=G.evaluate(manifest,linked,populated,reviews);
assert.equal(linkedReport.summary.metadataReady,0,"Di.Co. senza revisione bloccata");
const reviewed={schema:R.SCHEMA,events:[{documentId:"TEST-DOC-001",action:"REVIEWED",type:"DICO_ELETTRICO",operator:"Tecnico TEST",reason:"Verifica classificazione",at:"2026-11-08T12:01:00Z"}]};
const ready=G.evaluate(manifest,linked,populated,reviewed);
assert.equal(ready.summary.metadataReady,1,"Metadati collegati e revisionati");
assert.equal(ready.summary.officialReady,0,"Nessuna emissione ufficiale senza verifica PDF");
assert.equal(ready.rows[0].readyForOfficialIssue,false);
const credit=I.createRecord({id:"TEST-DOC-002",name:"NOTA DI CREDITO TD04.pdf",size:100,mime:"application/pdf"});
const creditManifest=I.append(manifest,credit);
const creditLinked=L.link(linked,creditManifest,populated,"TEST-DOC-002",{clientId:"TEST-CLIENT-01"},"Tecnico TEST","2026-11-08T12:02:00Z");
const creditReport=G.evaluate(creditManifest,creditLinked,populated,reviewed);
assert.ok(creditReport.rows[1].issues.includes("CONTROLLO_AMMINISTRATIVO_RICHIESTO"));
assert.equal(creditReport.summary.blocked,1);
console.log("4.0.95 gate documentale TEST OK");
