'use strict';
const assert=require('node:assert/strict'),p=require('./ite-field-planning.js');
const t='2026-11-01T09:00:00+01:00',end='2026-11-01T10:00:00+01:00';
const catalog={clients:[{id:'C1'}],sites:[{id:'S1',clientId:'C1'}],systems:[{id:'I1',siteId:'S1'}],equipment:[{id:'E1',systemId:'I1'}],operators:[{id:'O1',active:true},{id:'O2',active:true}]};
const fixture={id:'A1',clientId:'C1',siteId:'S1',systemId:'I1',equipmentId:'E1',operatorId:'O1',kind:'manutenzione',startsAt:t,endsAt:end};
let list=p.schedule(catalog,[],fixture);
assert.equal(list.length,1);assert.equal(list[0].status,'scheduled');
assert.throws(()=>p.schedule(catalog,list,{...fixture,id:'A2'}),/OPERATORE_OCCUPATO/);
assert.throws(()=>p.schedule(catalog,list,fixture),/DUPLICATO/);
assert.equal(p.schedule(catalog,list,{...fixture,id:'A2',operatorId:'O2'}).length,2);
assert.equal(p.schedule(catalog,list,{...fixture,id:'A2',startsAt:end,endsAt:'2026-11-01T11:00:00+01:00'}).length,2);
assert.throws(()=>p.schedule({...catalog,equipment:[{id:'E1',systemId:'ALTRO'}]},[],fixture),/APPARECCHIATURA_IMPIANTO/);
assert.throws(()=>p.schedule({...catalog,operators:[{id:'O1',active:false}]},[],fixture),/NON_ATTIVO/);
assert.equal(p.calendar(list,{operatorId:'O1'}).length,1);
assert.equal(p.calendar(list,{from:end,to:'2026-11-01T11:00:00+01:00'}).length,0);
assert.throws(()=>p.calendar(list,{from:end,to:t}),/INTERVALLO/);
list=p.transition(list,'A1','arrive','O1',t);
list=p.transition(list,'A1','addExtra','O1',t,{extra:{id:'X1',description:'Lavabo',category:'idrico',lines:[{type:'FORNITURA',description:'Lavabo',quantity:1,unitCents:12000},{type:'POSA',description:'Montaggio',quantity:2,unitCents:3500}]}});
assert.equal(p.extrasTotals(list[0]).totalCents,0);
list=p.transition(list,'A1','decideExtra','O1',t,{id:'X1',status:'accettato'});
assert.deepEqual([p.extrasTotals(list[0]).FORNITURA,p.extrasTotals(list[0]).POSA,p.extrasTotals(list[0]).totalCents],[12000,7000,19000]);
list=p.transition(list,'A1','close','O1',end,{notes:'Collaudo OK'});
assert.equal(p.equipmentHistory(list,'E1')[0].minutes,60);
list=p.transition(list,'A1','reopen','O1',end,{reason:'Rettifica orario'});
list=p.transition(list,'A1','reviseTimes','O1',end,{changes:[{visitIndex:0,arrivedAt:'2026-11-01T09:15:00+01:00'}]});
list=p.transition(list,'A1','finishRevision','O1',end);
assert.equal(p.equipmentHistory(list,'E1')[0].minutes,45);
assert.equal(p.equipmentHistory(list,'E1')[0].extraWorks[0].status,'accettato');
console.log('PASS: hierarchy, conflicts, calendar, operator, intervention, extra, equipment history and revision');
