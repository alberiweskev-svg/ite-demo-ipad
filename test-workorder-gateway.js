'use strict';
const assert=require('node:assert/strict'),ledger=require('./ite-workorder-ledger.js'),g=require('./ite-workorder-gateway.js');
const data={clients:[{id:'C'}],sites:[{id:'S',clientId:'C'}],systems:[{id:'I',siteId:'S'}],equipment:[{id:'E',systemId:'I'}],operators:[{id:'T',active:true}],appointments:[{id:'A',clientId:'C',siteId:'S',systemId:'I',equipmentId:'E',operatorId:'T',start:'2026-11-03T08:00:00Z',end:'2026-11-03T09:00:00Z'}]};
const order={id:'O',clientId:'C',siteId:'S',systemId:'I',appointmentId:'A',operatorId:'T'};
assert.equal(g.verify(data).c.clients.length,1);
assert.deepEqual(g.overlaps(data),[]);
assert.throws(()=>g.verify({...data,sites:[{id:'S',clientId:'UNKNOWN'}]}),/SEDE_CLIENTE/);
assert.throws(()=>g.verify({...data,equipment:[{id:'E',systemId:'UNKNOWN'}]}),/APPARECCHIO_IMPIANTO/);
assert.throws(()=>g.verify({...data,appointments:[{...data.appointments[0],end:data.appointments[0].start}]}),/APPUNTAMENTO_ORARIO/);
assert.throws(()=>g.verify({...data,appointments:[{...data.appointments[0],siteId:'WRONG'}]}),/APPUNTAMENTO_RIFERIMENTI/);
assert.throws(()=>g.checkOrder(data,{...order,clientId:'WRONG'}),/ORDINE_APPUNTAMENTO_DIVERSO/);
assert.throws(()=>g.checkOrder({...data,operators:[{id:'T',active:false}]},order),/ORDINE_RIFERIMENTI/);
const overlap={...data,appointments:[...data.appointments,{...data.appointments[0],id:'B',start:'2026-11-03T08:30:00Z',end:'2026-11-03T09:30:00Z'}]};
assert.equal(g.overlaps(overlap).length,1);
assert.throws(()=>g.addOrder(ledger.initial(),0,order,'DEMO','2026-11-02T04:00:00Z',overlap),/OPERATORE_SOVRAPPOSTO/);
const s=g.addOrder(ledger.initial(),0,order,'DEMO','2026-11-02T04:00:00Z',data);
assert.equal(s.revision,1);
assert.equal(g.audit(s,data).ok,true);
assert.throws(()=>g.addOrder(s,1,{...order,id:'O2'},'DEMO','2026-11-02T04:00:00Z',data),/APPUNTAMENTO_GIA_UTILIZZATO/);
assert.equal(g.audit(s,{...data,operators:[{id:'T',active:false}]}).ok,false);
assert.equal(g.audit(s,overlap).ok,false);
console.log('OK: gateway hierarchy, scheduling, work orders and audit (15 assertions)');
