'use strict';
const assert=require('node:assert/strict');
const H=require('./ite-hierarchy-workspace.js');
const I=require('./ite-document-intake.js');
const D=require('./ite-technical-dossier.js');
let master=H.empty();
master=H.add(master,'clients',{id:'client-test',name:'Cliente Fittizio'});
master=H.add(master,'sites',{id:'site-test',clientId:'client-test',address:'Via Esempio 1'});
master=H.add(master,'plants',{id:'plant-test',siteId:'site-test'});
master=H.add(master,'devices',{id:'device-test',plantId:'plant-test'});
master=H.add(master,'appointments',{id:'appointment-test',clientId:'client-test',siteId:'site-test',deviceId:'device-test',operator:'Tecnico Demo',start:'2026-11-04T09:00',end:'2026-11-04T10:00'});
master=H.createIntervention(master,'appointment-test','Tecnico Demo','intervention-test');
let queue=I.add(I.empty(),{id:'doc-test',filename:'dico-fittizia.pdf',addedAt:'2026-11-04',type:'DICO_IDRICO',clientId:'client-test',siteId:'site-test',number:'TEST-001',documentDate:'2026-11-04'});
const ref={documentId:'doc-test',clientId:'client-test',siteId:'site-test',plantId:'plant-test',deviceId:'device-test',interventionId:'intervention-test',linkedAt:'2026-11-04'};
assert.throws(()=>D.attach(D.empty(),queue,master,ref),/VERIFICARE/);
queue=I.verify(queue,'doc-test','Tecnico Demo');
assert.throws(()=>D.attach(D.empty(),queue,master,{...ref,siteId:'wrong'}),/INCOERENTE/);
assert.throws(()=>D.attach(D.empty(),queue,master,{...ref,deviceId:'missing'}),/INCOERENTE/);
const linked=D.attach(D.empty(),queue,master,ref);
assert.equal(linked.links.length,1);
assert.equal(D.dossier(linked,queue,master,{deviceId:'device-test'})[0].number,'TEST-001');
assert.equal(D.coverage(linked,queue,master,'client-test','site-test').byType.DICO_IDRICO,1);
assert.deepEqual(D.coverage(D.empty(),queue,master,'client-test','site-test').unlinkedVerified,['doc-test']);
assert.throws(()=>D.attach(linked,queue,master,ref),/GIA_COLLEGATO/);
assert.equal(D.empty().links.length,0);
assert.equal(queue.items[0].status,'VERIFICATO');
const storage=new Map();
const adapter={getItem:k=>storage.has(k)?storage.get(k):null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
D.save(adapter,linked,queue,master);
assert.deepEqual(D.load(adapter,queue,master),linked);
assert.equal(JSON.parse(storage.get(D.KEY+'_previous')).links.length,0);
queue=I.archive(queue,'doc-test');
assert.equal(D.dossier(linked,queue,master).length,1);
assert.throws(()=>D.validate(linked,I.empty(),master),/NON_VERIFICATO/);
console.log('Technical dossier: all synthetic integration tests passed');
