'use strict';
const assert=require('node:assert/strict');
const reg=require('./ite-technical-register.js'),intake=require('./ite-pdf-intake.js'),review=require('./ite-technical-review.js');
const h={clients:[{id:'TEST-C',sites:[{id:'TEST-S',plants:[{id:'TEST-P',devices:[{id:'TEST-D'}]}]}]}]};
const base='DICHIARAZIONE TEST-DEMO\nNumero: TEST-001\nData: 04/11/2026\nCommittente: TEST Cliente\nIndirizzo: TEST Via 1\nImpianto: TEST Idrico';
const item=i=>({id:'TEST-PDF-'+i,kind:'DICO_IDRICA',text:base.replace('TEST-001','TEST-00'+i),clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',deviceId:'TEST-D'});
const state=intake.register({records:[]},[item(1),item(2)],h,reg,'TECNICO TEST','2026-11-05T01:00:00Z');
const args={operator:'TECNICO TEST',at:'2026-11-05T01:30:00Z',reason:'TEST correzione controllata'};
const next=review.revise(state,'TEST-PDF-1',{number:'TEST-101',committente:'TEST Nuovo'},args.operator,args.at,args.reason);
assert.equal(state.records[0].number,'TEST-001');
assert.equal(next.records[0].number,'TEST-101');
assert.equal(next.records[0].extracted.committente,'TEST Nuovo');
assert.equal(next.records[0].history.at(-1).before.number,'TEST-001');
assert.equal(next.records[0].history.at(-1).after.number,'TEST-101');
assert.equal(review.audit(next)[0].corrections,1);
assert.throws(()=>review.revise(next,'TEST-PDF-1',{committente:'Mario Rossi'},args.operator,args.at,args.reason),/SOLO_DATI_FITTIZI/);
assert.throws(()=>review.revise(next,'TEST-PDF-1',{date:'2026-02-30'},args.operator,args.at,args.reason),/DATA_NON_VALIDA/);
assert.throws(()=>review.reviseBatch(state,[{id:'TEST-PDF-1',changes:{number:'TEST-999'},...args},{id:'TEST-PDF-2',changes:{address:'Via reale'},...args}]),/SOLO_DATI_FITTIZI/);
assert.equal(state.records[0].number,'TEST-001');
const confirmed=reg.transition(next,'TEST-PDF-1','CONFERMA','TECNICO TEST','2026-11-05T01:35:00Z','');
assert.throws(()=>review.revise(confirmed,'TEST-PDF-1',{number:'TEST-102'},args.operator,args.at,args.reason),/RIAPRIRE/);
const reopened=reg.transition(confirmed,'TEST-PDF-1','RIAPRI','TECNICO TEST','2026-11-05T01:40:00Z','TEST nuova revisione');
assert.equal(review.revise(reopened,'TEST-PDF-1',{number:'TEST-102'},args.operator,args.at,args.reason).records[0].number,'TEST-102');
console.log('ITE technical review synthetic: OK');
