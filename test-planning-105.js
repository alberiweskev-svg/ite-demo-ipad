const assert=require("node:assert/strict");
const base=require("./ite-workflow-100.js"),plan=require("./ite-planning-105.js");
let s=base.fresh();
const add=(k,r)=>{s=base.transact(s,k,r,"Operatore TEST",s.revision);};
add("clients",{id:"TEST-CLIENT-001",name:"Cliente fittizio"});
add("sites",{id:"TEST-SITE-001",name:"Sede TEST",clientId:"TEST-CLIENT-001"});
add("plants",{id:"TEST-PLANT-001",name:"Impianto TEST",clientId:"TEST-CLIENT-001",siteId:"TEST-SITE-001"});
add("devices",{id:"TEST-DEVICE-001",name:"Generatore TEST",clientId:"TEST-CLIENT-001",plantId:"TEST-PLANT-001"});
add("operators",{id:"TEST-OPERATOR-001",name:"Tecnico TEST"});
const a={clientId:"TEST-CLIENT-001",siteId:"TEST-SITE-001",plantId:"TEST-PLANT-001",deviceId:"TEST-DEVICE-001",operatorId:"TEST-OPERATOR-001"};
const row={...a,id:"TEST-APPT-001",startsAt:"2026-11-12T09:00:00+01:00",endsAt:"2026-11-12T10:00:00+01:00"};
s=plan.createAppointment(s,row,"Operatore TEST",s.revision);
assert.equal(plan.conflicts(s,a.operatorId,"2026-11-12T09:30:00+01:00","2026-11-12T10:30:00+01:00").length,1);
assert.equal(plan.conflicts(s,a.operatorId,"2026-11-12T10:00:00+01:00","2026-11-12T11:00:00+01:00").length,0);
const original=JSON.stringify(s);
assert.throws(()=>plan.createAppointment(s,{...row,id:"TEST-APPT-002",startsAt:"2026-11-12T09:30:00+01:00"},"Operatore TEST",s.revision),/impegnato/);
assert.equal(JSON.stringify(s),original);
assert.throws(()=>plan.reviseAppointment(s,row.id,{startsAt:"2026-11-12T11:00:00+01:00"},"TEST","motivo",s.revision-1),/Conflitto/);
s=plan.reviseAppointment(s,row.id,{startsAt:"2026-11-12T11:00:00+01:00",endsAt:"2026-11-12T12:00:00+01:00"},"TEST","Cambio disponibilità",s.revision);
s=plan.startJob(s,row.id,"TEST-JOB-001","2026-11-12T11:05:00+01:00","TEST",s.revision);
assert.throws(()=>plan.startJob(s,row.id,"TEST-JOB-002","2026-11-12T11:10:00+01:00","TEST",s.revision),/già associato/);
assert.throws(()=>plan.closeJob(s,"TEST-JOB-001","2026-11-12T10:00:00+01:00","TEST","Pulizia caldaia",s.revision),/uscita/);
s=plan.closeJob(s,"TEST-JOB-001","2026-11-12T11:45:00+01:00","TEST","Pulizia caldaia TEST",s.revision);
const d=plan.dossier(s,row.id);
assert.equal(d.interventions[0].status,"CHIUSO");
assert.equal(d.officialReady,false);
assert(s.audit.some(x=>x.action==="RESCHEDULE"));
assert(s.audit.some(x=>x.action==="CLOSE"));
console.log("Planning 105: OK");
