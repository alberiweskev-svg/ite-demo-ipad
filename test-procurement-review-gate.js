'use strict';
const assert=require('node:assert/strict');
const gate=require('./ite-procurement-review.js');
const adapter=require('./ite-procurement-document-bridge.js');
const reconcile=require('./ite-core-reconciliation.js');
const core={clienti:[],immobili:[],impianti:[],apparecchiature:[],appuntamenti:[],interventi:[]};
const quote={id:'Q1',type:'Preventivo fornitore',source:'pdf',supplierId:'SUP',lines:[{code:'VAL',unitPrice:'10,00'}]};
const invoice={id:'F1',type:'Fattura acquisto',source:'pdf',supplierId:'SUP',supplierQuoteId:'Q1',lines:[{code:'VAL',unitPrice:12}]};
const original=JSON.stringify([quote,invoice]);
assert.equal(gate.needsReview(quote),true);
let merged=adapter.merge({documents:[quote,invoice]});
assert.equal(merged.quotes.length,0);
assert.equal(merged.invoices.length,0);
assert.equal(merged.issues.filter(x=>x.code==='IMPORTED_DOCUMENT_REVIEW_REQUIRED').length,2);
assert.throws(()=>gate.review({...quote,lines:[{code:'VAL',unitPrice:-1}]},'TEC','2026-10-31T12:00:00Z'));
assert.throws(()=>gate.review({...quote,lines:[{code:'VAL',unitPrice:10},{code:'VAL',unitPrice:11}]},'TEC','2026-10-31T12:00:00Z'));
assert.throws(()=>gate.review(quote,'','2026-10-31T12:00:00Z'));
const approved=[gate.review(quote,'TEC','2026-10-31T12:00:00Z'),gate.review(invoice,'TEC','2026-10-31T12:05:00Z')];
assert.equal(gate.needsReview(approved[0]),false);
assert.equal(approved[0].lines[0].unitPrice,10);
merged=adapter.merge({documents:approved});
assert.equal(merged.quotes.length,1);
assert.equal(merged.invoices.length,1);
const report=reconcile.inspect(core,{documents:approved});
assert.equal(report.supplierAudit[0].status,'DIFFERENZE');
assert.equal(report.supplierAudit[0].differences[0].percent,20);
assert.equal(JSON.stringify([quote,invoice]),original);
console.log('Procurement review gate: synthetic end-to-end checks passed');
