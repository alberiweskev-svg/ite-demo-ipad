'use strict';
const assert=require('node:assert/strict'),core=require('../ite-integrated-core-225.js'),registry=require('./document-registry-255.js');
const store=core.createStore(),add=(t,x)=>core.add(store,t,x);
add('clients',{id:'C1',name:'Demo'});add('clients',{id:'C2',name:'Demo 2'});
add('sites',{id:'S1',clientId:'C1',address:'Via Fittizia'});add('sites',{id:'S2',clientId:'C2',address:'Via Demo'});
add('plants',{id:'P1',siteId:'S1',type:'Termico'});add('equipment',{id:'E1',plantId:'P1',type:'Caldaia'});
add('interventions',{id:'I1',siteId:'S1',operator:'Operatore',status:'APERTO'});
const d=(id,kind='DICO')=>({id,kind,filename:'demo.pdf',mime:'application/pdf',bytes:100,siteId:'S1',interventionId:'I1',equipmentId:'E1'});
const reject=(fn,code)=>{const before=store.exportMetadata();assert.throws(fn,new RegExp(code));assert.equal(store.exportMetadata(),before);};
registry.registerBatch(store,[d('D1'),d('D2','GAS'),d('D3','DIRI'),d('D4','CAD'),d('D5','POS')]);
reject(()=>registry.registerBatch(store,[d('D6'),{...d('D7'),siteId:'S2'}]),'INTERVENTO_SEDE_DIVERSI');
reject(()=>registry.registerBatch(store,[{...d('D6'),payload:'%PDF'}]),'CONTENUTO_PDF_NON_AMMESSO');
reject(()=>registry.registerBatch(store,[d('D1')]),'ID_DOCUMENTO_DUPLICATO');
registry.registerBatch(store,[{...d('D6'),replacesId:'D1',version:2}]);
assert.equal(registry.dossier(store.snapshot(),'S1').current,5);
reject(()=>registry.registerBatch(store,[{...d('D7'),replacesId:'D1'}]),'REVISIONE_GIA_PRESENTE');
registry.registerBatch(store,[d('=D8','ALLEGATO')]);
assert(registry.csv(store.snapshot(),'S1').includes("'=D8"));
assert.deepEqual(registry.audit(store.snapshot()),[]);
// Existing valid revisions must not be reported as already replaced.
const good=store.snapshot();
assert.equal(registry.audit(good).length,0);
// Imported or recovered inconsistent metadata must be diagnosed without mutation.
const fork=JSON.parse(JSON.stringify(good));
fork.documents.push({...fork.documents.find(x=>x.id==='D6'),id:'FORK',replacesId:'D1',version:2});
assert(registry.audit(fork).some(x=>x.code==='REVISIONE_RAMIFICATA'));
const cycle=JSON.parse(JSON.stringify(good));
cycle.documents.find(x=>x.id==='D1').replacesId='D6';
assert(registry.audit(cycle).some(x=>x.code==='REVISIONE_CICLICA'));
const missing=JSON.parse(JSON.stringify(good));
missing.documents.find(x=>x.id==='D6').replacesId='UNKNOWN';
assert(registry.audit(missing).some(x=>x.code==='REVISIONE_ORIGINE_NON_VALIDA'));
assert.equal(core.validate(store.snapshot()),true);
console.log('PASS document registry 255');
