'use strict';
const assert=require('node:assert/strict');
const core=require('../ite-integrated-core-225.js'),extras=require('./extras-244.js'),billing=require('./billing-245.js'),audit=require('./commercial-audit-246.js');
const store=core.createStore();
core.add(store,'clients',{id:'C',name:'Cliente TEST'});
core.add(store,'quotes',{id:'Q',clientId:'C',status:'ACCETTATO',lines:[{id:'F',kind:'FORNITURA',description:'Materiale TEST',cents:10000,qty:1},{id:'P',kind:'POSA',description:'Posa TEST',cents:5000,qty:1}]});
extras.propose(store,{quoteId:'Q',id:'E',description:'Extra TEST',supplyCents:1000,laborCents:2000,qty:2});
assert(audit.inspect(store.snapshot()).issues.some(x=>x.code==='EXTRA_IN_ATTESA'));
extras.decide(store,'Q','E',1);
billing.issue(store,{quoteId:'Q',id:'I',number:'1/TEST',cents:8000});
billing.credit(store,{invoiceId:'I',id:'N',number:'NC/TEST',cents:2000});
let a=audit.inspect(store.snapshot());assert.equal(a.blocking,0);assert.equal(a.review,0);
assert.deepEqual([a.rows[0].supplyCents,a.rows[0].laborCents,a.rows[0].totalCents,a.rows[0].remainingCents],[11000,7000,18000,12000]);
const raw=store.exportMetadata();const bad=store.snapshot();bad.quotes[0].lines.find(x=>x.id==='E-P').qty=2;
assert(audit.inspect(bad).issues.some(x=>x.code==='EXTRA_RIGA_INCOERENTE'));
bad.quotes[0].lines=bad.quotes[0].lines.filter(x=>x.id!=='E-F');
assert(audit.inspect(bad).issues.some(x=>x.code==='EXTRA_RIGA_INCOERENTE'));
bad.invoices.push({id:'N2',kind:'TD04',clientId:'C',originalInvoiceId:'I',number:'NC/TEST2',cents:8000});
assert(audit.inspect(bad).issues.some(x=>x.code==='TD04_SUPERA_FATTURA'));
bad.invoices.push({id:'I2',kind:'VENDITA',clientId:'C',quoteId:'Q',number:'1/TEST',cents:15000});
assert(audit.inspect(bad).issues.some(x=>x.code==='NUMERO_DUPLICATO_TIPO'));
assert(audit.inspect(bad).issues.some(x=>x.code==='NUMERO_DUPLICATO_TIPO'));
const over=structuredClone(bad);over.invoices.find(x=>x.id==='I2').cents=30000;
assert(audit.inspect(over).issues.some(x=>x.code==='SALDO_PREVENTIVO_INCOERENTE'));
const foreign=structuredClone(store.snapshot());foreign.clients.push({id:'OTHER',name:'Altro TEST'});foreign.invoices[0].clientId='OTHER';
assert(audit.inspect(foreign).issues.some(x=>x.code==='FATTURA_ALTRO_CLIENTE'));
foreign.invoices.push({...foreign.invoices[0]});
assert(audit.inspect(foreign).issues.some(x=>x.code==='DOCUMENTO_ID_DUPLICATO'));
foreign.quotes[0].clientId='MISSING';
assert(audit.inspect(foreign).issues.some(x=>x.code==='CLIENTE_PREVENTIVO_ASSENTE'));
assert.equal(store.exportMetadata(),raw,'audit must never mutate original');
console.log('PASS 4.0.246 integrated read-only commercial audit');
