'use strict';
const assert=require('node:assert/strict'),core=require('../ite-integrated-core-225.js'),flow=require('./document-workflow-258.js');
const store=core.createStore(),add=(t,x)=>core.add(store,t,x);
add('clients',{id:'C1',name:'Cliente fittizio'});add('sites',{id:'S1',clientId:'C1',address:'Via Demo 1'});
add('plants',{id:'P1',siteId:'S1',type:'Termico'});add('equipment',{id:'E1',plantId:'P1',type:'Caldaia'});add('equipment',{id:'E2',plantId:'P1',type:'Pompa di calore'});
add('interventions',{id:'I1',siteId:'S1',equipmentId:'E1',operator:'Tecnico demo',status:'APERTO'});
const d=(id,kind='DICO')=>({id,kind,siteId:'S1',filename:'demo.pdf',mime:'application/pdf',bytes:100,equipmentId:'E1',interventionId:'I1'});
flow.register(store,[d('D1'),d('D2','GAS')]);
assert.equal(flow.summary(store.snapshot(),'S1').current,2);
const before=store.exportMetadata();
assert.throws(()=>flow.register(store,[{...d('D3'),replacesId:'D1'}, {...d('D4'),replacesId:'D1'}]),/REVISIONE_ORIGINE_NON_VALIDA/);
assert.equal(store.exportMetadata(),before);
assert.throws(()=>flow.register(store,[{...d('D3'),replacesId:'D1',equipmentId:'E2'}]),/REVISIONE_APPARECCHIATURA_DIVERSA/);
assert.throws(()=>flow.register(store,[{...d('D3'),equipmentId:'E2'}]),/INTERVENTO_APPARECCHIATURA_DIVERSA/);
flow.register(store,[{...d('D3'),replacesId:'D1',version:2},d('D4','POS')]);
assert.equal(flow.summary(store.snapshot(),'S1').current,3);
assert.deepEqual(flow.check(store.snapshot()),[]);
const corrupted=store.snapshot();corrupted.documents.find(x=>x.id==='D3').version=7;
assert(flow.check(corrupted).some(x=>x.code==='VERSIONE_NON_SEQUENZIALE'));
assert.equal(core.validate(store.snapshot()),true);
