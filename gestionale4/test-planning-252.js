'use strict';
const assert=require('node:assert/strict');
const core=require('../ite-integrated-core-225.js');
const planning=require('./planning-252.js');
const ops=require('./operations-250.js');
const s=core.createStore();
core.add(s,'clients',{id:'C1',name:'Cliente TEST'});
core.add(s,'sites',{id:'S1',clientId:'C1',address:'Via Fittizia 1'});
core.add(s,'sites',{id:'S2',clientId:'C1',address:'Via Fittizia 2'});
core.add(s,'plants',{id:'P1',siteId:'S1',type:'Termico'});
core.add(s,'equipment',{id:'E1',plantId:'P1',type:'Caldaia'});
const v=(id,siteId,start,end,operator='Tecnico TEST')=>({appointmentId:'A'+id,interventionId:'I'+id,siteId,start,end,operator});
const a=v('1','S1','2026-11-25T09:00','2026-11-25T10:00');
const b=v('2','S2','2026-11-25T10:00','2026-11-25T11:00');
planning.batchSchedule(s,[{...a,equipmentId:'E1'},b]);
assert.equal(s.snapshot().appointments.length,2);
assert.equal(s.snapshot().interventions.length,2);
const reject=(fn,code)=>{const before=s.exportMetadata();assert.throws(fn,new RegExp(code));assert.equal(s.exportMetadata(),before);};
reject(()=>planning.batchSchedule(s,[v('3','S1','2026-11-25T09:30','2026-11-25T10:30')]),'OPERATORE_OCCUPATO');
reject(()=>planning.batchSchedule(s,[v('3','S1','2026-11-25T11:00','2026-11-25T12:00'),{...v('4','S2','2026-11-25T12:00','2026-11-25T13:00'),equipmentId:'E1'}]),'APPARECCHIO_SEDE_DIVERSA');
reject(()=>planning.batchSchedule(s,[v('3','S1','2026-11-25T11:00','2026-11-25T12:00'),v('3','S1','2026-11-25T12:00','2026-11-25T13:00')]),'ID_DUPLICATO');
reject(()=>planning.batchReschedule(s,[{appointmentId:'A1',operator:'Tecnico TEST',start:'2026-11-25T10:30',end:'2026-11-25T11:30'}]),'OPERATORE_OCCUPATO');
planning.batchReschedule(s,[{appointmentId:'A1',operator:'Tecnico TEST',start:'2026-11-25T10:00',end:'2026-11-25T11:00'},{appointmentId:'A2',operator:'Tecnico TEST',start:'2026-11-25T09:00',end:'2026-11-25T10:00'}]);
assert.equal(s.snapshot().interventions.find(x=>x.id==='I1').operator,'Tecnico TEST');
assert.deepEqual(planning.auditSchedule(s.snapshot()),[]);
reject(()=>planning.batchReschedule(s,[{appointmentId:'A1',operator:'Altro',start:'2026-11-25T12:00',end:'2026-11-25T13:00'},{appointmentId:'A1',operator:'Altro',start:'2026-11-25T13:00',end:'2026-11-25T14:00'}]),'APPUNTAMENTO_DUPLICATO_NEL_LOTTO');
const conflict=s.snapshot();conflict.appointments[1].start=conflict.appointments[0].start;conflict.appointments[1].end=conflict.appointments[0].end;
assert.equal(planning.auditSchedule(conflict)[0].code,'OPERATORE_OCCUPATO');
assert.equal(core.validate(s.snapshot()),true);
assert.equal(ops.siteLedger(s.snapshot(),'S1').interventions,1);
console.log('PASS 4.0.252 atomic batch schedule, multi-move, equipment site, conflict audit and rollback');
