'use strict';
const assert=require('node:assert/strict');
const core=require('../ite-integrated-core-225.js'),extras=require('./extras-244.js'),finance=require('./finance-230.js'),commercial=require('./commercial-240.js');
const store=core.createStore();
core.add(store,'clients',{id:'C1',name:'Cliente TEST'});
core.add(store,'sites',{id:'S1',clientId:'C1',address:'Sede fittizia'});
core.add(store,'quotes',{id:'Q1',clientId:'C1',status:'BOZZA',lines:[{id:'BASE-F',kind:'FORNITURA',description:'Materiale TEST',cents:10000,qty:1},{id:'BASE-P',kind:'POSA',description:'Posa TEST',cents:5000,qty:1}]});
const rev=()=>store.snapshot().revision;
extras.propose(store,{quoteId:'Q1',id:'E1',description:'Lavorazione TEST',supplyCents:2000,laborCents:3000,qty:4});
assert.equal(core.totals(store.snapshot().quotes[0]).cents,15000,'pending extra must not affect quote');
const before=rev();assert.throws(()=>extras.decide(store,'Q1','E1',5),/QUANTITA_SUPERIORE/);assert.equal(rev(),before);
extras.decide(store,'Q1','E1',2);
assert.equal(extras.summary(store.snapshot(),'Q1').quoteTotalCents,25000);
assert.equal(extras.summary(store.snapshot(),'Q1').approvedSupplyCents,4000);
assert.equal(extras.summary(store.snapshot(),'Q1').approvedLaborCents,6000);
assert.equal(store.snapshot().quotes[0].lines.filter(x=>x.kind==='EXTRA_FORNITURA').length,1);
assert.equal(store.snapshot().quotes[0].lines.filter(x=>x.kind==='EXTRA_POSA').length,1);
assert.throws(()=>extras.decide(store,'Q1','E1',2),/EXTRA_NON_IN_ATTESA/);
extras.propose(store,{quoteId:'Q1',id:'E2',description:'Rifiutato TEST',supplyCents:500, laborCents:500,qty:1});
extras.decide(store,'Q1','E2',0);
assert.equal(core.totals(store.snapshot().quotes[0]).cents,25000);
assert.equal(extras.summary(store.snapshot(),'Q1').extras[1].status,'RIFIUTATO');
assert.equal(finance.audit(store.snapshot()).ok,true);
assert.equal(commercial.reconcile(store.snapshot()).rows[0].quoted,25000);
assert.throws(()=>extras.propose(store,{quoteId:'Q1',id:'E1',description:'Duplicato',supplyCents:1,laborCents:1}),/EXTRA_DUPLICATO/);
console.log('PASS extra workflow 4.0.244: partial approval, rejection, rollback, quote and finance reconciliation');
