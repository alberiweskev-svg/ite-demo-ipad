'use strict';
const assert=require('node:assert/strict'),M=require('./ite-technical-register.js');
const h={clients:[{id:'TEST-C',sites:[{id:'TEST-S',plants:[{id:'TEST-P',devices:[{id:'TEST-D'}]}]}]}]};
const raw={id:'TEST-DICO-1',kind:'DICO_IDRICA',number:'TEST-01',date:'2026-11-04',clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',deviceId:'TEST-D'};
let s={records:[]};const original=JSON.stringify(s);
s=M.addBatch(s,[raw,{...raw,id:'TEST-POS-2',kind:'POS'}],h);
assert.equal(original,JSON.stringify({records:[]}));
assert.equal(s.records.length,2);
assert.throws(()=>M.addBatch(s,[{...raw,id:'TEST-NEW'},raw],h),/DUPLICATO/);
assert.throws(()=>M.addBatch({records:[]},[{...raw,siteId:'TEST-OTHER'}],h),/SEDE/);
assert.throws(()=>M.addBatch({records:[]},[{...raw,id:'REAL-DICO'}],h),/FITTIZI/);
s=M.attachMetadata(s,'TEST-DICO-1',{id:'TEST-A1',kind:'SCHEMA',label:'Schema fittizio'});
