assert.throws(()=>M.attachMetadata(s,'TEST-DICO-1',{id:'TEST-A2',kind:'PROVE',label:'Test'}),/RIAPRIRE/);
s=M.transition(s,'TEST-DICO-1','RIAPRI','TEST TECNICO','2026-11-04T21:05:00Z','Correzione');
