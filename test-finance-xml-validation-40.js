'use strict';
const assert=require('node:assert/strict');
const xml=require('./ite-finance-xml-40.js');
const finance=require('./ite-finance-40.js');
const batch=require('./ite-finance-batch-40.js');
const header='<FatturaElettronicaHeader><CedentePrestatore><Anagrafica><Denominazione>TEST Fornitore</Denominazione></Anagrafica></CedentePrestatore><CessionarioCommittente><Anagrafica><Denominazione>TEST ITE</Denominazione></Anagrafica></CessionarioCommittente></FatturaElettronicaHeader>';
const body=(date='2026-11-05',rate='22.00',vat='22.00')=>'<FatturaElettronicaBody><DatiGenerali><DatiGeneraliDocumento><TipoDocumento>TD01</TipoDocumento><Data>'+date+'</Data><Numero>TEST-CHECK-1</Numero><ImportoTotaleDocumento>122.00</ImportoTotaleDocumento></DatiGeneraliDocumento></DatiGenerali><DatiBeniServizi><DatiRiepilogo><AliquotaIVA>'+rate+'</AliquotaIVA><ImponibileImporto>100.00</ImponibileImporto><Imposta>'+vat+'</Imposta></DatiRiepilogo></DatiBeniServizi></FatturaElettronicaBody>';
const wrap=(h=header,b=body())=>'<FatturaElettronica>'+h+b+'</FatturaElettronica>';
const valid=xml.parse(wrap(),'TEST-CHECK-1');
assert.equal(valid.total,122);
assert.equal(valid.issuer,'ESTERNO');
const imported=batch.importBatch(finance.empty(),[valid],'DEMO','2026-11-05T13:00:00Z');
assert.equal(imported.state.documents.length,1);
assert.throws(()=>xml.parse(wrap(header+header),'TEST-CHECK-2'),/HEADER_NON_UNICO/);
assert.throws(()=>xml.parse(wrap(header,body('2026-02-30')),'TEST-CHECK-3'),/DATA_XML_NON_VALIDA/);
assert.throws(()=>xml.parse(wrap(header,body('2026-11-05','99.00')),'TEST-CHECK-4'),/IVA_XML_NON_COERENTE/);
assert.throws(()=>xml.parse(wrap(header,body('2026-11-05','-1')),'TEST-CHECK-5'),/ALIQUOTA_XML_NON_VALIDA/);
assert.throws(()=>xml.parse('garbage'+wrap(),'TEST-CHECK-6'),/NON_FATTURAPA/);
assert.throws(()=>xml.parse(wrap()+'garbage','TEST-CHECK-7'),/NON_FATTURAPA/);
assert.throws(()=>xml.parse(wrap().replace('TEST Fornitore','Fornitore Reale'),'TEST-CHECK-8'),/SOLO_DATI_TEST/);
assert.throws(()=>batch.importBatch(imported.state,[valid],'DEMO','2026-11-05T13:01:00Z'),/LOTTO_BLOCCATO/);
console.log('PASS: envelope, unique header, date, VAT, TEST-only, duplicate integration');
