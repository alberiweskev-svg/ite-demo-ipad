'use strict';
// Synthetic data only: administrative batch import safety regression.
const assert=require('node:assert/strict');
const R=require('./ite-administrative-register.js');
const I=require('./ite-administrative-intake.js');
const map=new Map();
const store={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,String(v))};
const doc=(id,type,number,party='CLIENTE FITTIZIO',originalId)=>({id,type,number,party,issued:'2026-11-02',taxable:100,vat:10,total:110,...(originalId?{originalId}:{})});
const incoming=docs=>R.exportJSON(docs.reduce((s,d)=>R.add(s,s.revision,d,'Operatore test'),R.empty()));
let initial=I.open(store).state;
const duplicateArchive=JSON.stringify({schema:1,revision:0,documents:[doc('a','VENDITA','1'),doc('b','VENDITA','1')],audit:[]});
assert.throws(()=>I.previewImport(duplicateArchive,initial),/DOCUMENTO_DUPLICATO/);
assert.throws(()=>I.importReviewed(store,duplicateArchive,0,'Operatore test',true),/DOCUMENTO_DUPLICATO/);
assert.equal(I.open(store).state.revision,0);
let preview;
preview=I.previewImport(incoming([doc('c','TD04','NC1','CLIENTE FITTIZIO','missing')]),initial);
assert.equal(preview.missingOriginals.length,1);
assert.throws(()=>I.importReviewed(store,incoming([doc('c','TD04','NC1','CLIENTE FITTIZIO','missing')]),0,'Operatore test',true),/COLLEGAMENTI_TD04_NON_VALIDI/);
preview=I.previewImport(incoming([doc('inv','VENDITA','F1'),doc('credit','TD04','NC2','ALTRA CONTROPARTE','inv')]),initial);
assert.equal(preview.invalidCredits.length,1);
assert.throws(()=>I.importReviewed(store,incoming([doc('inv','VENDITA','F1'),doc('credit','TD04','NC2','ALTRA CONTROPARTE','inv')]),0,'Operatore test',true),/COLLEGAMENTI_TD04_NON_VALIDI/);
const valid=incoming([doc('inv','VENDITA','F1'),doc('credit','TD04','NC2','CLIENTE FITTIZIO','inv')]);
preview=I.previewImport(valid,initial);
assert.equal(preview.invalidCredits.length,0);
const saved=I.importReviewed(store,valid,0,'Operatore test',true);
assert.equal(saved.revision,1);
assert.equal(saved.documents.length,2);
assert.equal(saved.documents.every(d=>!d.verified),true);
assert.equal(saved.audit.at(-1).action,'IMPORTAZIONE_REVISIONATA:2');
console.log('OK: duplicate batches, TD04 links, atomic rollback and valid reviewed import');
