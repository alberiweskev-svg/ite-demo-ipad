'use strict';
const assert=require('node:assert/strict');
const settlement=require('./ite-procurement-cumulative-settlement.js');
const reviewed={status:'confirmed',operator:'Tecnico fittizio',reviewedAt:'2026-11-01T08:00:00Z'};
const quote={id:'Q-FAKE',type:'Preventivo fornitore',supplierId:'SUP-FAKE',review:reviewed,lines:[{code:'A',qty:10,unitPrice:12.5},{code:'B',qty:2,unitPrice:5}]};
const invoice=(id,qty,price=12.5)=>({id,type:'Fattura acquisto',supplierId:'SUP-FAKE',supplierQuoteId:'Q-FAKE',review:reviewed,lines:[{code:'A',qty,unitPrice:price}]});
const snapshot=JSON.stringify([quote,invoice('F-1',4),invoice('F-2',6)]);
let r=settlement.inspect([quote,invoice('F-1',4),invoice('F-2',6)]);
assert.equal(r.valid,true);
assert.equal(r.totals.orderedCents,13500);
assert.equal(r.totals.invoicedCents,12500);
assert.equal(r.totals.invoiceCount,2);
assert.equal(r.quotes[0].rows.find(x=>x.code==='A').state,'COMPLETO');
assert.equal(r.quotes[0].rows.find(x=>x.code==='B').state,'NON_FATTURATO');
assert.equal(r.quotes[0].status,'PARZIALE');
assert.equal(JSON.stringify([quote,invoice('F-1',4),invoice('F-2',6)]),snapshot);
r=settlement.inspect([quote,invoice('F-1',8),invoice('F-2',6)]);
assert.equal(r.quotes[0].status,'DA_VERIFICARE');
assert.equal(r.totals.excessQuotes,1);
r=settlement.inspect([quote,{...invoice('F-1',2),supplierId:'OTHER'}]);
assert.equal(r.blocked,true);
assert.equal(r.totals,null);
r=settlement.inspect([quote,{...invoice('F-1',2),review:{status:'pending'}}]);
assert.equal(r.blocked,true);
r=settlement.inspect([quote,invoice('F-1',2),invoice('F-1',2)]);
assert.equal(r.blocked,true);
r=settlement.inspect([quote,{...invoice('F-1',2),supplierQuoteId:'MISSING'}]);
assert.equal(r.blocked,true);
console.log('PASS: cumulative settlement with synthetic supplier documents');
