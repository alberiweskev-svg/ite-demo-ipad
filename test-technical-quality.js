'use strict';
const assert=require('node:assert/strict');
const reg=require('./ite-technical-register.js'),q=require('./ite-technical-quality.js');
const h={clients:[{id:'TEST-C',sites:[{id:'TEST-S',plants:[{id:'TEST-P',devices:[{id:'TEST-D'}]}]}]}]};
const doc=i=>({id:'TEST-Q-'+i,kind:'DICO_IDRICA',number:'TEST-N-'+i,date:'2026-11-05',clientId:'TEST-C',siteId:'TEST-S',plantId:'TEST-P',deviceId:'TEST-D'});
let s=reg.addBatch({records:[]},[doc(1),doc(2)],h);
assert.equal(q.dashboard(s,h,reg).blocked,2);
assert(q.inspect(s.records[0],h,reg).issues.includes('ALLEGATO_MANCANTE_PROVE'));
assert.throws(()=>q.confirmBatch(s,['TEST-Q-1'],h,reg,'OPERATORE TEST','2026-11-05T02:00:00Z'),/DOCUMENTO_INCOMPLETO/);
for(const id of ['TEST-Q-1','TEST-Q-2'])for(const kind of ['SCHEMA','MATERIALI','PROVE'])s=reg.attachMetadata(s,id,{id:'TEST-'+id.slice(5)+'-'+kind,kind,label:'TEST '+kind});
assert.equal(q.dashboard(s,h,reg).ready,2);
const before=JSON.stringify(s);
const done=q.confirmBatch(s,['TEST-Q-1','TEST-Q-2'],h,reg,'OPERATORE TEST','2026-11-05T02:00:00Z');
assert.equal(done.records.filter(x=>x.status==='VERIFICATO').length,2);
assert.equal(JSON.stringify(s),before);
assert.throws(()=>q.confirmBatch(s,['TEST-Q-1','TEST-MISSING'],h,reg,'OPERATORE TEST','2026-11-05T02:00:00Z'),/DOCUMENTO_ASSENTE/);
assert.throws(()=>q.confirmBatch(s,['TEST-Q-1','TEST-Q-1'],h,reg,'OPERATORE TEST','2026-11-05T02:00:00Z'),/LOTTO_NON_VALIDO/);
const bad=JSON.parse(JSON.stringify(s));bad.records[0].link.siteId='TEST-OTHER';
assert(q.inspect(bad.records[0],h,reg).issues.includes('SEDE_NON_DEL_CLIENTE'));
console.log('ITE technical quality: OK');
