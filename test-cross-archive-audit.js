'use strict';
const assert=require('node:assert/strict');
const H=require('./ite-hierarchy-workspace.js'),A=require('./ite-atomic-workspace.js');
const D=require('./ite-document-intake.js'),X=require('./ite-cross-archive-audit.js');
let h=H.empty();
h=H.add(h,'clients',{id:'C',name:'Cliente inventato'});
h=H.add(h,'sites',{id:'S',clientId:'C',address:'Via Fittizia 1'});
h=H.add(h,'plants',{id:'P',siteId:'S'});
const state=A.wrap?A.wrap(A.empty(),0):A.parse(JSON.stringify({format:'ITE40_ATOMIC',version:1,revision:0,data:A.empty()}));
let docs=D.add(D.empty(),{id:'D1',filename:'dico_fittizia.pdf',type:'DICO_IDRICO',status:'DA_VERIFICARE',addedAt:'2026-11-03',clientId:'C',siteId:'S',notes:''});
const snap={...state,data:{...state.data,hierarchy:h}};
assert.equal(X.audit(snap,docs,[{documentId:'D1',plantId:'P'}]).ok,true);
const bad=D.update(docs,'D1',{siteId:'MISSING'});
const report=X.audit(snap,bad,[{documentId:'D1',plantId:'P'}]);
assert.equal(report.ok,false);
assert(report.issues.some(x=>x.code==='SEDE_CLIENTE_INCOERENTE'));
assert(report.issues.some(x=>x.code==='SEDE_DOCUMENTO_OBBLIGATORIA'||x.code==='SEDE_RIFERIMENTO_INCOERENTE'||x.code==='SEDE_CLIENTE_INCOERENTE'));
const storage=new Map([[A.KEY,JSON.stringify(snap)],['docs',D.exportJSON(docs)],['links',JSON.stringify([{documentId:'D1',plantId:'P'}])]]);
const store={getItem:k=>storage.has(k)?storage.get(k):null};
const bundle=X.capture(store,'docs','links');
assert.equal(X.parse(X.exportJSON(bundle)).report.ok,true);
assert.throws(()=>X.parse(X.exportJSON(bundle).replace('"revision": 0','"revision": 99')),/RIEPILOGO_NON_COHERENTE/);
assert.equal(storage.size,3);
console.log('PASS: cross-archive audit, inconsistent links, export integrity, read-only capture');
