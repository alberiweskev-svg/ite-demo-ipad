'use strict';
const assert=require('node:assert/strict'),H=require('./ite-hierarchy-workspace.js'),C=require('./ite-commerce.js');
let h=H.add(H.empty(),'clients',{id:'c',name:'Cliente demo'});h=H.add(h,'sites',{id:'s',clientId:'c',address:'Via Fittizia'});
let d=C.createQuote(C.empty(),h,{id:'q',clientId:'c',siteId:'s',paymentTerms:'40-40-20'});
d=C.addLine(d,h,'q',{id:'l1',type:'FORNITURA',category:'idrico',description:'Rubinetto',quantityMilli:1000,unitCents:10000,vatRate:10,origin:'BASE'});
d=C.addLine(d,h,'q',{id:'l2',type:'POSA',category:'idrico',description:'Installazione',quantityMilli:1500,unitCents:5000,vatRate:22,origin:'EXTRA'});
assert.deepEqual(C.totals(d.quotes[0]),{netCents:17500,vatCents:2650,totalCents:20150});
assert.equal(C.totals(d.quotes[0],{approvedOnly:true}).totalCents,11000);
assert.throws(()=>C.setQuoteStatus(d,h,'q','ACCETTATO'),/EXTRA_DA_DECIDERE/);
d=C.approveExtra(d,h,'q',['l2'],'APPROVATO');d=C.setQuoteStatus(d,h,'q','ACCETTATO');
assert.equal(d.quotes[0].status,'ACCETTATO');
assert.throws(()=>C.addLine(d,h,'q',{id:'x'}),/RIGA_NON_AGGIUNGIBILE/);
d=C.addInvoice(d,h,{id:'f1',direction:'ACQUISTO',kind:'TD04',number:'NC-1',netCents:10000,vatCents:2200,totalCents:12200});
assert.equal(d.invoices[0].status,'DA_RECUPERARE');
assert.throws(()=>C.setInvoiceStatus(d,h,'f1','PAGATA'),/STATO_NOTA_CREDITO_NON_VALIDO/);
d=C.setInvoiceStatus(d,h,'f1','RECUPERATA');
assert.deepEqual(C.classify({type:'PR',issuedByITE:true}),{kind:'PROFORMA',direction:'VENDITA',requiresReview:false});
assert.equal(C.classify({type:'TD04'}).requiresReview,true);
const store=new Map(),storage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v)};
C.save(storage,d,h);assert.equal(C.load(storage,h).invoices[0].status,'RECUPERATA');
assert.ok(store.has(C.KEY+'_previous'));
assert.throws(()=>C.createQuote(d,h,{id:'bad',clientId:'nonexistent'}),/CLIENTE_NON_TROVATO/);
