'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const op=require('./ite-operations-40.js'),tech=require('./ite-technical-registry-40.js');
const now='2026-11-05T15:00:00.000Z';
let state=op.empty();
state=op.addClient(state,{id:'TEST-CLIENTE',name:'Cliente dimostrativo'},'TEST-OP',now);
state=op.addSite(state,'TEST-CLIENTE',{id:'TEST-SEDE',address:'Via Test 1'},'TEST-OP',now);
state=op.addPlant(state,'TEST-CLIENTE','TEST-SEDE',{id:'TEST-IMPIANTO',type:'Riscaldamento'},'TEST-OP',now);
state=op.addDevice(state,{clientId:'TEST-CLIENTE',siteId:'TEST-SEDE',plantId:'TEST-IMPIANTO'},{id:'TEST-APP',brand:'TEST',model:'Demo',serial:'TEST-01'},'TEST-OP',now);
let reg=tech.create(tech.empty(),state,{id:'TEST-DOC',clientId:'TEST-CLIENTE',siteId:'TEST-SEDE',plantId:'TEST-IMPIANTO',deviceId:'TEST-APP',type:'DIRI',title:'Di.Ri. dimostrativa'},'TEST-OP',now);
assert.equal(tech.forClient(reg,'TEST-CLIENTE').length,1);
reg=tech.update(reg,state,'TEST-DOC',{status:'DA_VERIFICARE'},'TEST-OP',now);
reg=tech.update(reg,state,'TEST-DOC',{status:'VERIFICATO'},'TEST-OP',now);
reg=tech.update(reg,state,'TEST-DOC',{status:'ARCHIVIATO'},'TEST-OP',now);
assert.equal(reg.documents[0].revision,4);
assert.throws(()=>tech.update(reg,state,'TEST-DOC',{title:'Non permesso'},'TEST-OP',now),/ARCHIVIATO/);
assert.equal(tech.restore(tech.backup(reg,state),state).documents[0].status,'ARCHIVIATO');
const html=fs.readFileSync('index.html','utf8');
assert.match(html,/ite-technical-registry-40\.js/);
assert.match(html,/ite-technical-registry-ui-40\.js/);
assert.ok(html.indexOf('ite-technical-registry-40.js')<html.indexOf('ite-technical-registry-ui-40.js'));
const ui=fs.readFileSync('ite-technical-registry-ui-40.js','utf8');
assert.match(ui,/tech\.create\(/);assert.match(ui,/tech\.update\(/);
assert.doesNotMatch(ui,/FileReader|readAsDataURL|\.base64\s*=/);
console.log('Technical UI integration TEST: OK');
