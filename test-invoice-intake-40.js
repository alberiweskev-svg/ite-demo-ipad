const assert=require("node:assert/strict");
const ledger=require("./ite-invoice-ledger-40.js"), intake=require("./ite-invoice-intake-40.js");
const lines=[{quantity:2,unitPrice:50,vat:10}];
const make=(id,extra={})=>({id,number:"PR-72",party:"Soggetto TEST",issuer:"Fornitore TEST",date:"2026-11-07",lines,expectedTotal:110,...extra});
const records=[make("TEST-PR-1"),make("TEST-PR-2",{documentCode:"TD04",number:"NC-2"}),make("TEST-PR-3",{issuer:"I.T.E. DI MERKAJ ALBAN",number:"F-3"}),make("TEST-PR-4",{issuer:"",number:"F-4"}),make("TEST-PR-1")];
const review=intake.inspect(ledger.empty(),records);
assert.deepEqual(review.map(r=>r.status),["READY","READY","READY","REVIEW","REVIEW"]);
assert.deepEqual(review.slice(0,3).map(r=>r.type),["PROFORMA","CREDIT_NOTE","SALE"]);
assert.throws(()=>intake.apply(ledger.empty(),records,[3]),/non approvabile/);
assert.throws(()=>intake.apply(ledger.empty(),records,[0,0]),/duplicate/);
let db=intake.apply(ledger.empty(),records,[0,1,2]);
assert.equal(db.documents.length,3);
assert.equal(intake.reconcile(db).creditsToRecover,110);
assert.equal(intake.reconcile(db).proformas,110);
db=ledger.payment(db,"TEST-PR-2",40,"2026-11-07");
assert.equal(intake.reconcile(db).creditsToRecover,70);
assert.equal(intake.reconcile(db).byType.CREDIT_NOTE.remaining,70);
assert.equal(intake.inspect(db,[make("TEST-PR-1")])[0].status,"REVIEW");
assert.equal(intake.inspect(ledger.empty(),[make("TEST-BAD",{expectedTotal:999})])[0].status,"REVIEW");
assert.equal(intake.inspect(ledger.empty(),[make("TEST-BAD",{lines:[{quantity:1,unitPrice:2,vat:21}]})])[0].status,"REVIEW");
assert.throws(()=>intake.inspect(db,new Array(201).fill(null)),/200/);
console.log("ITE 4.0.53 intake: classification, duplicate detection, manual approval, TD04 reconciliation PASS");

const planDb=ledger.empty();
const planRows=[make("TEST-PLAN-01",{number:"F-01",issuer:"I.T.E. DI MERKAJ ALBAN"}),make("TEST-PLAN-02",{number:"PR-02"}),make("TEST-PLAN-03",{issuer:"",number:"F-03"})];
const plan=intake.plan(planDb,planRows,[0,1]);
assert.equal(plan.totals.count,2);
assert.equal(plan.totals.taxable,100);
assert.equal(plan.totals.vat,10);
assert.equal(plan.totals.total,110*2);
assert.equal(plan.reviewCount,1);
assert.throws(()=>intake.plan(planDb,planRows,[2]),/non selezionabile/);
assert.throws(()=>intake.plan(planDb,planRows,[0,0]),/duplicata/);
assert.throws(()=>intake.plan(planDb,planRows,[99]),/non selezionabile/);
assert.throws(()=>intake.apply(planDb,planRows,[]),/Nessun documento/);
const onlyOne=intake.apply(planDb,planRows,[1]);
assert.equal(onlyOne.documents.length,1);
assert.equal(onlyOne.documents[0].id,"TEST-PLAN-02");
assert.equal(planDb.documents.length,0);
console.log("ITE 4.0.54 batch selection and totals PASS");
