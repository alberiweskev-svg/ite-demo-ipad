"use strict";
const assert=require("node:assert/strict");
const D=require("./ite-document-register-164.js");
const own="03857941201";
const base={number:"PR-TEST-01",date:"2026-11-11",issuerVat:"TEST-SUPPLIER",recipientVat:own,net:100,vat:22,total:122};
const first=D.add(D.init(),base,own,"Tecnico TEST",0);
assert.equal(first.record.kind,"PROFORMA");
assert.equal(first.record.direction,"ACQUISTO");
assert.equal(first.record.reviewStatus,"DA_VERIFICARE");
assert.equal(first.state.revision,1);
assert.throws(()=>D.add(first.state,base,own,"TEST",1),/DOCUMENTO_DUPLICATO/);
assert.throws(()=>D.add(first.state,{...base,number:"X",total:120},own,"TEST",1),/TOTALI_NON_COERENTI/);
assert.throws(()=>D.add(first.state,{...base,number:"X"},own,"TEST",0),/REVISIONE_OBSOLETA/);
const checked=D.review(first.state,first.record.id,"CONFERMATO","TEST",1);
assert.equal(checked.documents[0].reviewStatus,"CONFERMATO");
assert.equal(first.state.documents[0].reviewStatus,"DA_VERIFICARE");
const td=D.add(checked,{...base,type:"TD04",number:"NC-TEST-02",issuerVat:own,net:50,vat:11,total:61},own,"TEST",2);
assert.equal(td.record.kind,"NOTA_CREDITO");
assert.equal(td.record.direction,"VENDITA");
assert.equal(td.record.paymentStatus,"DA_RECUPERARE");
const part=D.recover(td.state,td.record.id,20,"TEST",3);
assert.equal(part.documents[1].paymentStatus,"PARZIALMENTE_RECUPERATA");
const full=D.recover(part,td.record.id,41,"TEST",4);
assert.equal(full.documents[1].paymentStatus,"RECUPERATA");
assert.throws(()=>D.recover(full,td.record.id,1,"TEST",5),/RECUPERO_NON_VALIDO/);
assert.equal(td.state.documents[1].recovered,0);
assert.equal(D.classify({...base,issuerVat:""},own).direction,"DA_VERIFICARE");
assert.equal(full.events.length,5);
console.log("Document register 4.0.164: PASS");
