'use strict';
const assert=require('node:assert/strict');
const staging=require('./ite-procurement-pdf-staging.js');
const review=require('./ite-procurement-review.js');
const bridge=require('./ite-procurement-document-bridge.js');
const reconcile=require('./ite-core-reconciliation.js');
const core={clienti:[],immobili:[],impianti:[],apparecchiature:[]};
const q=staging.stage({id:'Q-DEMO',type:'Preventivo fornitore',supplierId:'S-DEMO',text:'A-1 | 2 | 10,00\nB-2 | 1 | 20,00'});
const i=staging.stage({id:'F-DEMO',type:'Fattura acquisto',supplierId:'S-DEMO',text:'A-1 | 3 | 12,00\nB-2 | 1 | 20,00'});
assert.equal(q.document.lines.length,2);
assert.equal(q.document.lines[0].unitPrice,10);
assert.equal(bridge.extract({documents:[q.document,i.document]}).quotes.length,0);
const timestamp='2026-11-01T09:00:00+01:00';
const quote=review.review(q.document,'OPERATORE-DEMO',timestamp);
const invoice={...review.review(i.document,'OPERATORE-DEMO',timestamp),supplierQuoteId:'Q-DEMO'};
const merged=bridge.merge({documents:[quote,invoice]});
assert.equal(merged.quotes.length,1);
assert.equal(merged.invoices.length,1);
const report=reconcile.inspect(core,{documents:[quote,invoice]});
assert.equal(report.supplierQuantityAudit[0].status,'DIFFERENZE');
assert.ok(report.supplierQuantityAudit[0].differences.some(x=>x.kind==='QUANTITA_AUMENTATA'));
assert.ok(report.supplierQuantityAudit[0].differences.some(x=>x.kind==='PREZZO_AUMENTATO'));
assert.equal(report.readOnly,true);
assert.equal(i.document.review.status,'pending');
const malformed=staging.stage({id:'BAD',type:'Fattura acquisto',supplierId:'S-DEMO',text:'X | 0 | 5\nY | 1 | -3'});
assert.equal(malformed.document.lines.length,0);
assert.ok(malformed.rejected.length===2);
assert.throws(()=>review.review(malformed.document,'OPERATORE-DEMO',timestamp));
console.log('PDF staging -> review -> bridge -> quantity audit: synthetic integration passed');
