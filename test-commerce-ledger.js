'use strict';
const assert=require('node:assert/strict');
const C=require('./ite-commerce.js'),L=require('./ite-commerce-ledger.js');
let c=C.empty();
c=C.createQuote(c,null,{id:'Q-1',clientId:'FAKE-CLIENT'});
c=C.addLine(c,null,'Q-1',{id:'L-1',type:'FORNITURA',category:'idrico',description:'Prodotto di prova',quantityMilli:1000,unitCents:10000,vatRate:10,origin:'BASE'});
c=C.setQuoteStatus(c,null,'Q-1','ACCETTATO');
c=C.addInvoice(c,null,{id:'F-1',direction:'VENDITA',kind:'FATTURA',number:'TEST-1',date:'2026-11-04',counterparty:'Cliente fittizio',netCents:10000,vatCents:1000,totalCents:11000});
c=C.addInvoice(c,null,{id:'NC-1',direction:'ACQUISTO',kind:'TD04',number:'TEST-NC',date:'2026-11-04',counterparty:'Fornitore fittizio',netCents:2000,vatCents:440,totalCents:2440});
let l=L.link(L.empty(),c,'F-1','Q-1');
assert.equal(L.summary(l,c)[0].quoteId,'Q-1');
let a=L.record(l,c,{id:'P-1',invoiceId:'F-1',amountCents:4000,date:'2026-11-04',method:'BONIFICO'});l=a.ledger;
assert.equal(a.status,'PARZIALE');assert.equal(a.remainingCents,7000);
assert.equal(L.summary(l,c,{asOf:'2026-11-03'})[0].status,'DA_PAGARE');
a=L.record(l,c,{id:'P-2',invoiceId:'F-1',amountCents:7000,date:'2026-11-05',method:'POS'});l=a.ledger;
assert.equal(a.status,'PAGATA');
assert.throws(()=>L.record(l,c,{id:'P-3',invoiceId:'F-1',amountCents:1,date:'2026-11-06',method:'POS'}),/IMPORTO_SUPERIORE/);
assert.throws(()=>L.link(l,c,'F-1','Q-1'),/GIA_COLLEGATO/);
a=L.record(l,c,{id:'R-1',invoiceId:'NC-1',amountCents:1000,date:'2026-11-04',method:'BONIFICO'});l=a.ledger;
assert.equal(a.status,'PARZIALMENTE_RECUPERATA');
a=L.record(l,c,{id:'R-2',invoiceId:'NC-1',amountCents:1440,date:'2026-11-05',method:'BONIFICO'});l=a.ledger;
assert.equal(a.status,'RECUPERATA');
const data=new Map();const storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};
L.save(storage,l,c);assert.deepEqual(L.load(storage,c),l);
assert.ok(data.has(L.KEY+'_previous'));
assert.throws(()=>L.record(l,c,{id:'bad',invoiceId:'F-1',amountCents:1,date:'2026-02-30',method:'POS'}),/MOVIMENTO_NON_VALIDO/);
console.log('Commerce ledger: all synthetic tests passed');
