const assert=require("node:assert/strict");
const q=require("./ite-quotes-40.js"),i=require("./ite-invoice-ledger-40.js"),s=require("./ite-contract-settlement-40.js");
const d="2026-11-07";
let quotes=q.create(q.empty(),{id:"TEST-Q-59",customer:"Cliente fittizio",date:d});
quotes=q.addLine(quotes,"TEST-Q-59",{id:"TEST-S-59",kind:"SUPPLY",description:"Fornitura fittizia",quantity:1,unitPrice:100,vat:10});
quotes=q.addLine(quotes,"TEST-Q-59",{id:"TEST-P-59",kind:"INSTALLATION",description:"Posa fittizia",quantity:1,unitPrice:100,vat:10});
quotes=q.setStatus(q.setStatus(quotes,"TEST-Q-59","SENT"),"TEST-Q-59","ACCEPTED");
let ledger=i.empty();
ledger=i.add(ledger,{id:"TEST-I-59A",type:"SALE",number:"AC-1",party:"Cliente fittizio",date:d,lines:[{quantity:1,unitPrice:50,vat:10}]});
ledger=i.add(ledger,{id:"TEST-I-59B",type:"SALE",number:"SAL-1",party:"Cliente fittizio",date:d,lines:[{quantity:1,unitPrice:150,vat:10}]});
let links=s.empty();
assert.equal(s.report(links,quotes,ledger,"TEST-Q-59").remainingToInvoice,220);
const first=s.link(links,quotes,ledger,"TEST-Q-59","TEST-I-59A","ADVANCE");
links=first.archive;
assert.equal(first.report.billed,55);
assert.equal(first.report.remainingToInvoice,165);
assert.equal(s.empty().links.length,0);
ledger=i.payment(ledger,"TEST-I-59A",20,d);
assert.equal(s.report(links,quotes,ledger,"TEST-Q-59").paid,20);
assert.equal(s.report(links,quotes,ledger,"TEST-Q-59").unpaid,35);
links=s.link(links,quotes,ledger,"TEST-Q-59","TEST-I-59B","BALANCE").archive;
assert.equal(s.report(links,quotes,ledger,"TEST-Q-59").remainingToInvoice,0);
assert.throws(()=>s.link(links,quotes,ledger,"TEST-Q-59","TEST-I-59B","BALANCE"),/già collegata/);
assert.deepEqual(s.importJson(s.exportJson(links,quotes,ledger),quotes,ledger),links);
const altered=JSON.parse(JSON.stringify(links));altered.links[0].invoiceId="TEST-MISSING";
