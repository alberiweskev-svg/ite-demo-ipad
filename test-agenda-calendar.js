'use strict';
const assert=require('node:assert/strict');
const C=require('./ite-agenda-calendar.js'),A=require('./ite-field-agenda.js');
const m={clients:[{id:'demo-c'}],sites:[{id:'demo-s',clientId:'demo-c'}],systems:[{id:'demo-i',siteId:'demo-s'}],equipment:[{id:'demo-e',systemId:'demo-i'}],operators:[{id:'demo-t1'},{id:'demo-t2'}]};
const p={id:'demo-a',clientId:'demo-c',siteId:'demo-s',systemId:'demo-i',equipmentId:'demo-e',operatorId:'demo-t1',kind:'MANUTENZIONE',startsAt:'2026-11-04T08:00:00Z',endsAt:'2026-11-04T09:00:00Z'};
let s=A.schedule({appointments:[]},m,p);
assert.equal(C.calendar(s,'2026-11-04','day').entries.length,1);
assert.equal(C.calendar(s,'2026-11-04','week').entries.length,1);
assert.equal(C.calendar(s,'2026-11-04','month').entries.length,1);
assert.equal(C.calendar(s,'2026-11-04','day','demo-t2').entries.length,0);
assert.equal(C.range('2026-11-04','week').from,'2026-11-02');
assert.equal(C.range('2026-11-04','month').to,'2026-12-01');
assert.equal(C.addDays('2026-12-31',1),'2027-01-01');
assert.throws(()=>C.range('2026-02-30','day'),/GIORNO_NON_VALIDO/);
s=A.transition(s,p.id,'arrive','demo-t1','2026-11-04T08:01:00Z');
s=A.transition(s,p.id,'addExtra','demo-t1','2026-11-04T08:05:00Z',{extra:{id:'extra-1',description:'Lavabo',category:'IDRICO',lines:[{type:'FORNITURA',description:'Lavabo',quantity:2,unitCents:10000},{type:'POSA',description:'Posa lavabo',quantity:1,unitCents:8000}]}});
assert.equal(C.extraTotals(s.appointments[0]).proposedCents,28000);
s=A.transition(s,p.id,'approveLines','demo-t1','2026-11-04T08:10:00Z',{extraId:'extra-1',quantities:[1,1]});
assert.equal(C.extraTotals(s.appointments[0]).acceptedCents,18000);
assert.equal(s.appointments[0].extraWorks[0].status,'parzialmente_accettato');
assert.deepEqual(C.validateDemo(s),s);
assert.throws(()=>C.validateDemo({appointments:[{...s.appointments[0],clientId:'real-client'}]}),/DATI_NON_DIMOSTRATIVI/);
const frozen=JSON.stringify(s);C.calendar(s,'2026-11-04','month');assert.equal(JSON.stringify(s),frozen);
console.log('PASS: calendar day/week/month, filters, dates, extras partial approval, demo-only archive');
