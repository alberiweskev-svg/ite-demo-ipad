'use strict';
const assert=require('node:assert/strict');
const workspace=require('./ite-procurement-review-workspace.js');
const bridge=require('./ite-procurement-document-bridge.js');
const reconcile=require('./ite-core-reconciliation.js');
const core={clienti:[],immobili:[],impianti:[],apparecchiature:[]};
const base={id:'Q-FAKE',supplierId:'S-FAKE',type:'Preventivo fornitore',text:'A | 2 | 10,00 | 20,00\nB | 0 | 4,00'};
const prepared=workspace.prepare(base);
assert.equal(prepared.document.lines.length,1);
assert.equal(prepared.rejected.length,1);
assert.equal(prepared.ready,false);
assert.throws(()=>workspace.confirm(prepared,'TECNICO-FAKE','2026-11-01T10:00:00Z'));
const corrected=workspace.correct(prepared,workspace.parseManual('A | 2 | 10,00\nB | 1 | 4,00'));
assert.equal(corrected.ready,true);
assert.equal(prepared.document.lines.length,1);
const quote=workspace.confirm(corrected,'TECNICO-FAKE','2026-11-01T10:00:00Z');
assert.equal(quote.review.status,'confirmed');
assert.equal(bridge.extract({documents:[quote]}).quotes.length,1);
assert.equal(bridge.extract({documents:[prepared.document]}).quotes.length,0);
assert.throws(()=>workspace.parseManual('A | 2'));
assert.equal(workspace.correct(prepared,[{code:'A',qty:0,unitPrice:1}]).ready,false);
const invoicePrepared=workspace.prepare({...base,id:'F-FAKE',type:'Fattura acquisto',text:'A | 3 | 11,00\nB | 1 | 4,00'});
const invoice={...workspace.confirm(workspace.correct(invoicePrepared,invoicePrepared.document.lines),'TECNICO-FAKE','2026-11-01T10:00:00Z'),supplierQuoteId:quote.id};
const report=reconcile.inspect(core,{documents:[quote,invoice]});
assert.equal(report.supplierQuantityAudit[0].status,'DIFFERENZE');
assert.equal(report.supplierAudit[0].status,'DIFFERENZE');
assert.equal(invoicePrepared.document.review.status,'pending');
console.log('Supplier review workspace: synthetic validation, confirmation and reconciliation passed');
