'use strict';
const assert=require('node:assert/strict'),A=require('./ite-field-agenda.js'),D=require('./ite-agenda-dispatch.js');
const master={clients:[{id:'demo-c'}],sites:[{id:'demo-s',clientId:'demo-c'}],systems:[{id:'demo-i',siteId:'demo-s'}],equipment:[{id:'demo-e',systemId:'demo-i'}],operators:[{id:'demo-t1'},{id:'demo-t2'}]};
const p=(id,operatorId,start,end)=>({id,clientId:'demo-c',siteId:'demo-s',systemId:'demo-i',equipmentId:'demo-e',operatorId,kind:'MANUTENZIONE',startsAt:start,endsAt:end});
const t='2026-11-04T07:00:00Z';
let s=A.schedule({appointments:[]},master,p('demo-1','demo-t1','2026-11-05T08:00:00Z','2026-11-05T09:00:00Z'));
s=A.schedule(s,master,p('demo-2','demo-t2','2026-11-05T08:00:00Z','2026-11-05T09:00:00Z'));
const frozen=JSON.stringify(s);
assert.throws(()=>D.dispatch(s,master,'demo-1',{action:'reassign',operatorId:'demo-t2'},'demo-t1',t),/OPERATORE_OCCUPATO/);
assert.equal(JSON.stringify(s),frozen);
let n=D.dispatch(s,master,'demo-1',{action:'reschedule',startsAt:'2026-11-05T10:00:00Z',endsAt:'2026-11-05T11:00:00Z'},'demo-t1',t);
n=D.dispatch(n,master,'demo-1',{action:'reassign',operatorId:'demo-t2'},'demo-t1',t);
assert.equal(n.appointments[0].operatorId,'demo-t2');
assert.equal(n.appointments[0].audit.at(-1).event,'REASSIGNED');
assert.equal(D.workload(n,master,'2026-11-05T00:00:00Z','2026-11-06T00:00:00Z').find(x=>x.operatorId==='demo-t2').scheduledMinutes,120);
assert.throws(()=>D.dispatch(n,master,'demo-1',{action:'cancel'},'demo-t2',t),/MOTIVO_OBBLIGATORIO/);
n=D.dispatch(n,master,'demo-1',{action:'cancel',reason:'Prova'},'demo-t2',t);
assert.equal(n.appointments[0].status,'cancelled');
assert.equal(D.workload(n,master,'2026-11-05T00:00:00Z','2026-11-06T00:00:00Z').find(x=>x.operatorId==='demo-t2').scheduledMinutes,60);
assert.throws(()=>D.batch(s,master,[{id:'demo-1',change:{action:'cancel',reason:'Test'},actor:'demo-t1',at:t},{id:'missing',change:{action:'cancel',reason:'Test'},actor:'demo-t1',at:t}]),/APPUNTAMENTO_INESISTENTE/);
assert.equal(JSON.stringify(s),frozen);
console.log('PASS: dispatch, collisioni, riassegnazione, audit, annullamento, carico, batch atomico');
