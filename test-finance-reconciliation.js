'use strict';
const assert=require('node:assert/strict'),R=require('./ite-finance-reconciliation.js');
const fresh=()=>({documents:[{id:'F-1',kind:'FATTURA',direction:'VENDITA',totalCents:12000,reviewed:true},{id:'PR-1',kind:'PROFORMA',direction:'VENDITA',totalCents:9000,reviewed:true},{id:'NC-1',kind:'NOTA_CREDITO',direction:'ACQUISTO',totalCents:3000,recoveredCents:0,reviewed:true}],movements:[]});
let s=fresh();s=R.register(s,{id:'B-1',date:'2026-11-04',amountCents:7000,reference:'TEST-001',direction:'ENTRATA'});
s=R.register(s,{id:'B-2',date:'2026-11-04',amountCents:5000,reference:'TEST-002',direction:'ENTRATA'});
s=R.match(s,'B-1','F-1','TECNICO TEST','2026-11-04T12:00:00Z');
assert.equal(R.overview(s)[0].status,'PARZIALE');
s=R.match(s,'B-2','F-1','TECNICO TEST','2026-11-04T12:01:00Z');
assert.equal(R.overview(s)[0].status,'SALDATO');
assert.equal(R.overview(s)[1].status,'NON_RICONCILIABILE');
const original=JSON.stringify(s);
assert.throws(()=>R.match(s,'B-1','PR-1','TEST','2026-11-04T12:02:00Z'));
assert.equal(JSON.stringify(s),original);
s=R.unmatch(s,'B-2','TECNICO TEST','2026-11-04T12:03:00Z','correzione');
assert.equal(R.overview(s)[0].remainingCents,5000);
assert.equal(s.reconciliationHistory.length,3);
const old=JSON.stringify(s);
assert.throws(()=>R.batch(s,[{action:'REGISTER',movement:{id:'B-3',date:'2026-11-04',amountCents:100,reference:'TEST-003',direction:'ENTRATA'}},{action:'MATCH',movementId:'B-3',documentId:'PR-1',operator:'TEST',at:'2026-11-04T12:04:00Z'}]));
assert.equal(JSON.stringify(s),old);
assert.throws(()=>R.register(s,{id:'B-3',date:'2026-02-30',amountCents:1,reference:'TEST',direction:'ENTRATA'}));
console.log('ITE finance reconciliation: OK');
