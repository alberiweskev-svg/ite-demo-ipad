"use strict";
const assert=require("node:assert/strict");
const I=require("./ite-inventory-154.js"),P=require("./ite-partial-dispatch-159.js");
let s={schema:"ITE_OPERATIONS_123",revision:0,events:[],commercial:{estimates:[{id:"P-TEST",status:"ACCETTATO",siteId:"SEDE-FITTIZIA",lines:[{id:"L1",kind:"FORNITURA",quantity:5},{id:"L2",kind:"FORNITURA",quantity:2}]}]},inventory:{items:[],movements:[],reservations:[]}};
s=I.item(s,{id:"A",code:"A-TEST",description:"Articolo fittizio",unitPrice:10,vatRate:10},"TEST",s.revision);
s=I.movement(s,{id:"IN-TEST",itemId:"A",direction:"IN",quantity:7},"TEST",s.revision);
s=I.reserve(s,{id:"R1",estimateId:"P-TEST",itemId:"A",quantity:5},"TEST",s.revision);
s=I.reserve(s,{id:"R2",estimateId:"P-TEST",itemId:"A",quantity:2},"TEST",s.revision);
s.inventory.reservations[0].lineId="L1";s.inventory.reservations[1].lineId="L2";
assert.equal(P.inspect(s,"P-TEST",[{reservationId:"R1",quantity:2}]).rows[0].remaining,3);
assert.throws(()=>P.inspect(s,"P-TEST",[{reservationId:"R1",quantity:6}]),/QUANTITA_SUPERA_PRENOTAZIONE/);
assert.throws(()=>P.inspect(s,"P-TEST",[{reservationId:"R1",quantity:1},{reservationId:"R1",quantity:1}]),/PRENOTAZIONE_DUPLICATA/);
assert.throws(()=>P.dispatch(s,"P-TEST",[{reservationId:"R1",quantity:2}],"TEST",s.revision-1,"LOTTO"),/REVISIONE_OBSOLETA/);
const before=JSON.stringify(s);
let n=P.dispatch(s,"P-TEST",[{reservationId:"R1",quantity:2},{reservationId:"R2",quantity:2}],"TEST",s.revision,"LOTTO-TEST");
assert.equal(JSON.stringify(s),before);
assert.equal(I.overview(n).items[0].onHand,3);
assert.equal(I.overview(n).items[0].reserved,3);
assert.equal(n.inventory.reservations.find(r=>r.id==="R1").quantity,3);
assert.equal(P.report(n,"P-TEST").dispatched.length,2);
assert.equal(n.inventory.movements.at(-1).siteId,"SEDE-FITTIZIA");
assert.throws(()=>P.dispatch(n,"P-TEST",[{reservationId:"R1",quantity:1}],"TEST",n.revision,"LOTTO-TEST"),/LOTTO_DUPLICATO/);
n=P.dispatch(n,"P-TEST",[{reservationId:"R1",quantity:3}],"TEST",n.revision,"LOTTO-TEST-2");
assert.equal(I.overview(n).items[0].onHand,0);
assert.equal(I.overview(n).items[0].reserved,0);
assert.equal(P.report(n,"P-TEST").dispatched.length,3);
console.log("4.0.159 partial dispatch tests passed");
