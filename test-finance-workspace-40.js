"use strict";
const assert=require("node:assert/strict"),W=require("./ite-finance-workspace-40.js");
const invoice={id:"TEST-INV-1",partyId:"TEST-CLIENT-1",appointmentId:"TEST-APP-1",direction:"VENDITA",td:"TD01",number:"1",net:100,tax:10,total:110,paid:40};
const credit={...invoice,id:"TEST-CREDIT-1",td:"TD04",number:"2",net:20,tax:2,total:22,paid:0};
const proforma={...invoice,id:"TEST-PR-1",number:"PR-72",net:30,tax:3,total:33,paid:0};
const a={documents:[invoice,credit,proforma],links:[invoice,credit,proforma].map(d=>({appointmentId:"TEST-APP-1",documentId:d.id})),recoveries:[]};
assert.equal(W.report(a).summaries[0].balanceCents,4800);
assert.equal(W.report(a).credits[0].status,"DA_RECUPERARE");
const b=W.addRecovery(a,{id:"TEST-REC-1",documentId:credit.id,direction:"COMPENSAZIONE",amount:10});
assert.equal(W.report(b).credits[0].status,"PARZIALMENTE_RECUPERATA");
const c=W.addRecovery(b,{id:"TEST-REC-2",documentId:credit.id,direction:"INCASSO",amount:12});
assert.equal(W.report(c).credits[0].status,"RECUPERATA");
assert.equal(a.recoveries.length,0);
assert.equal(W.report(W.importJSON(W.exportJSON(c))).credits[0].residualCents,0);
assert.throws(()=>W.addRecovery(c,{id:"TEST-REC-3",documentId:credit.id,direction:"INCASSO",amount:1}),/superiori/);
assert.throws(()=>W.addRecovery(a,{id:"TEST-REC-3",documentId:invoice.id,direction:"INCASSO",amount:1}),/TD04/);
assert.throws(()=>W.report({...a,documents:[...a.documents,invoice]}),/duplicato/);
assert.throws(()=>W.report({...a,links:[...a.links,a.links[0]]}),/duplicato/);
assert.throws(()=>W.report({...a,recoveries:[{id:"TEST-REC-3",documentId:credit.id,direction:"INCASSO",amount:0}]}),/nullo/);
assert.throws(()=>W.importJSON('{"schema":"UNKNOWN","documents":[],"links":[],"recoveries":[]}'),/Schema/);
console.log("11 finance workspace assertions passed");