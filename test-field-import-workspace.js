'use strict';
const assert=require('node:assert/strict');
const adapter=require('./ite-field-legacy-adapter.js'),planning=require('./ite-field-planning.js'),report=require('./ite-field-operations-report.js');
const source={clienti:[{id:'C1',name:'Cliente fittizio'}],immobili:[{id:'S1',client_id:'C1',indirizzo:'Via Prova 1'}],impianti:[{id:'I1',immobile_id:'S1'}],apparecchiature:[{id:'E1',impianto_id:'I1'}],operatori:[{id:'O1',nome:'Operatore fittizio',active:true}],appuntamenti:[]};
const original=JSON.stringify(source),a=adapter.adapt(source);
assert.equal(a.issues.length,0);assert.equal(a.catalog.equipment.length,1);
const item={id:'A1',clientId:'C1',siteId:'S1',systemId:'I1',equipmentId:'E1',operatorId:'O1',kind:'manutenzione',startsAt:'2026-11-02T09:00:00+01:00',endsAt:'2026-11-02T10:00:00+01:00'};
const list=planning.schedule(a.catalog,[],item);
const imported=adapter.adapt({...source,appuntamenti:list});
assert.equal(imported.issues.length,0);assert.equal(imported.appointments.length,1);
const result=report.report(imported.catalog,imported.appointments,{operatorId:'O1'});
assert.equal(result.printReady,true);assert.equal(result.entries.length,1);
assert.equal(report.report(imported.catalog,imported.appointments,{operatorId:'other'}).entries.length,0);
assert.equal(JSON.stringify(source),original);
const bad=adapter.adapt({...source,appuntamenti:[{id:'A2',clientId:'C1'}]});
assert.equal(bad.appointments.length,0);assert.equal(bad.skippedLegacyAppointments,1);
assert.ok(bad.issues.some(x=>x.code==='SCHEMA_APPUNTAMENTO_NON_COMPATIBILE'));
const orphan=adapter.adapt({...source,immobili:[{id:'S1',client_id:'NOT-EXIST'}]});
assert.ok(orphan.issues.some(x=>x.code==='RIFERIMENTO_ORFANO_clientId'));
console.log('PASS: local import adapter -> hierarchy -> agenda -> operator filtering; incompatible legacy rejected, no mutations');
