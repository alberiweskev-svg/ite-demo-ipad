assert.equal(records[0].status,'DA_VERIFICARE');
assert.throws(()=>A.batchAppend(records,[{...base,id:'demo-3',number:'D-02'},{...base,id:'demo-4'}]),/DUPLICATO/);
assert.equal(records.length,2,'failed batch must not mutate source');
assert.throws(()=>A.verify(records,'demo-1','',true),/OPERATORE/);
