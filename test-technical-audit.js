const assert=require('node:assert/strict');
const A=require('./ite-technical-audit.js');
const base={id:'demo-1',kind:'DICO',clientId:'c1',siteId:'s1',plantId:'p1',deviceId:'a1',number:'D-01',issued:'2026-11-02',operator:'Demo',confirmed:true};
const records=A.batchAppend([],[base,{...base,id:'demo-2',kind:'GAS',number:'G-01'}]);
assert.equal(records.length,2);
assert.equal(records[0].status,'DA_VERIFICARE');
assert.throws(()=>A.batchAppend(records,[{...base,id:'demo-3',number:'D-02'},{...base,id:'demo-4'}]),/DUPLICATO/);
assert.equal(records.length,2,'failed batch must not mutate source');
assert.throws(()=>A.verify(records,'demo-1','',true),/OPERATORE/);
assert.throws(()=>A.verify(records,'demo-1','Tecnico',false),/CONFERMA/);
const verified=A.verify(records,'demo-1','Tecnico',true);
assert.equal(verified[0].status,'VERIFICATO');assert.equal(records[0].status,'DA_VERIFICARE');
assert.throws(()=>A.verify(verified,'demo-1','Tecnico',true),/GIA_VERIFICATO/);
const masters={clients:[{id:'c1'}],sites:[{id:'s1',clientId:'c1'}],plants:[{id:'p1',siteId:'s1'}],devices:[{id:'a1',plantId:'p1'}]};
assert.equal(A.audit(verified,masters)[0].ready,true);
assert.equal(A.audit(verified,{...masters,sites:[{id:'s1',clientId:'other'}]})[0].issues[0],'SEDE_CLIENTE_INCOERENTE');
assert.equal(A.audit(verified,{...masters,devices:[{id:'a1',plantId:'other'}]})[0].issues[0],'APPARECCHIATURA_IMPIANTO_INCOERENTE');
assert.throws(()=>A.read(JSON.stringify([{...base,issued:'2026-02-30'}])),/NON_VALIDO/);
assert.throws(()=>A.read('{'),/DANNEGGIATO/);
assert.deepEqual(A.read(JSON.stringify(verified)),verified);
console.log('Technical document audit: 13 synthetic assertions passed');


const noMasters=A.audit(verified);
assert.equal(noMasters[0].ready,false,'verified document without master records must not be marked ready');
assert.ok(noMasters[0].issues.includes('ARCHIVIO_CLIENTI_NON_COLLEGATO'));
assert.ok(noMasters[0].issues.includes('ARCHIVIO_SEDI_NON_COLLEGATO'));
assert.ok(noMasters[0].issues.includes('ARCHIVIO_IMPIANTI_NON_COLLEGATO'));
assert.ok(noMasters[0].issues.includes('ARCHIVIO_APPARECCHIATURE_NON_COLLEGATO'));
assert.equal(A.summary(verified,masters).ready,1);
assert.equal(A.summary(verified).ready,0);
assert.equal(A.summary(verified).unlinked,2);
assert.equal(A.filter(verified,{kind:'DICO'}).length,1);
assert.equal(A.filter(verified,{status:'VERIFICATO'}).length,1);
assert.equal(A.filter(verified,{query:'g-01'})[0].kind,'GAS');
assert.equal(A.filter(verified,{query:'c1'}).length,2);
assert.equal(A.filter(verified,{query:'missing'}).length,0);
assert.equal(A.filter(verified)[0].kind,'DICO');
console.log('Technical audit hierarchy, filters and summaries: 13 additional assertions passed');
