'use strict';
const assert=require('node:assert/strict');
const h=require('./ite-hierarchy-workspace.js'),c=require('./ite-calendar-service.js');
let s=h.empty();
s=h.add(s,'clients',{id:'C1',name:'Cliente sintetico'});
s=h.add(s,'sites',{id:'S1',clientId:'C1',address:'Via Fittizia 10'});
s=h.add(s,'plants',{id:'P1',siteId:'S1'});
s=h.add(s,'devices',{id:'D1',plantId:'P1'});
const ap=(id,start,end,operator='Tecnico Test')=>({id,clientId:'C1',siteId:'S1',deviceId:'D1',operator,start,end});
s=h.add(s,'appointments',ap('A1','2026-11-04T09:00','2026-11-04T10:00'));
s=h.add(s,'appointments',ap('A2','2026-11-04T09:30','2026-11-04T10:30'));
s=h.add(s,'appointments',ap('A3','2026-11-04T09:30','2026-11-04T10:30','Secondo tecnico'));
assert.equal(c.conflicts(s).length,1);
assert.deepEqual([c.conflicts(s)[0].first,c.conflicts(s)[0].second],['A1','A2']);
assert.equal(c.schedule(s,{operator:'Tecnico Test'}).length,2);
assert.equal(c.schedule(s,{from:'2026-11-05'}).length,0);
assert.equal(c.schedule(s,{query:'fittizia'}).length,3);
assert.equal(c.summary(s).planned,3);
assert.equal(c.summary(s).conflicts,1);
assert.throws(()=>c.schedule(s,{from:'2026-11-05',to:'2026-11-04'}),/INTERVALLO/);
s=h.createIntervention(s,'A1','Tecnico Test','I1');
s=h.clock(s,'I1','ARRIVO','2026-11-04T09:05');
assert.equal(c.summary(s).inProgress,1);
s=h.clock(s,'I1','USCITA','2026-11-04T09:55');
assert.equal(c.summary(s).completed,1);
assert.equal(c.serviceHistory(s,'D1').length,3);
assert.equal(c.serviceHistory(s,'D1')[0].status,'CONCLUSO');
assert.throws(()=>c.serviceHistory(s,'missing'),/NON_TROVATA/);
assert.match(c.csv(s),/Cliente sintetico/);
assert.match(c.csv(s),/CONCLUSO/);
assert.equal(c.overlap({start:'2026-11-04T09:00',end:'2026-11-04T10:00'},{start:'2026-11-04T10:00',end:'2026-11-04T11:00'}),false);
console.log('Calendar/service integration: 16 synthetic assertions passed');
