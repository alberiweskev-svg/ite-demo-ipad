'use strict';
const assert=require('node:assert/strict');
const dirty=require('./ite-field-dirty-guard.js');
const persistence=require('./ite-field-persistence.js');
const data={catalog:{clients:[{id:'C'}],sites:[{id:'S',clientId:'C'}],systems:[{id:'I',siteId:'S'}],equipment:[{id:'E',systemId:'I'}],operators:[{id:'O'}]},appointments:[]};
const store=new Map();
const vault={isUnlocked:()=>true,storage:{getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)}};
const guard=dirty.create();
assert.equal(guard.isDirty(null),false);
assert.equal(guard.isDirty(data),true);
persistence.save(data,vault);guard.markSaved(data);
assert.equal(guard.isDirty(data),false);
const changed=JSON.parse(JSON.stringify(data));changed.catalog.clients[0].name='Demo';
assert.equal(guard.isDirty(changed),true);
assert.equal(guard.isDirty(data),false);
persistence.save(changed,vault);guard.markSaved(changed);
assert.equal(guard.isDirty(changed),false);
assert.deepEqual(persistence.load(vault),changed);
assert.throws(()=>persistence.save(changed,{isUnlocked:()=>false}),/BLOCCATO/);
guard.reset();assert.equal(guard.hasBaseline(),false);
console.log('PASS unsaved workspace guard and explicit local persistence');
