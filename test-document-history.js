'use strict';
const assert=require('node:assert/strict');
const H=require('./ite-hierarchy-workspace.js');
const D=require('./ite-document-intake.js');
const X=require('./ite-document-history.js');
let h=H.empty();
h=H.add(h,'clients',{id:'C1',name:'Cliente sintetico'});
h=H.add(h,'sites',{id:'S1',clientId:'C1',address:'Via Fittizia 1'});
h=H.add(h,'plants',{id:'P1',siteId:'S1'});
h=H.add(h,'devices',{id:'M1',plantId:'P1'});
h=H.add(h,'appointments',{id:'A1',clientId:'C1',siteId:'S1',deviceId:'M1',operator:'Tecnico demo',start:'2026-11-04T09:00',end:'2026-11-04T10:00'});
h=H.createIntervention(h,'A1','Tecnico demo','I1');
let docs=D.add(D.empty(),{id:'DOC1',filename:'dico_demo.pdf',type:'DICO_IDRICO',status:'DA_VERIFICARE',addedAt:'2026-11-03',clientId:'C1',siteId:'S1',notes:''});
docs=D.add(docs,{id:'DOC2',filename:'gas_demo.pdf',type:'ALLEGATI_GAS',status:'DA_VERIFICARE',addedAt:'2026-11-02',clientId:'C1',siteId:'S1',notes:''});
const good={documentId:'DOC1',plantId:'P1',deviceId:'M1',appointmentId:'A1',interventionId:'I1'};
let links=X.link([],good,docs,h);
assert.equal(X.timeline(docs,h,links,{interventionId:'I1'}).length,1);
assert.deepEqual(X.timeline(docs,h,links,{clientId:'C1'}).map(x=>x.id),['DOC1','DOC2']);
assert.equal(X.reconcile(docs,h,links).unlinked,1);
assert.throws(()=>X.link(links,{...good,documentId:'DOC2',interventionId:'BAD'},docs,h),/RIFERIMENTO_INESISTENTE/);
assert.throws(()=>X.link(links,{...good,documentId:'DOC2',appointmentId:null},docs,h),/INTERVENTO_APPUNTAMENTO_INCOERENTE/);
assert.throws(()=>X.link(links,{...good,documentId:'DOC2',plantId:'BAD'},docs,h),/RIFERIMENTO_INESISTENTE/);
assert.equal(X.unlink(links,'DOC1',docs,h).length,0);
const broken=X.reconcile(docs,h,[{documentId:'MISSING',plantId:'P1'}]);
assert.deepEqual(broken.missingDocuments,['MISSING']);
assert.equal(broken.invalidLinks.length,1);
console.log('PASS: document history links, timeline, reconciliation and integrity checks');
