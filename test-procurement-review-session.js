'use strict';
const assert=require('node:assert/strict');
const workspace=require('./ite-procurement-review-workspace.js');
const session=require('./ite-procurement-review-session.js');
const time='2026-11-01T12:00:00Z';
const prepare=(id,type,text)=>workspace.prepare({id,type,supplierId:'FORNITORE-FITTIZIO',text});
const quote=prepare('Q-TEST','Preventivo fornitore','A | 2 | 10,00\nB | 1 | 5,00');
const invoice=prepare('F-TEST','Fattura acquisto','A | 3 | 12,00\nB | 1 | 5,00');
const initial=session.create();
const first=session.add(initial,quote,quote.document.lines,'OPERATORE-TEST',time);
assert.equal(initial.documents.length,0);
assert.equal(first.documents.length,1);
const second=session.add(first,invoice,invoice.document.lines,'OPERATORE-TEST',time,'Q-TEST');
const result=session.inspect(second);
assert.equal(result.documents,2);
assert.equal(result.priceResult.records[0].status,'DIFFERENZE');
assert.ok(result.priceResult.records[0].differences.some(x=>x.kind==='AUMENTO'));
assert.ok(result.quantityResult.records[0].differences.some(x=>x.kind==='QUANTITA_AUMENTATA'));
assert.equal(result.persisted,false);
assert.equal(second.documents[1].review.status,'confirmed');
assert.throws(()=>session.add(second,invoice,invoice.document.lines,'OPERATORE-TEST',time,'Q-TEST'),/duplicato/);
assert.throws(()=>session.add(initial,quote,[{code:'A',qty:0,unitPrice:2}],'OPERATORE-TEST',time),/non valide/);
const orphan=session.add(first,invoice,invoice.document.lines,'OPERATORE-TEST',time,'INESISTENTE');
assert.equal(session.inspect(orphan).priceResult.records[0].status,'PREVENTIVO_ASSENTE');
const unlinked=session.add(first,invoice,invoice.document.lines,'OPERATORE-TEST',time,'');
assert.equal(session.inspect(unlinked).priceResult.records[0].status,'NON_ASSOCIATA');
console.log('Supplier review session: synthetic multi-document end-to-end tests passed');
