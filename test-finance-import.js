'use strict';
const assert=require('node:assert/strict'),I=require('./ite-finance-import.js');
const row=(id,type,issuerVat,number)=>({id,type,issuerVat,number,date:'2026-11-04',netCents:10000,vatCents:1000,totalCents:11000});
const original={documents:[]};
const rows=[row('v','TD01','03857941201','101'),row('a','TD01','01234567890','102'),row('p','PR','03857941201','PR-1'),row('c','TD04','01234567890','NC-1')];
const check=I.preview(original,rows,'MANUALE');
assert.equal(check.ready,true);assert.equal(check.accepted.length,4);
const next=I.importBatch(original,rows,'MANUALE');assert.equal(original.documents.length,0);
assert.deepEqual(next.documents.map(x=>x.kind),['FATTURA','FATTURA','PROFORMA','NOTA_CREDITO']);
assert.equal(I.summary(next).toReview,4);
const reviewed=I.review(next,'v','Operatore DEMO','2026-11-04T18:00:00Z','CONFERMA','');
assert.equal(I.summary(reviewed).confirmed,1);assert.equal(next.documents[0].reviewed,false);
assert.equal(I.review(reviewed,'a','Operatore DEMO','2026-11-04T18:01:00Z','DA_VERIFICARE','Controllo intestazione').documents[1].reviewHistory.length,1);
const bad=[rows[0],{...rows[1],totalCents:999}];
assert.equal(I.preview(original,bad,'MANUALE').ready,false);
assert.throws(()=>I.importBatch(original,bad,'MANUALE'),/LOTTO_RESPINTO/);
assert.throws(()=>I.importBatch(next,[rows[0]],'MANUALE'),/LOTTO_RESPINTO/);
assert.throws(()=>I.prepare({...rows[0],issuerVat:''},'MANUALE'),/EMITTENTE/);
assert.throws(()=>I.prepare(rows[0],'PDF'),/ORIGINE/);
assert.throws(()=>I.review(next,'a','Operatore DEMO','2026-11-04T18:00:00Z','DA_VERIFICARE',''),/MOTIVO/);
console.log('Finance import: 12 verifiche completate');
