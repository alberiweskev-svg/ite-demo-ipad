const assert=require("node:assert/strict");
const D=require("./ite-document-intake-90.js");
const sample=(id,name,text="",issuerIsITE)=>D.createRecord({id,name,text,issuerIsITE,size:1024,mime:"application/pdf",clientId:"TEST-CLIENT-1",appointmentId:"TEST-APP-1"});
assert.equal(sample("TEST-001","fattura.pdf","TD04 nota di credito",true).type,"NOTA_CREDITO_TD04");
assert.equal(sample("TEST-002","PR 72.pdf").type,"PROFORMA");
assert.equal(sample("TEST-003","dico.pdf","Dichiarazione di conformità impianto elettrico").type,"DICO_ELETTRICO");
assert.equal(sample("TEST-004","diri.pdf","Dichiarazione di rispondenza").type,"DIRI");
assert.equal(sample("TEST-005","fattura.pdf","fattura TD01",true).type,"FATTURA_VENDITA");
assert.equal(sample("TEST-006","fattura.pdf","fattura TD01",false).type,"FATTURA_ACQUISTO");
assert.equal(sample("TEST-007","fattura.pdf","fattura TD01").type,"DA_VERIFICARE");
let m=D.append(D.empty(),sample("TEST-008","listino.pdf","listino prezzi"));
assert.equal(D.summary(m).counts.LISTINO,1);
assert.deepEqual(D.importJSON(D.exportJSON(m)),m);
assert.throws(()=>D.append(m,m.records[0]),/duplicato/);
assert.throws(()=>D.importJSON('{"schema":"WRONG","records":[]}'),/incompatibile/);
assert.throws(()=>D.createRecord({id:"TEST-009",name:"../bad.pdf",size:1,mime:"application/pdf"}),/Nome/);
assert.throws(()=>D.createRecord({id:"TEST-010",name:"big.pdf",size:15000001,mime:"application/pdf"}),/Dimensione/);
assert.equal(m.records[0].source,"TEST_METADATA_ONLY");
