'use strict';
/* Milestone 41 — dati esclusivamente sintetici; nessuna rete o file cliente. */
const assert=require('node:assert/strict');
const cad=require('../ite-cad.js');
const wall=cad.make('wall',{x:100,y:100},{x:300,y:100});
const line=cad.make('line',{x:100,y:200},{x:300,y:200});
const symbol=cad.make('symbol',{x:350,y:250},{x:350,y:250},'presa');
symbol.articleId='art_12345678';
const initial=[wall,line,symbol],original=JSON.stringify(initial);
let rows=cad.operate(initial,'group','',{ids:[wall.id,line.id]});
assert(rows[0].groupId&&rows[0].groupId===rows[1].groupId);
assert.throws(()=>cad.operate(rows,'group','',{ids:[wall.id,symbol.id]}),/Selezione parziale/);
const beforeLength=Math.hypot(rows[0].x2-rows[0].x,rows[0].y2-rows[0].y);
rows=cad.operate(rows,'rotate',wall.id);
assert.equal(rows[0].rotation,90);
assert.equal(rows[1].rotation,90);
assert.equal(Math.hypot(rows[0].x2-rows[0].x,rows[0].y2-rows[0].y),beforeLength);
assert.equal(rows[0].x,rows[0].x2);
rows=cad.operate(rows,'resize',wall.id,{factor:1.5});
assert(Math.hypot(rows[0].x2-rows[0].x,rows[0].y2-rows[0].y)>beforeLength);
assert.equal(rows[0].groupId,rows[1].groupId);
assert.throws(()=>cad.operate(rows,'resize',wall.id,{factor:0.01}),/50%/);
assert.throws(()=>cad.operate(rows,'resize',wall.id,{factor:NaN}),/50%/);
assert.throws(()=>cad.operate([symbol],'resize',symbol.id,{factor:1.5}),/dimensione grafica/);
assert.deepEqual(cad.orthogonalPoint({x:10,y:10},{x:100,y:40}),{x:100,y:10});
assert.deepEqual(cad.orthogonalPoint({x:10,y:10},{x:30,y:120}),{x:10,y:120});
assert.throws(()=>cad.orthogonalPoint({x:NaN,y:10},{x:30,y:120}),/Punti/);
const front=cad.operate(rows,'front',wall.id);
assert.deepEqual(front.slice(-2).map(e=>e.id),[wall.id,line.id]);
const back=cad.operate(front,'back',wall.id);
assert.deepEqual(back.slice(0,2).map(e=>e.id),[wall.id,line.id]);
const clipboard=cad.copySelection(rows,wall.id);
assert.equal(clipboard.length,2);
const pasted=cad.pasteSelection(rows,clipboard,20,20);
assert.equal(pasted.elements.length,5);
assert.equal(new Set(pasted.elements.map(e=>e.id)).size,5);
assert(pasted.elements[3].groupId===pasted.elements[4].groupId);
assert.notEqual(pasted.elements[3].groupId,rows[0].groupId);
assert.equal(JSON.stringify(rows),JSON.stringify(cad.operate(rows,'color',wall.id,{color:rows[0].color})));
assert.throws(()=>cad.pasteSelection(rows,clipboard,1000,0),/fuori dal foglio/);
assert.throws(()=>cad.copySelection(rows,'missing'),/Seleziona/);
assert.equal(cad.operate(rows,'deleteGroup',wall.id).length,1);
assert.equal(cad.operate(rows,'delete',wall.id).length,2);
const replacement=cad.operate(rows,'replaceSymbol',symbol.id,{symbol:'lavabo'});
assert.equal(replacement[2].text,'lavabo');
assert.equal(replacement[2].articleId,undefined,'Do not inherit a mismatched catalogue article');
assert.equal(rows[2].articleId,'art_12345678','Original catalogue link must remain untouched');
assert.throws(()=>cad.operate(rows,'replaceSymbol',symbol.id,{symbol:'<script>'}),/sostituto/);
assert.throws(()=>cad.operate(rows,'replaceSymbol',wall.id,{symbol:'presa'}),/simbolo/);
const nearEdge=cad.make('wall',{x:10,y:10},{x:310,y:10});
const rotated=cad.operate([nearEdge],'rotate',nearEdge.id);
assert.equal(Math.hypot(rotated[0].x2-rotated[0].x,rotated[0].y2-rotated[0].y),300);
assert(rotated[0].y>=0&&rotated[0].y2<=650);
assert.throws(()=>cad.operate([nearEdge],'move',nearEdge.id,{dx:-20,dy:0}),/fuori dal foglio/);
assert.equal(JSON.stringify(initial),original,'Source CAD drawing must never mutate');
console.log('OK: CAD group rotation, sheet fit, resize, order, clipboard, replacement, deletion, bounds, immutability');
