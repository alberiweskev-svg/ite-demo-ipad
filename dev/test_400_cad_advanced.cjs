'use strict';
const assert=require('node:assert/strict');
const cad=require('../ite-cad.js');
const db={clienti:[{id:1}],immobili:[{id:10,client_id:'1'}],cantieri:[],impianti:[]};
const wall=cad.make('wall',{x:10,y:10},{x:210,y:10});
const line=cad.make('line',{x:10,y:20},{x:110,y:20});
const presa=cad.make('symbol',{x:30,y:40},{x:30,y:40},'presa');
const lavabo=cad.make('symbol',{x:60,y:70},{x:60,y:70},'lavabo');
assert.equal(presa.kind,'symbol');
assert.equal(presa.text,'presa');
assert.throws(()=>cad.make('symbol',{x:0,y:0},{x:0,y:0},'<script>'),/Elemento/);
assert.throws(()=>cad.validateElement({...presa,groupId:'unsafe'}),/Elemento/);
assert.equal(cad.snapPoint({x:18,y:15},[wall]).x,10);
assert.equal(cad.snapPoint({x:18,y:15},[wall],false).x,20);
assert.equal(cad.snapPoint({x:400,y:300},[wall]).x,400);
const elements=[wall,line,presa,lavabo];
const metric=cad.materialSchedule(elements,2);
assert.equal(metric.wallMeters,4);
assert.equal(metric.lineMeters,2);
assert.equal(metric.items.find(x=>x.code==='presa').count,1);
assert.equal(metric.items.find(x=>x.code==='lavabo').label,'Lavabo');
assert.equal(cad.materialSchedule(elements).wallMeters,null);
assert.throws(()=>cad.materialSchedule(elements,0),/Distinta/);
assert.throws(()=>cad.materialSchedule(elements,NaN),/Distinta/);
assert.equal(cad.validScale(0.01),true);
assert.equal(cad.validScale(101),false);
let rows=cad.operate([],'add','',{element:wall});
rows=cad.operate(rows,'add','',{element:line});
rows=cad.operate(rows,'add','',{element:presa});
rows=cad.operate(rows,'group','',{ids:[wall.id,line.id]});
assert(rows[0].groupId&&rows[0].groupId===rows[1].groupId);
assert.throws(()=>cad.operate(rows,'group','',{ids:[wall.id,wall.id]}),/due elementi/);
assert.throws(()=>cad.operate(rows,'group','',{ids:[wall.id,'missing']}),/due elementi/);
rows=cad.operate(rows,'move',wall.id,{dx:20,dy:20});
assert.equal(rows[0].x,30);
assert.equal(rows[1].x,30);
assert.equal(rows[2].x,30);
rows=cad.operate(rows,'color',wall.id,{color:'#16805d'});
assert.equal(rows[0].color,'#16805d');
assert.equal(rows[1].color,'#16805d');
rows=cad.operate(rows,'duplicate',wall.id);
assert.equal(rows.length,5);
assert(rows[3].groupId===rows[4].groupId&&rows[3].groupId!==rows[0].groupId);
rows=cad.operate(rows,'ungroup',wall.id);
assert.equal(rows[0].groupId,undefined);
assert.equal(rows[1].groupId,undefined);
assert.throws(()=>cad.operate(rows,'ungroup',wall.id),/non raggruppato/);
const drawing={id:'cad_12345678',title:'Schema TEST sintetico',clientId:'1',propertyId:'10',siteId:'',plantId:'',revision:2,updated:'2026-10-29T08:00:00Z',archived:false,scaleCmPerUnit:2,elements:rows,history:[{revision:1,at:'2026-10-29T07:00:00Z',scaleCmPerUnit:null,elements:[wall]}]};
assert.equal(cad.validateCollection([drawing],db),true);
assert.equal(cad.validateCollection([{...drawing,scaleCmPerUnit:undefined,history:[{revision:1,at:'2026-10-29T07:00:00Z',elements:[wall]}]}],db),true,'legacy drawings remain valid');
assert.throws(()=>cad.validateCollection([{...drawing,scaleCmPerUnit:-2}],db),/Disegno/);
assert.throws(()=>cad.validateCollection([{...drawing,history:[{...drawing.history[0],scaleCmPerUnit:500}]}],db),/Revisione/);
console.log('OK: CAD metric scale, endpoint snap, 9 validated symbols, group operations, indicative bill, legacy and revision compatibility');
