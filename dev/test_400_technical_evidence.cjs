'use strict';
const assert=require('node:assert/strict');
const api=require('../ite-technical-evidence.js');
const clone=x=>JSON.parse(JSON.stringify(x));
const core={clienti:[{id:1,name:'Cliente TEST'},{id:2,name:'Cliente RISERVATO'}]};
const p={id:'td_11111111-1111-4111-8111-111111111111',type:'Di.Co. idrica / termica',status:'Bozza',revision:1,clientId:'1',interventionId:'50',deviceId:'30',plantId:'20',siteId:'40',fields:{reference:'DICO-TEST'}};
const check={id:'fc_12345678',jobId:'50',clientId:'1',deviceId:'30',plantId:'20',siteId:'40',category:'Termico',kind:'Misura strumentale',label:'Temperatura TEST',value:'48.5',unit:'°C',outcome:'Rilevato',actorId:'7',createdAt:'2026-10-30T08:00:00Z',voidedAt:''};
const s={settings:{technicalDrafts:[p],fieldChecks:[check]},audit:[]};
assert(api.compatible(p,check));
assert(!api.compatible(p,{...check,clientId:'2'}));
assert(!api.compatible(p,{...check,jobId:'51'}));
assert(!api.compatible({...p,type:'POS'},check));
assert.throws(()=>api.attach(s,core,{practiceId:p.id,checkId:check.id,reviewer:'AB',note:'Breve'}),/revisore/i);
const l=api.attach(s,core,{practiceId:p.id,checkId:check.id,reviewer:'Tecnico TEST',note:'Rilevazione indicativa da controllare'});
assert.equal(s.audit[0].action,'COLLEGA_PROVA_PRATICA');
assert.equal(api.validate(s,core),true);
assert.equal(api.report(s,core,p.id).entries.length,1);
assert.equal(api.report(s,core,p.id).entries[0].status,'Riferimento attivo - da verificare');
assert.match(api.html(api.report(s,core,p.id)),/BOZZA NON UFFICIALE/);
assert.match(api.csv(api.report(s,core,p.id)),/Temperatura TEST/);
assert.throws(()=>api.attach(s,core,{practiceId:p.id,checkId:check.id,reviewer:'Tecnico TEST',note:'Secondo collegamento duplicato'}),/gia collegata/);
const copy=clone(s);
copy.settings.technicalDrafts[0].revision=2;
assert.equal(api.report(copy,core,p.id).entries[0].status,'Revisione pratica superata');
copy.settings.fieldChecks[0].voidedAt='2026-10-30T08:30:00Z';
assert.equal(api.report(copy,core,p.id).entries[0].status,'Prova stornata / assente');
assert.throws(()=>api.revoke(s,core,{linkId:l.id,reviewer:'Tecnico TEST',reason:'Breve'}),/motivazione/i);
api.revoke(s,core,{linkId:l.id,reviewer:'Tecnico TEST',reason:'Riferimento non pertinente'});
assert.equal(api.report(s,core,p.id).entries[0].status,'Revocato');
assert.equal(s.audit[1].action,'REVOCA_PROVA_PRATICA');
assert.throws(()=>api.revoke(s,core,{linkId:l.id,reviewer:'Tecnico TEST',reason:'Ancora da revocare'}),/gia revocato/);
const s2=clone(s);s2.settings.technicalDrafts.push({...p,id:'td_22222222-2222-4222-8222-222222222222',clientId:'2'});
assert.equal(api.summary(s2.settings.technicalDrafts[1],s2.settings.technicalEvidenceLinks,s2.settings.fieldChecks,'2').length,0);
const unsafe=clone(s);unsafe.settings.technicalEvidenceLinks[0].clientId='2';
assert.throws(()=>api.validate(unsafe,core),/cliente coerente/);
const duplicate=clone(s);duplicate.settings.technicalEvidenceLinks.push(clone(duplicate.settings.technicalEvidenceLinks[0]));
assert.throws(()=>api.validate(duplicate,core),/duplicato/);
const bad=clone(s);bad.settings.technicalEvidenceLinks[0].checkId='fc_non_esiste';
assert.throws(()=>api.validate(bad,core),/pratica o di cliente/);
const injection=clone(s);injection.settings.technicalDrafts[0].fields.reference='=2+2';
injection.settings.technicalEvidenceLinks[0].note='<script>alert(1)</script>';
assert.match(api.csv(api.report(injection,core,p.id)),/"'=2\+2"/);
assert.doesNotMatch(api.html(api.report(injection,core,p.id)),/<script>/);
const historical=clone(s);historical.settings.technicalDrafts[0].status='Annullata';
assert.equal(api.validate(historical,core),true);
assert.equal(api.report(historical,core,p.id).entries[0].status,'Revocato');
const manual={...p,interventionId:'',deviceId:'30',plantId:'20'};
assert(api.compatible(manual,{...check,jobId:'55'}));
assert(!api.compatible({...manual,siteId:'999'},check));
assert(!api.compatible({...manual,deviceId:''},check));
assert.equal(api.candidates({settings:{fieldChecks:[check]}},manual).length,1);

// Milestone 37: allegati originali tecnici, isolamento cliente, revisioni e revoche.
const annex=clone(s);
const sha='a'.repeat(64);
annex.documents=[{id:'doc_test_pdf',type:'Di.Co. idrica / termica',clientId:'1',propertyId:'',siteId:'40',
 fileId:'file_'+sha,sourceName:'originale_sintetico.pdf',number:'SYN-37',lines:[]}];
annex.files=[{id:'file_'+sha,hash:sha,size:12,base64:'JVBERi0xLjQKJSVFT0Y='}];
assert(api.technicalDoc(annex.documents[0]));
assert(api.originalMetadata(annex,annex.documents[0]));
assert.equal(api.annexCandidates(annex,p).length,1);
assert.throws(()=>api.attachAnnex(annex,core,{practiceId:p.id,documentId:'doc_test_pdf',category:'Progetto',reviewer:'A',note:'Breve'}),/Revisore/i);
const linked=api.attachAnnex(annex,core,{practiceId:p.id,documentId:'doc_test_pdf',category:'Schema impianto',reviewer:'Tecnico TEST',note:'Schema sintetico da verificare'});
assert.equal(api.validateAnnexes(annex),true);
assert.equal(api.annexCandidates(annex,p).length,0);
assert.equal(api.annexReport(annex,core,p.id).annexes[0].status,'Originale riferito - da verificare');
assert.match(api.annexCsv(api.annexReport(annex,core,p.id)),/SYN-37/);
assert.match(api.annexHtml(api.annexReport(annex,core,p.id)),/BOZZA NON UFFICIALE/);
assert.throws(()=>api.attachAnnex(annex,core,{practiceId:p.id,documentId:'doc_test_pdf',category:'Progetto',reviewer:'Tecnico TEST',note:'Duplicato da evitare'}),/gia collegato/);
const annexOther=clone(annex);annexOther.documents[0].clientId='2';
assert.throws(()=>api.validateAnnexes(annexOther),/cliente/i);
assert(!api.annexCompatible(p,annexOther.documents[0]));
const annexStale=clone(annex);annexStale.settings.technicalDrafts[0].revision=2;
assert.equal(api.annexReport(annexStale,core,p.id).annexes[0].status,'Revisione superata');
const annexMissing=clone(annex);annexMissing.files=[];
assert.equal(api.annexReport(annexMissing,core,p.id).annexes[0].status,'Originale mancante');
const annexInjection=clone(annex);annexInjection.documents[0].sourceName='<script>danger</script>';
annexInjection.settings.technicalAnnexLinks[0].note='=1+2+3+4';
assert.doesNotMatch(api.annexHtml(api.annexReport(annexInjection,core,p.id)),/<script>/);
assert.match(api.annexCsv(api.annexReport(annexInjection,core,p.id)),/"'=1\+2\+3\+4"/);
assert.throws(()=>api.revokeAnnex(annex,core,{linkId:linked.id,reviewer:'Tecnico TEST',reason:'Breve'}),/motivazione/i);
api.revokeAnnex(annex,core,{linkId:linked.id,reviewer:'Tecnico TEST',reason:'Originale sostituito da nuova versione'});
assert.equal(api.annexReport(annex,core,p.id).annexes[0].status,'Revocato');
assert(annex.audit.some(x=>x.action==='COLLEGA_ORIGINALE_PRATICA'));
assert(annex.audit.some(x=>x.action==='REVOCA_ORIGINALE_PRATICA'));
assert.throws(()=>api.revokeAnnex(annex,core,{linkId:linked.id,reviewer:'Tecnico TEST',reason:'Ancora da revocare'}),/gia revocato/);

console.log('OK: links, revisions, revoked/stale references, client isolation, manual review, A4/CSV, audit and no certification');
