'use strict';
const assert=require('node:assert/strict');
const cad=require('../ite-cad.js');
const presa=cad.make('symbol',{x:10,y:10},{x:10,y:10},'presa');
const lavabo=cad.make('symbol',{x:30,y:30},{x:30,y:30},'lavabo');
const id='art_12345678',other='art_87654321';
const articles=[{id,code:'TEST-PRESA',description:'Presa sintetica',unit:'pz',price:12.5,kind:'Materiale',priceRole:'cost'},{id:other,code:'TEST-M',description:'Tubo metri',unit:'m',price:4,kind:'Materiale'}];
let rows=cad.operate([presa,lavabo],'linkArticle',presa.id,{articleId:id});
rows=cad.operate(rows,'duplicate',presa.id);
assert.equal(rows.length,3);
assert.equal(rows[2].articleId,id,'Duplicate retains catalog link');
assert.throws(()=>cad.operate(rows,'linkArticle',lavabo.id,{articleId:'<script>'}),/Codice/);
assert.throws(()=>cad.operate(rows,'linkArticle','missing',{articleId:id}),/Seleziona/);
assert.throws(()=>cad.operate([cad.make('wall',{x:10,y:10},{x:20,y:20})],'linkArticle',presa.id,{articleId:id}),/Seleziona/);
let schedule=cad.catalogSchedule(rows,2,articles,[{articleId:id,quantity:3},{articleId:id,quantity:-2}]);
assert.equal(schedule.items.length,2);
const linked=schedule.items.find(x=>x.articleId===id);
assert.equal(linked.count,2);assert.equal(linked.stock,1);assert.equal(linked.shortage,1);assert.equal(linked.estimated,25);assert.match(linked.warning,/Giacenza inferiore/);
assert.equal(schedule.allPriced,false,'Unlinked symbol blocks total');
assert.equal(schedule.items.find(x=>!x.articleId).warning,'Articolo non associato o non più presente');
rows=cad.operate(rows,'linkArticle',lavabo.id,{articleId:other});
schedule=cad.catalogSchedule(rows,2,articles,[]);
assert.match(schedule.items.find(x=>x.articleId===other).warning,/Unità/);
assert.equal(schedule.archiveTotal,null);
const linkedOnly=cad.catalogSchedule([rows[0],rows[2]],null,articles,[{articleId:id,quantity:'bad'}]);
assert.equal(linkedOnly.items[0].stock,null);
assert.equal(linkedOnly.items[0].estimated,25);
assert.equal(linkedOnly.archiveTotal,25);
rows=cad.operate(rows,'linkArticle',presa.id,{articleId:''});
assert.equal(rows[0].articleId,undefined);
assert.throws(()=>cad.validateElement({...presa,articleId:'../../etc'}),/Elemento/);
assert.throws(()=>cad.validateElement({...cad.make('wall',{x:10,y:10},{x:30,y:30}),articleId:id}),/Elemento/);
const db={clienti:[{id:1}],immobili:[],cantieri:[],impianti:[]};
const record={id:'cad_12345678',title:'Bozza sintetica',clientId:'1',propertyId:'',siteId:'',plantId:'',updated:'2026-10-29T10:00:00Z',archived:false,revision:1,elements:[cad.operate([presa],'linkArticle',presa.id,{articleId:id})[0]],history:[]};
assert.equal(cad.validateCollection([record],db,articles),true);
assert.throws(()=>cad.validateCollection([record],db,[]),/Materiale CAD/);
assert.equal(cad.validateCollection([{...record,elements:[presa]}],db,articles),true,'Old drawings remain compatible');
console.log('OK: CAD catalog links, grouped quantities, pricing caveats, stock warnings, validations and legacy drawings');
