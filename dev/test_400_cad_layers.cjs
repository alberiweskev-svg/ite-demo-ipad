'use strict';
/* Milestone 43: livelli CAD, protezione dei gruppi, compatibilità e riepilogo. Solo fixture sintetiche. */
const assert=require('node:assert/strict'),cad=require('../ite-cad.js');
const a=cad.make('wall',{x:100,y:100},{x:300,y:100});
const b=cad.make('line',{x:100,y:200},{x:300,y:200});
const c=cad.make('symbol',{x:350,y:250},{x:350,y:250},'presa');
const original=JSON.stringify([a,b,c]);
assert.equal(cad.layerOf(a),'arch','legacy elements use architectural layer');
assert.equal(cad.validateElement({...a,layer:'idr',locked:true}),true);
assert.throws(()=>cad.validateElement({...a,layer:'invalid'}),/Elemento CAD/);
assert.throws(()=>cad.validateElement({...a,locked:'yes'}),/Elemento CAD/);
let rows=cad.operate([a,b,c],'group','',{ids:[a.id,b.id]});
rows=cad.operate(rows,'setLayer',a.id,{layer:'idr'});
assert.equal(rows[0].layer,'idr');assert.equal(rows[1].layer,'idr');
assert.equal(rows[2].layer,undefined,'unselected symbol is unchanged');
assert.throws(()=>cad.operate(rows,'setLayer',a.id,{layer:'script'}),/Livello CAD/);
rows=cad.operate(rows,'lock',a.id);
assert(rows[0].locked&&rows[1].locked);
for(const action of ['move','delete','deleteGroup','rotate','resize','ungroup','color','front','setLayer'])
 assert.throws(()=>cad.operate(rows,action,a.id,{dx:20,dy:0,factor:1.5,color:'#16805d',layer:'gas'}),/bloccato/,action);
assert.throws(()=>cad.operate(rows,'group','',{ids:[a.id,c.id]}),/Selezione parziale|bloccato/);
assert.equal(cad.copySelection(rows,a.id).length,2,'locked members remain copyable');
const pasted=cad.pasteSelection(rows,cad.copySelection(rows,a.id));
assert.equal(pasted.elements.length,5);
assert(pasted.elements.slice(-2).every(x=>!x.locked),'pasted copies are editable');
assert.equal(rows.length,3,'source remains unchanged');
rows=cad.operate(rows,'unlock',a.id);
assert(rows.slice(0,2).every(x=>x.locked===false));
rows=cad.operate(rows,'move',a.id,{dx:20,dy:0});
assert.equal(rows[0].x,120);assert.equal(rows[1].x,120);
const report=cad.layerReport(rows,2);
assert.equal(report.find(x=>x.id==='idr').count,2);
assert.equal(report.find(x=>x.id==='idr').wallMeters,4);
assert.equal(report.find(x=>x.id==='arch').symbols,1);
assert.equal(report.find(x=>x.id==='idr').locked,0);
assert.equal(cad.layerReport(rows).find(x=>x.id==='idr').wallMeters,null);
assert.throws(()=>cad.layerReport(rows,-2),/Registro/);
const db={clienti:[{id:1}],immobili:[{id:10,client_id:'1'}],cantieri:[],impianti:[]};
const drawing={id:'cad_12345678',title:'TEST livelli',clientId:'1',propertyId:'10',siteId:'',plantId:'',revision:1,updated:'2026-10-30T15:00:00Z',archived:false,scaleCmPerUnit:2,elements:rows,history:[{revision:1,at:'2026-10-30T14:00:00Z',elements:[a],scaleCmPerUnit:null}]};
assert.equal(cad.validateCollection([drawing],db),true);
assert.equal(JSON.stringify([a,b,c]),original,'originals unchanged');
console.log('OK: CAD levels, legacy defaults, grouped lock, copy safety, metric layer report, revision validation');
