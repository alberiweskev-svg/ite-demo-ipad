'use strict';
const assert=require('node:assert/strict');
globalThis.ITEContractBilling=require('../ite-contract-billing.js');
const api=require('../ite-site-costing.js');
const line=(kind,description,qty,unit,price)=>({line_type:kind,description,qty,unit,price,discount:0,vat:10,category:'Idrico'});
const site={id:9,client_id:1,name:'=CANTIERE',ite_quotes:JSON.stringify([{id:'q1',number:'Q1',status:'Accettato',lines:[line('Fornitura','=TUBO',5,'m',12),line('Posa','Posa tubo',1,'h',80)]},{id:'q2',status:'Da accettare',lines:[line('Fornitura','Non approvata',10,'m',20)]}]),ite_extras:JSON.stringify([{id:'e1',description:'Extra',status:'Parzialmente approvato',approved_line_indices:[0],lines:[line('Fornitura','Raccordo',3,'pz',4),line('Fornitura','Non approvata',3,'pz',4)]}])};
const core={clienti:[{id:1,name:'Cliente fittizio'},{id:2,name:'Altro'}],cantieri:[site,{id:10,client_id:2}]};
const usage=(id,q,unit,articleId,cost,clientId=1,siteId=9)=>({id,quantity:q,unit,articleId,unitCostCents:cost,clientId:String(clientId),siteId:String(siteId),jobId:'11',articleLabel:'=ARTICOLO',reversedAt:''});
const state=()=>({settings:{jobMaterialUsage:[usage('u1',4,'m','a',300),usage('u2',2,'pz','b',null),usage('u3',2,'m','a',200)],jobMaterialAllocations:[]},audit:[],documents:[]});
const s=state(),req={siteId:9,usageId:'u1',type:'quote',sourceId:'q1',index:0,quantity:'2.500'};
assert.equal(api.supplies(site).length,2);
assert.equal(api.analyze(site,core,s).supplySale,7200);
assert.equal(api.analyze(site,core,s).totalKnown,1600);
assert.equal(api.analyze(site,core,s).unknownCount,1);
assert.throws(()=>api.add(s,core,{...req,siteId:10}),/stesso cliente/);
assert.throws(()=>api.add(s,core,{...req,sourceId:'q2'}),/approvata/);
assert.throws(()=>api.add(s,core,{...req,index:1}),/approvata/);
assert.throws(()=>api.add(s,core,{...req,usageId:'u2'}),/Unità/);
const l1=api.add(s,core,req);
assert.equal(api.analyze(site,core,s).matchedKnown,750);
assert.equal(api.analyze(site,core,s).unassigned.find(x=>x.id==='u1').remaining,1.5);
assert.throws(()=>api.add(s,core,{...req,quantity:2}),/superiore al consumo/);
assert.throws(()=>api.add(s,core,{...req,quantity:'1e2'}),/Quantità/);
api.add(s,core,{...req,quantity:1.5});
assert.throws(()=>api.add(s,core,{...req,usageId:'u3',quantity:2}),/superiore alla Fornitura/);
api.add(s,core,{...req,usageId:'u3',quantity:1});
assert.equal(api.analyze(site,core,s).matchedKnown,1400);
assert.match(api.csv(site,core,s),/"'=CANTIERE"/);
assert.match(api.csv(site,core,s),/"'=TUBO"/);
assert.doesNotMatch(api.render(site,core,s),/<script/);
assert.throws(()=>api.reverse(s,core,9,l1.id,'no'),/Motivazione/);
api.reverse(s,core,9,l1.id,'Correzione sintetica');
assert.equal(api.analyze(site,core,s).matchedKnown,650);
assert.throws(()=>api.reverse(s,core,9,l1.id,'Secondo storno'),/già stornata/);
assert.equal(api.validate(s,core),true);
s.settings.jobMaterialUsage[2].reversedAt='2026-10-30T02:00:00Z';
assert.ok(api.analyze(site,core,s).warnings.some(w=>w.includes('non utilizzabile')));
assert.equal(api.validate(s,core),true);
const altered=structuredClone(s);altered.settings.jobMaterialAllocations[1].clientId='2';
assert.throws(()=>api.validate(altered,core),/incoerente/);
const foreign=state();foreign.settings.jobMaterialUsage.push(usage('foreign',1,'m','a',100,2,9));
assert.throws(()=>api.analyze(site,core,foreign),/altro cliente/);
console.log('OK: Fornitura/Posa, Extra parziali, quantità, costi, storni, privacy, CSV sintetico');
