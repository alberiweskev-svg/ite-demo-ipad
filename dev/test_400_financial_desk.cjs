'use strict';
const assert=require('node:assert/strict'),api=require('../ite-financial-desk.js');
const doc=(id,type,total,extra={})=>({id,type,total,number:id,date:'2026-10-01',due:'2026-10-20',status:'Registrato',party:{vat:'03857941201'},...extra});
const docs=[doc('a','Fattura vendita',110),doc('b','Nota credito vendita',30),doc('c','Fattura acquisto',220,{party:{vat:'01234567890'}}),doc('p','Proforma vendita',55),doc('z','Nota credito acquisto',100,{party:{vat:'01234567890'}})];
const entry=(id,kind,documentId,amountCents,creditId)=>({id:'fin_'+id,kind,documentId,amountCents,date:'2026-10-15',reference:'TEST-SINTETICO',...(creditId?{creditId}:{})});
let report=api.analyze(docs,[],'2026-10-29');
assert.equal(report.rows.find(x=>x.id==='a').status,'Da incassare');
assert.equal(report.rows.find(x=>x.id==='b').status,'Da rimborsare');
assert.equal(report.rows.find(x=>x.id==='z').status,'Da recuperare');
assert.equal(report.rows.find(x=>x.id==='p').status,'Proforma (non contabilizzata)');
assert.equal(report.totals.overdue,2);
const entries=[entry('e1','movimento','a',5000),entry('e2','compensazione','a',3000,'b'),entry('e3','movimento','z',10000)];
report=api.analyze(docs,entries,'2026-10-29');
assert.equal(report.rows.find(x=>x.id==='a').remaining,3000);
assert.equal(report.rows.find(x=>x.id==='b').status,'Rimborsata');
assert.equal(report.rows.find(x=>x.id==='z').status,'Recuperata');
assert.equal(report.rows.find(x=>x.id==='a').status,'Parzialmente incassata');
assert.equal(report.totals.vendita,3000);
assert.equal(report.totals.creditiVendita,0);
assert.throws(()=>api.validateLedger(docs,[entry('e1','movimento','a',11001)]),/superiori/);
assert.throws(()=>api.validateLedger(docs,[entry('e1','compensazione','a',3000,'z')]),/coerenti/);
assert.throws(()=>api.validateLedger(docs,[entry('e1','movimento','p',1000)]),/non disponibile/);
assert.throws(()=>api.validateLedger(docs,[entry('e1','movimento','a',1000),entry('e1','movimento','a',1000)]),/duplicato/);
assert.throws(()=>api.validateLedger(docs,[entry('e1','movimento','a',1000,'b')]),/non ammesso/);
assert.equal(api.cents(null),null);
assert.equal(api.cents('1e5'),null);
assert.equal(api.cents(-3.3),330);
assert.match(api.csv([{type:'=HYPERLINK()',number:'-danger',date:'',party:'@A',siteId:'',amount:100,applied:0,remaining:100,due:'',status:'Da verificare',issues:[]}]),/"'=HYPERLINK\(\)"/);
const duplicates=[doc('x','Fattura vendita',100,{number:'1'}),doc('y','Fattura vendita',100,{number:'1'})];
assert.equal(api.analyze(duplicates).totals.duplicates,2);
const installment=doc('i','Fattura vendita',100,{payments:[{due:'2026-10-01',amount:50},{due:'2026-11-01',amount:50}]});
report=api.analyze([installment],[entry('e1','movimento','i',5000)],'2026-10-29');
assert.equal(report.rows[0].due,'2026-11-01');
assert.equal(report.rows[0].overdue,false);
const voided={...entry('v1','movimento','a',5000),voidedAt:'2026-10-29T21:00:00Z',voidReason:'Doppia registrazione'};
report=api.analyze(docs,[voided]);
assert.equal(report.rows.find(x=>x.id==='a').remaining,11000);
assert.equal(report.entries,0);
assert.throws(()=>api.validateLedger(docs,[{...voided,voidReason:''}]),/Storno/);
assert.throws(()=>api.validateLedger(docs,[entry('bad','movimento','a',0)]),/non valido/);
assert.throws(()=>api.validateLedger(docs,[entry('bad','movimento','unknown',100)]),/non disponibile/);
console.log('OK: financial desk reconciliation, partial payments, TD04, proformas, compensation, voids, duplicates, due dates and safe CSV');
