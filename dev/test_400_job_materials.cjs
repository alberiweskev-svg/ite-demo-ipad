'use strict';
const assert=require('node:assert/strict'),api=require('../ite-job-materials.js');
const client={id:1,name:'=CLIENTE DI PROVA'},actor={id:2,name:'Tecnico fittizio'};
const core={clienti:[client,actor,{id:3,name:'Altro cliente'}],cantieri:[{id:9,client_id:1,name:'Cantiere fittizio'}],interventi:[{id:12,appointment:'1',client_id:1,cantiere_id:9,workflow_status:'In corso',assigned_operators:JSON.stringify([{operator_id:'2',role:'Principale'}])},{id:13,appointment:'1',client_id:3,cantiere_id:9,workflow_status:'In corso',assigned_operators:'[{"operator_id":"2"}]'}]};
const state=()=>({settings:{},articles:[{id:'a',kind:'Materiale',code:'=M1',description:'Tubo fittizio',unit:'m',costPrice:2.5},{id:'b',kind:'Servizio',description:'Posa'}],movements:[{id:'in',articleId:'a',quantity:10,date:'2026-10-30',reason:'Carico fittizio',siteId:'9'}],audit:[]});
const s=state(),req={jobId:12,actorId:2,articleId:'a',quantity:'2.500',note:'Bagno prova'};
assert.equal(api.stock(s,'a'),10);
assert.throws(()=>api.addUsage(s,core,{...req,quantity:11}),/Giacenza insufficiente/);
assert.throws(()=>api.addUsage(s,core,{...req,quantity:'1e2'}),/Quantità/);
assert.throws(()=>api.addUsage(s,core,{...req,quantity:'1.2345'}),/Quantità/);
assert.throws(()=>api.addUsage(s,core,{...req,actorId:3}),/non assegnato/);
assert.throws(()=>api.addUsage(s,core,{...req,articleId:'b'}),/Materiale/);
assert.throws(()=>api.addUsage(s,core,{...req,jobId:13}),/non assegnato|Cliente|cantiere/i);
const r=api.addUsage(s,core,req);
assert.equal(r.quantity,2.5);assert.equal(r.unitCostCents,250);
assert.equal(api.stock(s,'a'),7.5);
assert.equal(s.movements.length,2);
assert.equal(api.validate(s,core),true);
assert.throws(()=>api.reverseUsage(s,core,{usageId:r.id,actorId:2,reason:'no'}),/Motivazione/);
api.reverseUsage(s,core,{usageId:r.id,actorId:2,reason:'Correzione quantità'});
assert.equal(api.stock(s,'a'),10);
assert.equal(api.summarize(s.settings.jobMaterialUsage).reversed,1);
assert.throws(()=>api.reverseUsage(s,core,{usageId:r.id,actorId:2,reason:'Secondo storno'}),/già stornato/);
assert.equal(api.validate(s,core),true);
const t=api.addUsage(s,core,{...req,quantity:1,note:'=FORMULA'});
assert.match(api.csv(s.settings.jobMaterialUsage,core,s),/"'=CLIENTE DI PROVA"/);
assert.match(api.csv(s.settings.jobMaterialUsage,core,s),/"'=FORMULA"/);
assert.match(api.renderForJob(core.interventi[0],core,s),/Materiali utilizzati nell.intervento/);
assert.match(api.renderForSite(core.cantieri[0],core,s),/Consumi materiali degli interventi/);
assert.doesNotMatch(api.renderForJob(core.interventi[0],core,s),/<script/);
const bad=structuredClone(s);bad.movements.find(x=>x.id===t.movementId).quantity=-2;
assert.throws(()=>api.validate(bad,core),/non corrispondente/);
const foreign=structuredClone(s);foreign.settings.jobMaterialUsage[1].clientId='3';
assert.throws(()=>api.validate(foreign,core),/cliente o cantiere diverso/);
const closed=structuredClone(core);closed.interventi[0].workflow_status='Chiuso';
assert.throws(()=>api.addUsage(s,closed,req),/Revisiona intervento/);
const shortage=state();shortage.movements[0].quantity=-1;
assert.throws(()=>api.addUsage(shortage,core,req),/Giacenza insufficiente/);
console.log('OK: job material stock debit, actor/client/site isolation, shortages, reversal, audit, historical cost, CSV and validation');
