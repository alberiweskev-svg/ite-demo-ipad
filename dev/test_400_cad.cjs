'use strict';
const assert=require('node:assert/strict');
const cad=require('../ite-cad.js');
const db={clienti:[{id:1},{id:2}],immobili:[{id:10,client_id:'1'}],cantieri:[{id:20,client_id:'1',immobile_id:'10'}],impianti:[{id:30,immobile_id:'10'}]};
const a=cad.make('wall',{x:11,y:19},{x:311,y:19});
assert.equal(a.x,10);assert.equal(a.y,20);
assert.equal(a.x2,310);assert.equal(a.kind,'wall');
assert.throws(()=>cad.make('wall',{x:10,y:10},{x:10,y:10}),/Traccia/);
let rows=cad.operate([],'add','',{element:a});
rows=cad.operate(rows,'duplicate',a.id);
assert.equal(rows.length,2);assert.notEqual(rows[0].id,rows[1].id);
rows=cad.operate(rows,'move',a.id,{dx:20,dy:30});
assert.equal(rows[0].x,30);assert.equal(rows[0].y,50);
rows=cad.operate(rows,'rotate',a.id);assert.equal(rows[0].rotation,90);
rows=cad.operate(rows,'color',a.id,{color:'#16805d'});
assert.equal(rows[0].color,'#16805d');
assert.throws(()=>cad.operate(rows,'color',a.id,{color:'url(javascript:alert(1))'}),/Colore/);
rows=cad.operate(rows,'back',rows[1].id);assert.equal(rows[0].id!==a.id,true);
rows=cad.operate(rows,'front',rows[0].id);assert.equal(rows.at(-1).id!==a.id,true);
assert.throws(()=>cad.operate(rows,'delete','unknown'),/Seleziona/);
const drawing={id:'cad_12345678',title:'Disegno TEST',clientId:'1',propertyId:'10',siteId:'20',plantId:'30',revision:2,updated:'2026-10-29T07:00:00.000Z',archived:false,elements:rows,history:[{revision:1,at:'2026-10-29T06:00:00.000Z',elements:[a]}]};
assert.equal(cad.validateCollection([drawing],db),true);
assert(cad.references([drawing],'clienti',1));assert(cad.references([drawing],'immobili',10));
assert(!cad.references([drawing],'clienti',2));
assert.throws(()=>cad.validateCollection([{...drawing,clientId:'2'}],db),/Collegamenti/);
assert.throws(()=>cad.validateCollection([{...drawing,plantId:'999'}],db),/Collegamenti/);
assert.throws(()=>cad.validateCollection([drawing,drawing],db),/Disegno CAD non valido/);
assert.throws(()=>cad.validateCollection([{...drawing,elements:[a,a]}],db),/duplicato/);
assert.throws(()=>cad.validateCollection([{...drawing,history:[{revision:1,at:'invalid',elements:[a]}]}],db),/Revisione/);
assert.throws(()=>cad.validateElement({...a,text:'x'.repeat(121)}),/Elemento/);
assert.equal(cad.validateCollection(undefined,db),true);
console.log('OK: CAD vettoriale, quote, operazioni, revisioni, isolamento clienti, controlli e riferimenti');
