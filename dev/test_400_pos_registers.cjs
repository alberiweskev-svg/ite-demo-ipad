'use strict';
const assert=require('node:assert/strict');
const pos=require('../pos-operativo.js');
assert.equal(pos.CONFIG.length,5);
const legacy='Descrizione manuale già approvata da conservare';
let value=pos.apply(legacy,'add',-1,['Operatore TEST','Installazione idrica','Attestati da verificare']);
assert(value.startsWith(legacy+'\n'),'Il testo manuale non deve essere sovrascritto');
assert.equal(pos.parse(value).rows.length,1);
assert.equal(pos.parse(value).legacy.join('\n'),legacy);
value=pos.apply(value,'add',-1,['Tecnico TEST','Collegamenti elettrici','']);
assert.equal(pos.parse(value).rows.length,2);
assert.throws(()=>pos.apply(value,'add',-1,['Operatore TEST','Installazione idrica','Duplicato']),/duplicata/);
value=pos.apply(value,'update',0,['Operatore TEST','Installazione termica','Abilitazione da verificare']);
assert.match(value,/Installazione termica/);
assert(!value.includes('Installazione idrica'));
value=pos.apply(value,'delete',1);
assert.equal(pos.parse(value).rows.length,1);
assert.equal(pos.parse(value).legacy.join('\n'),legacy);
assert.throws(()=>pos.apply(value,'delete',4),/non trovata/);
assert.throws(()=>pos.apply(value,'add',-1,['Nome|malevolo','Mansione','']),/barre verticali/);
assert.throws(()=>pos.apply(value,'add',-1,['Nome\nmalevolo','Mansione','']),/ritorni a capo/);
assert.throws(()=>pos.apply(value,'add',-1,['X'.repeat(161),'Mansione','']),/160 caratteri/);
assert.throws(()=>pos.apply('A'.repeat(1990),'add',-1,['Operatore','Mansione','']),/2000 caratteri/);
let many='';
for(let i=0;i<15;i++)many=pos.apply(many,'add',-1,['Operatore '+i,'Mansione '+i,'']);
assert.equal(pos.parse(many).rows.length,15);
assert.throws(()=>pos.apply(many,'add',-1,['Sedicesimo','Mansione','']),/15 righe/);
const report=pos.review({personale:value,rischi:'• Scavo | Caduta | Delimitare',dpi:'',emergenze:''});
assert.equal(report.counts.personale,1);
assert(report.warnings.some(x=>x.includes('DPI')));
assert(report.warnings.some(x=>x.includes('emergenza')));
const noWarnings=pos.review({personale:'• Uno | Due | Tre',rischi:'• Uno | Due | Tre',dpi:'• Uno | Due | Tre',emergenze:'• Uno | Due | Tre'});
assert.equal(noWarnings.warnings.length,0);
assert.equal(pos.parse('testo libero\n• A | B | C').legacy.join('\n'),'testo libero');
console.log('OK: 5 registri POS, aggiunta/modifica/rimozione, testo libero conservato, limiti, duplicati e controlli incrociati');
