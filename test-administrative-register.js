'use strict';
const assert=require('node:assert/strict');
const a=require('./ite-administrative-register.js');
const sample=(id,type='VENDITA')=>({id,type,number:'N-'+id,issued:'2026-11-02',party:'CLIENTE DEMO',taxable:100,vat:10,total:110});
let s=a.empty();assert.equal(s.revision,0);
s=a.add(s,0,sample('F1'),'TECNICO DEMO');assert.equal(s.revision,1);
assert.equal(a.summary(s).totals.VENDITA,110);
assert.throws(()=>a.add(s,0,sample('F2'),'DEMO'),/REVISIONE/);
assert.throws(()=>a.add(s,1,sample('F1'),'DEMO'),/DUPLICATO/);
assert.throws(()=>a.add(s,1,{...sample('F2'),total:120},'DEMO'),/TOTALI/);
s=a.add(s,1,sample('P1','PROFORMA'),'DEMO');assert.equal(a.summary(s).counts.PROFORMA,1);
s=a.add(s,2,sample('C1','TD04'),'DEMO');assert.equal(a.creditStatus(s.documents[2]),'DA_RECUPERARE');
s=a.recover(s,3,'C1',40,'DEMO');assert.equal(a.creditStatus(s.documents[2]),'PARZIALMENTE_RECUPERATA');
assert.equal(a.summary(s).creditOutstanding,70);
assert.equal(a.validate(a.importJSON(a.exportJSON(s))),true); // TD04 con originalId nullo
assert.throws(()=>a.normalize({...sample('C2','TD04'),originalId:''}),/FATTURA_ORIGINALE/);
assert.throws(()=>a.recover(s,4,'C1',71,'DEMO'),/ECCESSIVO/);
s=a.recover(s,4,'C1',70,'DEMO');assert.equal(a.creditStatus(s.documents[2]),'RECUPERATA');
s=a.verify(s,5,'F1','DEMO');assert.equal(a.summary(s).unverified,2);
assert.equal(a.importJSON(a.exportJSON(s)).revision,s.revision);
assert.equal(a.classify({filename:'nota_TD04.pdf'}).type,'TD04');
assert.equal(a.classify({text:'Proforma PR 12'}).type,'PROFORMA');
assert.equal(a.classify({filename:'fattura.pdf'}).type,null);
assert.throws(()=>a.normalize({...sample('F3'),issued:'2026-02-30'}),/DATA/);
assert.throws(()=>a.importJSON('{"schema":9}'),/ARCHIVIO/);
console.log('PASS: registro amministrativo, 17 verifiche sintetiche');
