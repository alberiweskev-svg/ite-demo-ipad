'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const H=require('./ite-hierarchy-workspace.js'),I=require('./ite-document-intake.js'),D=require('./ite-technical-dossier.js'),UI=require('./ite-technical-dossier-ui.js');
let master=H.empty();
master=H.add(master,'clients',{id:'c-demo',name:'Cliente fittizio'});
master=H.add(master,'sites',{id:'s-demo',clientId:'c-demo',address:'Via Fittizia 1'});
master=H.add(master,'plants',{id:'p-demo',siteId:'s-demo',name:'Impianto demo'});
master=H.add(master,'devices',{id:'d-demo',plantId:'p-demo',model:'Macchina demo'});
let queue=I.add(I.empty(),{id:'doc-demo',filename:'documento-fittizio.pdf',addedAt:'2026-11-04',type:'DICO_IDRICO',clientId:'c-demo',siteId:'s-demo'});
queue=I.verify(queue,'doc-demo','Operatore demo');
const map=new Map([[H.KEY,JSON.stringify(master)],['ite40_document_intake_v1',JSON.stringify(queue)]]);
const storage={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
let loaded=UI.read(storage);
assert.equal(loaded.state.links.length,0);
assert.equal(UI.choices(loaded.master,loaded.queue,loaded.state,'c-demo','s-demo').documents.length,1);
const next=D.attach(loaded.state,loaded.queue,loaded.master,{documentId:'doc-demo',clientId:'c-demo',siteId:'s-demo',plantId:'p-demo',deviceId:'d-demo',linkedAt:'2026-11-04'});
D.save(storage,next,queue,master);
loaded=UI.read(storage);
assert.equal(loaded.state.links.length,1);
assert.equal(UI.choices(loaded.master,loaded.queue,loaded.state,'c-demo','s-demo').documents.length,0);
assert.equal(D.dossier(loaded.state,queue,master,{clientId:'c-demo'})[0].type,'DICO_IDRICO');
assert.throws(()=>D.attach(next,queue,master,{documentId:'doc-demo',clientId:'c-demo',siteId:'s-demo',linkedAt:'2026-11-04'}),/GIA_COLLEGATO/);
assert.equal(JSON.parse(map.get(D.KEY+'_previous')).links.length,0);
const html=fs.readFileSync('index.html','utf8');
assert.match(html,/<section id="fascicolo-tecnico"/);
assert.match(html,/src="\.\/ite-technical-dossier\.js\?v=4\.0\.13"/);
assert.match(html,/src="\.\/ite-technical-dossier-ui\.js\?v=4\.0\.13"/);
assert.ok(html.indexOf('ite-document-intake.js')<html.indexOf('ite-technical-dossier.js'));
assert.ok(html.indexOf('ite-hierarchy-workspace.js')<html.indexOf('ite-technical-dossier.js'));
console.log('Technical dossier UI and integration: synthetic checks passed');
