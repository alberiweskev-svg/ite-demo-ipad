'use strict';
const assert=require('node:assert/strict');
const ledger=require('./ite-workorder-ledger.js'),coord=require('./ite-workorder-coordination.js');
const data={clients:[{id:'C'}],sites:[{id:'S',clientId:'C'}],systems:[{id:'I',siteId:'S'}],equipment:[{id:'E',systemId:'I'}],operators:[{id:'T',active:true}],appointments:[{id:'A',clientId:'C',siteId:'S',systemId:'I',equipmentId:'E',operatorId:'T',start:'2026-11-03T08:00:00Z',end:'2026-11-03T09:00:00Z'},{id:'B',clientId:'C',siteId:'S',systemId:'I',equipmentId:'E',operatorId:'T',start:'2026-11-03T09:00:00Z',end:'2026-11-03T10:00:00Z'}]};
const order=id=>({id:'O'+id,clientId:'C',siteId:'S',systemId:'I',equipmentId:'E',appointmentId:id,operatorId:'T'});
const at='2026-11-02T05:50:00Z';
assert.equal(coord.schedule(data),true);
const s=coord.createBatch(ledger.initial(),0,[order('A'),order('B')],'DEMO',at,data);
assert.equal(s.orders.length,2);assert.equal(s.revision,2);assert.equal(coord.audit(data,s).ok,true);
assert.equal(ledger.initial().orders.length,0);
assert.throws(()=>coord.createBatch(ledger.initial(),0,[order('A'),order('A')],'DEMO',at,data),/LOTTO_DUPLICATI/);
assert.throws(()=>coord.createBatch(ledger.initial(),1,[order('A')],'DEMO',at,data),/REVISIONE_NON_CORRENTE/);
assert.throws(()=>coord.createBatch(ledger.initial(),0,[{...order('A'),equipmentId:'WRONG'}],'DEMO',at,data),/APPARECCHIO_DIVERSO/);
assert.throws(()=>coord.createBatch(ledger.initial(),0,[order('A'),{...order('B'),clientId:'WRONG'}],'DEMO',at,data),/ORDINE_APPUNTAMENTO_DIVERSO/);
const shifted=coord.reschedule(data,s,'B',{start:'2026-11-03T10:00:00Z',end:'2026-11-03T11:00:00Z'});
assert.equal(shifted.appointments[1].start,'2026-11-03T10:00:00Z');
assert.equal(data.appointments[1].start,'2026-11-03T09:00:00Z');
assert.throws(()=>coord.reschedule(data,s,'B',{start:'2026-11-03T08:30:00Z'}),/OPERATORE_SOVRAPPOSTO/);
assert.throws(()=>coord.reschedule(data,s,'B',{clientId:'C'}),/MODIFICA_NON_VALIDA/);
assert.throws(()=>coord.reschedule(data,s,'B',{operatorId:'X'}),/OPERATORE_ORDINE_DIVERSO/);
const started=ledger.orderStatus(s,s.revision,'OB','IN_CORSO','DEMO',at);
assert.throws(()=>coord.reschedule(data,started,'B',{start:'2026-11-03T11:00:00Z'}),/INTERVENTO_AVVIATO/);
assert.equal(coord.audit({...data,operators:[{id:'T',active:false}]},s).ok,false);
assert.equal(coord.audit({...data,appointments:[...data.appointments,{...data.appointments[0],id:'X'}]},s).ok,false);
console.log('OK: operational coordination batch, audit, rescheduling (16 assertions)');
