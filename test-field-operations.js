'use strict';
const assert=require('node:assert/strict');
const H=require('./ite-hierarchy-workspace.js'),F=require('./ite-field-operations.js');
let s=H.empty();
s=H.add(s,'clients',{id:'C1',name:'Cliente dimostrativo'});
s=H.add(s,'sites',{id:'S1',clientId:'C1',address:'Via Esempio 1'});
s=H.add(s,'plants',{id:'P1',siteId:'S1'});
s=H.add(s,'devices',{id:'D1',plantId:'P1'});
s=F.schedule(s,{id:'A1',clientId:'C1',siteId:'S1',deviceId:'D1',operator:'Tecnico demo',start:'2026-11-04T09:00',end:'2026-11-04T10:00'});
assert.throws(()=>F.schedule(s,{id:'A2',clientId:'C1',siteId:'S1',operator:'Tecnico demo',start:'2026-11-04T09:30',end:'2026-11-04T10:30'}),/OPERATORE_GIA_OCCUPATO/);
s=F.schedule(s,{id:'A3',clientId:'C1',siteId:'S1',operator:'Altro tecnico',start:'2026-11-04T09:30',end:'2026-11-04T10:30'});
assert.equal(F.operatorLoad(s,'2026-11-04T09:00','2026-11-04T10:00').reduce((n,x)=>n+x.minutes,0),90);
assert.throws(()=>F.reschedule(s,'A3',{operator:'Tecnico demo'},'Coordinatore','2026-11-03T12:00'),/OPERATORE_GIA_OCCUPATO/);
s=F.reschedule(s,'A3',{start:'2026-11-04T10:00',end:'2026-11-04T11:00',operator:'Tecnico demo'},'Coordinatore','2026-11-03T12:00');
assert.equal(s.appointments.find(x=>x.id==='A3').history[0].previous.operator,'Altro tecnico');
assert.equal(F.agenda(s,'Tecnico demo','2026-11-04T08:00','2026-11-04T12:00').length,2);
s=F.start(s,'A1','Tecnico demo','I1','2026-11-04T09:03');
assert.equal(s.interventions[0].status,'IN_CORSO');
assert.throws(()=>F.reschedule(s,'A1',{start:'2026-11-04T11:00'},'Coordinatore','2026-11-04T09:04'),/APPUNTAMENTO_GIA_AVVIATO/);
assert.throws(()=>F.start(s,'A1','Tecnico demo','I2','2026-11-04T09:04'),/INTERVENTO_GIA_APERTO/);
s=F.close(s,'I1','2026-11-04T09:45',[{description:'Sostituito componente aggiuntivo',attachments:['foto-demo']}]);
assert.equal(s.interventions[0].status,'CONCLUSO');
assert.equal(s.interventions[0].otherWork.length,1);
assert.throws(()=>F.reopen(s,'I1','Tecnico demo','2026-11-04T11:00',''),/RIAPERTURA_NON_VALIDA/);
s=F.reopen(s,'I1','Tecnico demo','2026-11-04T11:00','Correzione orario');
assert.equal(s.interventions[0].status,'REVISIONATO');
s=F.revise(s,'I1','Tecnico demo',{leftAt:'2026-11-04T09:50'},'2026-11-04T11:05');
assert.equal(s.interventions[0].leftAt,'2026-11-04T09:50');
assert.deepEqual(s.interventions[0].history.map(x=>x.action),['CHIUSURA','RIAPERTURA','REVISIONE_CHIUSA']);
assert.equal(s.interventions[0].status,'CONCLUSO');
console.log('PASS: field operations scheduling, operator conflicts, arrival, closure, extra work, revision audit');
