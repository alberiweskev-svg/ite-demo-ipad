'use strict';
const assert=require('node:assert/strict');
const H=require('./ite-hierarchy-workspace.js'),A=require('./ite-atomic-workspace.js');
const D=require('./ite-document-intake.js'),P=require('./ite-reconciliation-planner.js');
let h=H.empty();
h=H.add(h,'clients',{id:'C1',name:'Cliente fittizio'});
h=H.add(h,'sites',{id:'S1',clientId:'C1',address:'Via Esempio 1'});
h=H.add(h,'plants',{id:'P1',siteId:'S1'});
const snapshot={format:'ITE40_ATOMIC',version:1,revision:3,data:{...A.empty(),hierarchy:h}};
let docs=D.add(D.empty(),{id:'D1',filename:'dico_test.pdf',type:'DICO_IDRICO',status:'DA_VERIFICARE',addedAt:'2026-11-03',clientId:'C1',siteId:'S1',notes:''});
docs=D.add(docs,{id:'D2',filename:'allegato_test.pdf',type:'ALLEGATI_GAS',status:'DA_VERIFICARE',addedAt:'2026-11-03',clientId:'C1',siteId:'S1',notes:''});
const valid=P.plan(snapshot,docs,[{documentId:'D1',plantId:'P1'}]);
assert.equal(valid.automaticChanges,0);
assert.equal(valid.report.ok,true);
assert(valid.suggestions.some(x=>x.documentId==='D2'&&x.action==='VERIFICARE_COLLEGAMENTO'));
assert.deepEqual(P.review(valid,3),{ready:true,blocked:0,actions:2});
assert.throws(()=>P.review(valid,4),/ARCHIVIO_MODIFICATO/);
const bad=P.plan(snapshot,docs,[{documentId:'D1',plantId:'INESISTENTE'},{documentId:'D1',plantId:'P1'}]);
assert.equal(bad.blocked.length,2);
assert.equal(P.review(bad,3).ready,false);
assert.equal(snapshot.revision,3);
console.log('PASS: reconciliation planner, duplicate detection, non-destructive review and revision guard');
