'use strict';
const assert=require('node:assert/strict'),w=require('./ite-field-workflow.js');
const t='2026-11-01T09:00:00+01:00',end='2026-11-01T10:00:00+01:00';
const fixture={id:'APP-TEST',clientId:'CLIENTE-FITTIZIO',siteId:'SEDE-FITTIZIA',systemId:'IMPIANTO-FITTIZIO',equipmentId:'CALDAIA-FITTIZIA',operatorId:'OPERATORE-TEST',kind:'manutenzione',startsAt:t,endsAt:end};
let a=w.appointment(fixture);assert.equal(a.status,'scheduled');
assert.throws(()=>w.appointment({...fixture,endsAt:t}),/FASCIA/);
assert.throws(()=>w.arrive(a,'OPERATORE-ERRATO',t),/ASSEG NATO|ASSEGNATO/);
a=w.arrive(a,'OPERATORE-TEST',t);assert.equal(a.status,'in_progress');
assert.throws(()=>w.close(a,'OPERATORE-TEST','2026-11-01T08:00:00+01:00'),/USCITA_PRIMA/);
a=w.addExtra(a,{id:'E1',description:'Rubinetto',category:'idrico',lines:[{type:'FORNITURA',description:'Rubinetto',quantity:1,unitCents:5000},{type:'POSA',description:'Montaggio',quantity:1,unitCents:3500}]},'OPERATORE-TEST',t);
assert.equal(a.extraWorks[0].lines.length,2);
a=w.decideExtra(a,'E1','accettato','OPERATORE-TEST',t);
a=w.close(a,'OPERATORE-TEST',end,'Collaudo');assert.equal(w.summary(a).minutes,60);
a=w.reopen(a,'OPERATORE-TEST',end,'Orario da rettificare');
a=w.reviseTimes(a,'OPERATORE-TEST',end,[{visitIndex:0,arrivedAt:'2026-11-01T09:15:00+01:00'}]);
a=w.finishRevision(a,'OPERATORE-TEST',end);
assert.equal(w.summary(a).minutes,45);assert.equal(a.extraWorks[0].status,'accettato');
assert.deepEqual(a.audit.map(x=>x.event),['CREATED','ARRIVED','EXTRA_ADDED','EXTRA_DECIDED','CLOSED','REOPENED','TIMES_REVISED','REVISION_CLOSED']);
console.log('PASS: workflow field appointment/visit/extra/revision');
