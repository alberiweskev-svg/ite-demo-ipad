'use strict';
const assert=require('node:assert/strict');
const A=require('./ite-accounting-workspace.js');
let s=A.empty();
const base={id:'F1',number:'12/2026',date:'2026-11-02',kind:'VENDITA',counterparty:'Cliente fittizio',taxable:100,vat:10,total:110,vatCategory:'10'};
s=A.add(s,base);assert.equal(A.totals(s).pending,1);
assert.throws(()=>A.review(s,'F1','',true),/REVISIONE/);
s=A.review(s,'F1','Operatore demo',true);assert.equal(s.documents[0].status,'CONFERMATO');
assert.throws(()=>A.add(s,{...base,id:'F2'}),/DUPLICATO/);
assert.throws(()=>A.add(s,{...base,id:'F2',number:'13',total:111}),/COHERENTE/);
s=A.add(s,{...base,id:'N1',number:'NC-1',kind:'TD04',total:55,taxable:50,vat:5});
assert.equal(A.totals(s).creditToRecover,55);
s=A.recover(s,'N1',20);assert.equal(s.documents[1].creditStatus,'PARZIALMENTE');
assert.throws(()=>A.recover(s,'N1',36),/ECCESSIVO/);
s=A.recover(s,'N1',35);assert.equal(s.documents[1].creditStatus,'RECUPERATA');
assert.equal(A.totals(s).creditToRecover,0);
assert.equal(A.classify('Documento TD04 nota di credito'),'TD04');
assert.equal(A.classify('Copia di cortesia'),'PROFORMA');
assert.equal(A.classify('Fattura 123'),'DA_VERIFICARE');
const store=new Map(),storage={getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,v)};
A.save(storage,s);assert.deepEqual(A.load(storage),s);
assert.equal(A.parse(JSON.stringify(s)).documents.length,2);
assert.throws(()=>A.parse('not json'),/JSON/);
console.log('Accounting workspace: 16 verifiche completate');
