const assert=require("node:assert/strict"),I=require("./ite-inventory-154.js"),P=require("./ite-material-planning-156.js");
let s={schema:"ITE_OPERATIONS_123",revision:0,events:[],commercial:{estimates:[{id:"Q1",status:"ACCETTATO",lines:[{id:"L1",kind:"FORNITURA",description:"Tubo TEST",quantity:4},{id:"L2",kind:"POSA",description:"Posa TEST",quantity:4},{id:"L3",kind:"FORNITURA",description:"Raccordo TEST",quantity:3}]}]}};
const run=(fn,...a)=>{s=fn(s,...a,"Operatore TEST",s.revision)};
run(I.item,{id:"A",code:"TEST-A",description:"Tubo TEST",unitPrice:10,vatRate:22});
run(I.item,{id:"B",code:"TEST-B",description:"Raccordo TEST",unitPrice:5,vatRate:22});
run(I.movement,{id:"IN-A",itemId:"A",direction:"IN",quantity:5});
run(I.movement,{id:"IN-B",itemId:"B",direction:"IN",quantity:2});
const maps=[{lineId:"L1",itemId:"A",quantity:4},{lineId:"L3",itemId:"B",quantity:3}];
assert.equal(P.plan(s,"Q1",maps).canReserve,false);
assert.equal(P.plan(s,"Q1",maps).shortages[0].missing,1);
assert.throws(()=>P.reserveAll(s,"Q1",maps,"Operatore TEST",s.revision,"BATCH"),/GIACENZA/);
assert.equal(s.inventory.reservations.length,0);
run(I.movement,{id:"IN-B2",itemId:"B",direction:"IN",quantity:2});
assert.equal(P.plan(s,"Q1",maps).canReserve,true);
assert.throws(()=>P.plan(s,"Q1",[{lineId:"L2",itemId:"A"}]),/FORNITURA/);
assert.throws(()=>P.plan(s,"Q1",[{lineId:"L1",itemId:"A",quantity:5}]),/SUPERA/);
assert.throws(()=>P.reserveAll(s,"Q1",maps,"Operatore TEST",s.revision-1,"BATCH"),/REVISIONE/);
s=P.reserveAll(s,"Q1",maps,"Operatore TEST",s.revision,"BATCH");
assert.equal(s.inventory.reservations.length,2);
assert.equal(s.inventory.reservations[0].lineId,"L1");
assert.equal(I.overview(s).items.find(x=>x.id==="A").available,1);
assert.throws(()=>P.plan(s,"Q1",[{lineId:"L1",itemId:"A",quantity:1}]),/GIA_PRENOTATA/);
assert.equal(P.audit(s).problems.length,0);
console.log("Material planning 156 TEST: OK");