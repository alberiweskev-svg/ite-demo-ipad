const assert=require("node:assert/strict");
const q=require("./ite-quotes-40.js"),i=require("./ite-invoice-ledger-40.js"),b=require("./ite-quote-invoice-bridge-40.js");
let quotes=q.create(q.empty(),{id:"TEST-Q-01",customer:"Cliente fittizio",date:"2026-11-07"});
const row=(id,kind,description,unitPrice,vat=10)=>({id,kind,description,quantity:1,unitPrice,vat});
quotes=q.addLine(quotes,"TEST-Q-01",row("TEST-F-01","SUPPLY","Fornitura rubinetto",100));
quotes=q.addLine(quotes,"TEST-Q-01",row("TEST-P-01","INSTALLATION","Posa rubinetto",80));
let ledger=i.empty();
assert.throws(()=>b.prepare(quotes,ledger,"TEST-Q-01","TEST-I-01","1","2026-11-07"),/accettati/);
quotes=q.setStatus(quotes,"TEST-Q-01","SENT");quotes=q.setStatus(quotes,"TEST-Q-01","ACCEPTED");
quotes=q.addLine(quotes,"TEST-Q-01",row("TEST-E-01","INSTALLATION","Extra presa",50,22),true);
quotes=q.addLine(quotes,"TEST-Q-01",row("TEST-E-02","OTHER","Extra da rifiutare",10),true);
quotes=q.approveExtra(quotes,"TEST-Q-01","TEST-E-01","APPROVED");
quotes=q.approveExtra(quotes,"TEST-Q-01","TEST-E-02","REJECTED");
const result=b.prepare(quotes,ledger,"TEST-Q-01","TEST-I-01","FT-TEST-01","2026-11-07");
assert.equal(result.preview.rows.length,3);assert.equal(result.preview.excludedExtras,1);
assert.equal(result.preview.totals.total,259);assert.equal(result.ledger.documents[0].type,"SALE");
assert.equal(b.reconcile(quotes,result.ledger,"TEST-Q-01","TEST-I-01").matches,true);
assert.equal(ledger.documents.length,0);
assert.throws(()=>b.prepare(quotes,result.ledger,"TEST-Q-01","TEST-I-01","2","2026-11-07"),/già presente/);
assert.throws(()=>b.prepare(quotes,ledger,"TEST-Q-01","CLIENT-REAL","2","2026-11-07"),/TEST/);
const without=b.prepare(quotes,ledger,"TEST-Q-01","TEST-I-02","2","2026-11-07",{includeExtras:false});
assert.equal(without.preview.totals.total,198);
assert.equal(b.reconcile(quotes,without.ledger,"TEST-Q-01","TEST-I-02").difference,61);
const changed=JSON.parse(q.exportJson(quotes));changed.quotes[0].lines[0].total=0;
assert.throws(()=>b.prepare(changed,ledger,"TEST-Q-01","TEST-I-03","3","2026-11-07"),/alterati/);
