'use strict';
const assert=require('node:assert/strict');
const {audit}=require('./ite-procurement-quantity-audit.js');
const {inspect}=require('./ite-core-reconciliation.js');
const quote={id:'Q',supplierId:'S',lines:[{code:'A',qty:2,unitPrice:10},{code:'B',qty:1,unitPrice:5}]};
const invoice={id:'I',supplierQuoteId:'Q',supplierId:'S',lines:[{code:'A',qty:3,unitPrice:12},{code:'B',qty:1,unitPrice:5}]};
const a=audit([quote],[invoice]);
assert.equal(a.records[0].status,'DIFFERENZE');
assert.deepEqual(a.records[0].differences.map(d=>d.kind),['QUANTITA_AUMENTATA','PREZZO_AUMENTATO']);
assert.equal(a.records[0].differences[0].deltaQuantity,1);
assert.equal(a.records[0].differences[1].deltaPrice,2);
assert.equal(invoice.lines[0].qty,3);
assert.equal(audit([quote],[{...invoice,lines:quote.lines}]).records[0].status,'CONFORME');
assert.equal(audit([quote],[{...invoice,supplierId:'OTHER'}]).records[0].status,'FORNITORE_DIVERSO');
assert.equal(audit([quote],[{...invoice,lines:[{code:'A',qty:-1,unitPrice:10}]}]).records[0].status,'DATI_DA_VERIFICARE');
assert.equal(audit([quote],[{...invoice,supplierQuoteId:''}]).records[0].status,'NON_ASSOCIATA');
const core={clienti:[],immobili:[],impianti:[],apparecchiature:[],appuntamenti:[],interventi:[]};
const integrated=inspect(core,{supplierQuotes:[quote],purchaseInvoices:[invoice]});
assert.equal(integrated.supplierQuantityAudit[0].status,'DIFFERENZE');
assert.equal(integrated.readOnly,true);
console.log('Procurement quantity audit synthetic integration passed');
