'use strict';
const assert=require('node:assert/strict'),F=require('./ite-finance-workflow.js');
const mk=(id,type,issuerVat,number,totalCents=11000)=>({id,type,issuerVat,companyVat:'03857941201',number,date:'2026-11-04',netCents:10000,vatCents:1000,totalCents});
let s={documents:[]};
s=F.add(s,mk('v','TD01','03857941201','2026/101'));
s=F.add(s,mk('a','TD01','01234567890','2026/55'));
s=F.add(s,mk('p','PR','03857941201','PR-17'));
s=F.add(s,mk('c','TD04','01234567890','NC-2'));
assert.equal(s.documents[0].direction,'VENDITA');
assert.equal(s.documents[1].direction,'ACQUISTO');
assert.equal(s.documents[2].kind,'PROFORMA');
assert.equal(s.documents[3].paymentState,'DA_RECUPERARE');
assert.throws(()=>F.add(s,mk('v','TD01','03857941201','2026/101')),/DUPLICATO/);
assert.throws(()=>F.add(s,{...mk('bad','TD01','03857941201','bad'),totalCents:999}),/TOTALI/);
const before=JSON.stringify(s);
s=F.recover(s,'c',4000,'Tecnico demo','2026-11-04T16:00:00Z');
assert.equal(s.documents[3].paymentState,'PARZIALMENTE_RECUPERATA');
assert.throws(()=>F.recover(s,'c',8000,'Tecnico demo','2026-11-04T16:01:00Z'),/ECCESSIVO/);
s=F.recover(s,'c',7000,'Tecnico demo','2026-11-04T16:02:00Z');
assert.equal(s.documents[3].paymentState,'RECUPERATA');
assert.equal(F.totals(s).creditRemainingCents,0);
assert.equal(JSON.parse(before).documents[3].recoveredCents,0);
assert.equal(F.classify({type:'TD01',number:'9'}).direction,'DA_VERIFICARE');
console.log('Finance workflow: test completati');
