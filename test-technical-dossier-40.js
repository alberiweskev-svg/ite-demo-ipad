const assert=require("node:assert/strict");
const d=require("./ite-technical-dossier-40.js");
const h={clients:[{id:"TEST-CLIENT"}],sites:[{id:"TEST-SITE",clientId:"TEST-CLIENT"}],plants:[{id:"TEST-PLANT",siteId:"TEST-SITE"}],equipment:[{id:"TEST-EQUIP",plantId:"TEST-PLANT"}],appointments:[{id:"TEST-APPT",clientId:"TEST-CLIENT",siteId:"TEST-SITE",equipmentId:"TEST-EQUIP"}]};
const link={clientId:"TEST-CLIENT",siteId:"TEST-SITE",plantId:"TEST-PLANT",equipmentId:"TEST-EQUIP",appointmentId:"TEST-APPT"};
const input={id:"TEST-DOC",type:"DICO_IDRICO",title:"Dichiarazione di conformità TEST",date:"2026-11-06",link};
const pdf={id:"TEST-PDF",name:"facsimile.pdf",mime:"application/pdf",bytes:1234,sha256:"a".repeat(64)};
let db=d.empty();
db=d.create(db,h,input,"TEST-OPERATOR");
assert.equal(db.documents[0].state,"DRAFT");
assert.equal(db.audit.length,1);
assert.throws(()=>d.transition(db,h,"TEST-DOC","REVIEW","TEST-OPERATOR","2026-11-06"),/PDF/);
db=d.attach(db,h,"TEST-DOC",pdf,"TEST-OPERATOR","2026-11-06");
assert.throws(()=>d.attach(db,h,"TEST-DOC",pdf,"TEST-OPERATOR","2026-11-06"),/duplicato/);
assert.throws(()=>d.attach(db,h,"TEST-DOC",{...pdf,id:"TEST-PDF2",content:"sensitive"},"TEST-OPERATOR","2026-11-06"),/contenuti/);
db=d.transition(db,h,"TEST-DOC","REVIEW","TEST-OPERATOR","2026-11-06");
db=d.transition(db,h,"TEST-DOC","APPROVED","TEST-OPERATOR","2026-11-06");
db=d.transition(db,h,"TEST-DOC","ARCHIVED","TEST-OPERATOR","2026-11-06");
assert.throws(()=>d.attach(db,h,"TEST-DOC",{...pdf,id:"TEST-PDF2"},"TEST-OPERATOR","2026-11-06"),/bozza/);
assert.equal(db.audit.length,5);
assert.equal(d.list(db,h,{clientId:"TEST-CLIENT",state:"ARCHIVED"}).length,1);
assert.equal(d.list(db,h,{clientId:"TEST-OTHER"}).length,0);
assert.deepEqual(d.importJson(d.exportJson(db,h),h),db);
assert.throws(()=>d.create(db,h,{...input,id:"TEST-OTHER",link:{...link,siteId:"TEST-OTHER"}},"TEST-OPERATOR"),/Sede/);
assert.throws(()=>d.importJson(JSON.stringify({...db,schema:"UNKNOWN"}),h),/Schema/);
assert.throws(()=>d.create(db,h,{...input,id:"TEST-OTHER",date:"2026-02-30"},"TEST-OPERATOR"),/Data/);
assert.equal(db.documents[0].attachments[0].sha256,"a".repeat(64));
const r=d.report(db,h,{clientId:"TEST-CLIENT"});
assert.equal(r.total,1);
assert.equal(r.byState.ARCHIVED,1);
assert.equal(r.byType.DICO_IDRICO,1);
assert.equal(r.rows[0].attachmentCount,1);
assert.equal(r.rows[0].auditCount,5);
assert.equal(d.report(db,h,{state:"DRAFT"}).total,0);
assert.throws(()=>d.importJson(JSON.stringify({...db,audit:[{documentId:"TEST-GHOST",operatorId:"TEST-OPERATOR",date:"2026-11-06",action:"CREATE"}]}),h),/Storico/);
assert.throws(()=>d.importJson(JSON.stringify({...db,audit:[]}),h),/Storico creazione/);
console.log("ITE 4.0.47 technical dossier audit, filters and report tests passed");
