const assert=require("node:assert/strict");
const Q=require("./ite-quotes-40.js"),I=require("./ite-invoice-ledger-40.js"),B=require("./ite-quote-invoice-bridge-40.js");
const row=(id,kind,description,price,vat=10)=>({id,kind,description,quantity:1,unitPrice:price,vat});
let q=Q.create(Q.empty(),{id:"TEST-Q-INTEGRATED",customer:"Cliente fittizio",date:"2026-11-07"});
q=Q.addLine(q,"TEST-Q-INTEGRATED",row("TEST-F-01","SUPPLY","Fornitura lavabo",150));
q=Q.addLine(q,"TEST-Q-INTEGRATED",row("TEST-P-01","INSTALLATION","Posa lavabo",90));
q=Q.setStatus(q,"TEST-Q-INTEGRATED","SENT");q=Q.setStatus(q,"TEST-Q-INTEGRATED","ACCEPTED");
q=Q.addLine(q,"TEST-Q-INTEGRATED",row("TEST-E-01","INSTALLATION","Extra presa",50,22),true);
q=Q.addLine(q,"TEST-Q-INTEGRATED",row("TEST-E-02","REMOVAL","Extra escluso",20),true);
q=Q.approveExtra(q,"TEST-Q-INTEGRATED","TEST-E-01","APPROVED");
let i=I.empty();const before=JSON.stringify(i);
const p=B.prepare(q,i,"TEST-Q-INTEGRATED","TEST-I-INTEGRATED","BOZZA-001","2026-11-07");
assert.equal(JSON.stringify(i),before,"La preparazione non deve mutare l'archivio");
assert.equal(p.preview.rows.length,3);assert.equal(p.preview.excludedExtras,1);
assert.equal(p.preview.totals.total,325);assert.equal(p.ledger.documents.length,1);
assert.equal(B.reconcile(q,p.ledger,"TEST-Q-INTEGRATED","TEST-I-INTEGRATED").matches,true);
assert.throws(()=>B.prepare(q,p.ledger,"TEST-Q-INTEGRATED","TEST-I-INTEGRATED","BOZZA-002","2026-11-07"),/già presente/);
assert.throws(()=>B.prepare(q,i,"TEST-Q-INTEGRATED","REAL-01","BOZZA-002","2026-11-07"),/TEST/);
const base=B.prepare(q,i,"TEST-Q-INTEGRATED","TEST-I-BASE","BOZZA-BASE","2026-11-07",{includeExtras:false});
assert.equal(base.preview.rows.length,2);assert.equal(base.preview.totals.total,264);
assert.equal(B.reconcile(q,base.ledger,"TEST-Q-INTEGRATED","TEST-I-BASE").difference,61);
assert.equal(I.importJson(I.exportJson(p.ledger)).documents.length,1);
console.log("ITE 4.0.57 integrated quote/invoice TEST PASS");
