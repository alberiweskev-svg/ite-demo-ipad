const assert=require("node:assert/strict");
const a=require("./ite-invoice-ledger-40.js");
assert.deepEqual(a.classify({documentCode:"TD04",number:"X"}),{type:"CREDIT_NOTE",reason:"TD04"});
assert.equal(a.classify({number:"PR-72",issuer:"Altro"}).type,"PROFORMA");
assert.equal(a.classify({number:"1",issuer:"I.T.E. DI MERKAJ ALBAN"}).type,"SALE");
assert.equal(a.classify({number:"2",issuer:"Fornitore"}).type,"PURCHASE");
assert.equal(a.classify({number:"2"}).type,"UNRESOLVED");
const lines=[{quantity:2,unitPrice:100,vat:10},{quantity:1,unitPrice:50,vat:22}];
assert.deepEqual(a.totals(lines),{taxable:250,vat:31,total:281});
let db=a.empty();
for(const [i,type] of ["SALE","PURCHASE","PROFORMA","CREDIT_NOTE"].entries())db=a.add(db,{id:"TEST-I-"+i,type,number:"TEST-"+i,party:"Soggetto fittizio",date:"2026-11-06",lines});
assert.equal(a.summary(db).openSales,281);
assert.equal(a.summary(db).openPurchases,281);
assert.equal(a.summary(db).proformas,281);
assert.equal(a.summary(db).creditsToRecover,281);
db=a.payment(db,"TEST-I-3",100,"2026-11-06");
assert.equal(a.summary(db).rows[3].status,"PARTIALLY_RECOVERED");
db=a.payment(db,"TEST-I-3",181,"2026-11-06");
assert.equal(a.summary(db).rows[3].status,"RECOVERED");
assert.throws(()=>a.payment(db,"TEST-I-3",1,"2026-11-06"),/superiori/);
assert.deepEqual(a.importJson(a.exportJson(db)),db);
assert.throws(()=>a.add(db,{id:"CLIENT-REAL",type:"SALE",number:"1",party:"Test",date:"2026-11-06",lines}),/TEST/);
const tampered=JSON.parse(a.exportJson(db));tampered.documents[0].total=1;
assert.throws(()=>a.validate(tampered),/alterati/);
assert.throws(()=>a.totals([{quantity:1,unitPrice:1,vat:21}]),/IVA/);
assert.throws(()=>a.totals([{quantity:-1,unitPrice:1,vat:10}]),/Quantità/);
console.log("ITE 4.0.51: classification, VAT, TD04, balances, TEST-only archive and tamper tests passed");