"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const root={console,Date,crypto:require("node:crypto").webcrypto};
root.globalThis=root;vm.createContext(root);
vm.runInContext(fs.readFileSync("ite-document-intake-90.js","utf8"),root);
vm.runInContext(fs.readFileSync("ite-document-workspace-91.js","utf8"),root);
const api=root.ITEDocumentWorkspace91;
const memory=new Map(),store={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
assert.equal(api.load(store).records.length,0);
const pdf={name:"dico_elettrico_TEST.pdf",size:500,type:"application/pdf"};
let out=api.ingest(store,[pdf,{name:"script.exe",size:10,type:"application/octet-stream"}],{});
assert.equal(out.accepted.length,1);assert.equal(out.rejected.length,1);
assert.equal(api.load(store).records[0].type,"DICO_ELETTRICO");
assert.equal(api.load(store).records[0].reviewRequired,false);
assert.equal(api.load(store).records.length,1);
assert.throws(()=>api.save(store,{schema:"BAD",records:[]}));
assert.equal(api.load(store).records.length,1);
assert.equal(root.ITEDocumentIntake90.classify({name:"fattura_TEST.pdf",issuerIsITE:true}),"FATTURA_VENDITA");
assert.equal(root.ITEDocumentIntake90.classify({name:"fattura_TEST.pdf"}),"DA_VERIFICARE");
const html=fs.readFileSync("index.html","utf8");
assert(html.includes('ite-document-intake-90.js?v=4.0.91'));
assert(html.includes('ite-document-workspace-91.js?v=4.0.91'));
assert(html.indexOf('ite-document-intake-90.js?v=4.0.91')<html.indexOf('ite-document-workspace-91.js?v=4.0.91'));
console.log("OK: document workspace 4.0.91");
