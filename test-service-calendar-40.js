"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const R=require("./ite-service-registry-40.js"),W=require("./ite-service-workflow-40.js");
let db=R.blank();
for(const [kind,row] of [["clients",{id:"TEST-C1",name:"Cliente TEST"}],["sites",{id:"TEST-S1",clientId:"TEST-C1",address:"Via Fittizia"}],["plants",{id:"TEST-P1",siteId:"TEST-S1",name:"Impianto TEST"}],["equipment",{id:"TEST-E1",plantId:"TEST-P1",name:"Caldaia TEST"}],["operators",{id:"TEST-O1",name:"Operatore TEST"}],["operators",{id:"TEST-O2",name:"Altro TEST"}]])db=R.add(db,kind,row);
